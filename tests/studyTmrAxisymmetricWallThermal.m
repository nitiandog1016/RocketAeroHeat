function report=studyTmrAxisymmetricWallThermal(folder,maxSteps)
%STUDYTMRAXISYMMETRICWALLTHERMAL 实际SA热梯度边界消融：从冻结v65Q重新求解。
% 模块一：原网格、气体、储库、SA和给定Tw保持，只显式改墙Fourier梯度策略。
% 模块二：旧解仅为新方程初场；保存新旧同Q差异并实际解完整五量BE到原稳态门槛。
% 模块三：signed q与未知场身份保留；未稳态/实验未验收均不能晋升生产面积。
root=fileparts(fileparts(mfilename('fullpath')));
addpath(root,fullfile(root,'regionalFlow','axisymmetric'),fullfile(root,'internalFlow'));
if nargin<1,folder=fullfile(root,'outputs','v66_validation','tmr_wall_thermal');end
if nargin<2,maxSteps=65;end
validateattributes(maxSteps,{'numeric'},{'real','finite','scalar','integer','positive'});
source=fullfile(root,'outputs','v65_validation','tmr_sa_continue1','tmr_sa_evidence.mat');
if ~exist(source,'file'),source=fullfile(root,'validation','v65','tmr_sa_continue1','tmr_sa_evidence.mat');end
sourceSHA=fileSHA(source);saved=load(source,'mesh','gas','boundary','implicit','report');
mesh=saved.mesh;gas=saved.gas;boundary=saved.boundary;Q=saved.implicit.Q;scale=saved.implicit.residualScale;
[legacyRate,legacyInfo]=axisymmetricRANSResidual(Q,mesh,gas,boundary);
assert(isequaln(legacyInfo,saved.implicit.finalInfo)&&max(abs(legacyRate)./scale,[],'all')==saved.implicit.residualNorm, ...
    'AxisFV:WallThermalParent','冻结v65原方程不能完整重放，禁止沿用陈旧父结果。');
boundary.jMin.thermalGradient='dirichlet-tangent';
[initialRate,initialInfo]=axisymmetricRANSResidual(Q,mesh,gas,boundary);
assert(isequal(initialRate(:,[1 2 3 5]),legacyRate(:,[1 2 3 5]))&& ...
    isequaln(initialInfo.sa,legacyInfo.sa)&&isequaln(initialInfo.transport,legacyInfo.transport), ...
    'AxisFV:WallThermalIsolation','同Q对照只允许墙Fourier热通量改能量方程，SA/输运/其它分量不应偷改。');
assert(all(initialInfo.wallThermalGradient.tangentialGradientInputKm==0)&& ...
    ~initialInfo.wallThermalGradient.cellStateClipped);
opts=saved.implicit.options;opts.maxSteps=maxSteps;opts.initialPseudoCFL=1;opts.maximumPseudoCFL=1e6;
opts.maxNewtonIterations=24;opts.jacobianRefreshEvery=1;
assert(opts.steadyResidualTolerance==2e-6&&opts.steadyRequiredSteps==3&&opts.conservationTolerance==5e-10);
assert(~exist(fullfile(folder,'tmr_wall_thermal_evidence.mat'),'file'),'AxisFV:WallThermalOverwrite','不覆盖父证据或已有新结果。');
if ~exist(folder,'dir'),mkdir(folder);end
clock=tic;implicit=advanceAxisymmetricSteady(Q,mesh,gas,boundary,opts);elapsed=toc(clock);
[rate,info]=axisymmetricRANSResidual(implicit.Q,mesh,gas,boundary);
assert(isequaln(info,implicit.finalInfo)&&max(abs(rate)./scale,[],'all')==implicit.residualNorm&&strcmp(sourceSHA,fileSHA(source)));
report=struct('status','actual-explicit-wall-thermal-policy-SA-restart-not-experimental-validation', ...
    'parentCheckpoint',source,'parentCheckpointSHA256',sourceSHA, ...
    'singleChange','jMin Fourier wall gradient: explicit Dirichlet-tangent, constant Tw derivative 0; full SA scalar gradient unchanged', ...
    'initialOriginalResidual',max(abs(initialRate)./scale,[],'all'),'finalOriginalResidual',implicit.residualNorm, ...
    'steadyConverged',implicit.steadyConverged,'stopReason',implicit.stopReason,'acceptedSteps',implicit.acceptedSteps, ...
    'rejectedAttempts',implicit.rejectedAttempts,'solverResidualEvaluations',implicit.residualEvaluations, ...
    'diagnosticResidualEvaluations',3,'elapsedSeconds',elapsed,'fiveQuantityBalanceRelative',implicit.globalBalanceRelative, ...
    'initialSameQWallSignedHeatRangeWm2',[min(initialInfo.wall.heatFluxIntoWall),max(initialInfo.wall.heatFluxIntoWall)], ...
    'finalWallSignedHeatRangeWm2',[min(info.wall.heatFluxIntoWall),max(info.wall.heatFluxIntoWall)], ...
    'finalCoolingFaceIDs',info.wall.faceID(info.wall.heatFluxIntoWall<0), ...
    'wallThermalGradientPolicy','dirichlet-tangent','heatFluxWasClippedOrMultiplied',false, ...
    'pseudoTimeIsPhysical',false,'physicalTimeAdvanced',0,'physicalSolution',false,'eligibleForSurfaceCoverage',false, ...
    'experimentalValidation',false,'newProductionSolvedAreaM2',0);
save(fullfile(folder,'tmr_wall_thermal_evidence.mat'),'report','implicit','mesh','gas','boundary','Q','initialInfo','legacyInfo','sourceSHA');
fid=fopen(fullfile(folder,'tmr_wall_thermal_summary.json'),'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(report));clear cleanup;
fprintf('TMR wall thermal restart: %d accepted, residual %.9g -> %.9g, steady=%d; signed q [%.9g,%.9g].\n', ...
    implicit.acceptedSteps,report.initialOriginalResidual,report.finalOriginalResidual,implicit.steadyConverged, ...
    min(info.wall.heatFluxIntoWall),max(info.wall.heatFluxIntoWall));
end
function digest=fileSHA(path)
fid=fopen(path,'rb');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));bytes=fread(fid,Inf,'*uint8');clear cleanup;
md=java.security.MessageDigest.getInstance('SHA-256');md.update(bytes);
digest=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
