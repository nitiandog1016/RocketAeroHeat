function report=studyRocketPrimitiveReservoirTrial(folder)
%STUDYROCKETPRIMITIVERESERVOIRTRIAL 在同Q20/同正则方向上检验原始变量切向候选。
% 模块一：仅改变非线性候选路径；完整NS、原方向0.1、正性/温域/下降/守恒门槛不变。
% 模块二：Q22保守候选与Q23原始变量候选是Q20的并列子分支，不拼计数。
% 模块三：主求解器重新检查当前原NS方向；不把单元温域合法当完整NS或区域通过。
root=fileparts(fileparts(mfilename('fullpath')));addpath(root,fullfile(root,'internalFlow'));setupCutCellFlow;
assert(~exist(folder,'dir'));mkdir(folder);
baseFolder=fullfile(root,'outputs','v83_validation','krylov20');referenceFolder=fullfile(root,'outputs','v83_validation','krylov22');
probeFile=fullfile(root,'outputs','v83_validation','directnsprobereal04','direct_ns_direction_probe.mat');
options=struct('linearEquation','steady-newton','normalEulerLinearization','exact-branch','jacobianAction','original-difference', ...
    'trialStateCoordinates','primitive-tangent','maximumIterations',1,'initialPseudoDt',1e-7, ...
    'maximumKrylovIterations',48,'linearRelativeTolerance',.1,'maximumStepRetries',0,'maximumLineSearch',16, ...
    'steadyInitialGuess',struct('file',probeFile,'variant','ns-probe','scale',1));
main=continueRocketWallVelocityKrylov(fullfile(root,'outputs','v83_validation','krylov23'),baseFolder,options);
reference=jsondecode(fileread(fullfile(referenceFolder,'wall_velocity_krylov_summary.json')));
s=load(fullfile(root,'outputs','v83_validation','krylov23','wall_velocity_krylov_evidence.mat'),'result');
report=struct('status','tested-same-Q20-same-regularized-direction-primitive-tangent-original-NS-trial', ...
    'predecessorCase','krylov20','referenceCase','krylov22','candidateCase','krylov23', ...
    'candidatePath','primitive-tangent','referencePath','conservative','sameBaseSameDirectionComparison',true, ...
    'alternateHistoriesMerged',false,'newStandaloneProbeNS',0,'newMainActualNS',main.residualEvaluations, ...
    'main',main,'acceptedAlpha',s.result.history.alpha(end),'referenceAcceptedAlpha',1/4096, ...
    'referenceRmsMerit',reference.rmsMerit,'referenceMaximumResidual',reference.maximumResidual, ...
    'rmsBetterThanReference',main.rmsMerit<reference.rmsMerit,'maximumBetterThanReference',main.maximumResidual<reference.maximumResidual, ...
    'physicalSolution',false,'newProductionSolvedAreaM2',0,'engineProcessID',feature('getpid'));
save(fullfile(folder,'primitive_reservoir_trial_evidence.mat'),'report','main','-v7');
fid=fopen(fullfile(folder,'primitive_reservoir_trial_summary.json'),'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',jsonencode(report));fprintf('%s\n',jsonencode(report));
end
