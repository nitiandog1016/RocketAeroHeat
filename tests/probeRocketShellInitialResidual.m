function report=probeRocketShellInitialResidual(folder,domainFolder)
%PROBEROCKETSHELLINITIALRESIDUAL 在真实20度三维贴体外域评估现有完整黏性空间算子。
% 模块一：由保存来流构造均匀初猜及完整外边界储库，不以旧工程壁面外缘填满入口。
% 模块二：保留三个动量分量、给定Tw和常物性层流近似，记录实际空间代价/五量账。
% 模块三：初态p/q仅为未收敛派生量，不成为已解热流面积或真实飞行热环境结论。
root=fileparts(fileparts(mfilename('fullpath')));addpath(root,fullfile(root,'internalFlow'));
setupCutCellFlow;assert(~exist(folder,'dir'),'RocketShellInitial:Overwrite','不能覆盖实际算子试验。');
path=fullfile(domainFolder,'shell_domain_evidence.mat');d=load(path,'domain','fs','cfg');
cut=d.domain;fs=d.fs;assert(fs.alpha==20&&fs.Mach==5);
gas=struct('gamma',double(fs.gamma),'R',double(fs.R),'mu',double(fs.dynamicViscosity), ...
    'Pr',.72,'temperatureRange',[80 2000]);
rho=double(fs.density);u=double(fs.flowVelocityVector(:)');T=double(fs.temperature);
primitive=[rho u T];cv=gas.R/(gas.gamma-1);q=[rho,rho*u,rho*(cv*T+.5*dot(u,u))];
Q=repmat(q,numel(cut.cells.volume),1);
given=struct('type','characteristic','mode','riemannFarfield','reservoirPrimitive',primitive);
boundary=struct('xmin',given,'xmax',given,'ymin',given,'ymax',given,'zmin',given,'zmax',given, ...
    'solidWall',struct('type','wall','temperature',double(d.cfg.flight.Twall),'velocity',[0 0 0]));
t=tic;[rate,info]=cutCellNavierStokesResidual(Q,cut,gas,boundary);elapsed=toc(t);
scale=[rho,rho*fs.speed*ones(1,3),q(5)];residual=max(abs(rate)./scale,[],'all');
mapped=mapCutCellWallFields(cut,info,false);
assert(~mapped.eligibleForSurfaceCoverage&&mapped.newSolvedSurfaceAreaM2==0&& ...
    all(mapped.wallTemperatureInput.complete)&&all(mapped.pressure.complete)&&all(mapped.heatFluxIntoWall.complete));
L=max(cut.inputGeometry.V(:,1))-min(cut.inputGeometry.V(:,1));
report=struct('status','evaluated-real-20-degree-full-three-dimensional-initial-NS-residual-not-steady', ...
    'sourceDomainSHA256',fileSHA(path),'sourceFlowVelocityVector',u,'cellCount',size(Q,1), ...
    'wallFaces',numel(cut.walls.area),'openFaces',numel(cut.openFaces.area), ...
    'initialResidualPerSecond',residual,'oneSpatialEvaluationSeconds',elapsed, ...
    'referenceConvectiveTimeLoverUSeconds',L/fs.speed,'initialGuessKind','uniform-freestream-not-physical-solution', ...
    'outerBoundaryKind','full-three-component-characteristic-freestream-reservoir', ...
    'wallTemperatureKind','prescribed','gasModel','constant-gamma-frozen-freestream-mu-laminar-NS', ...
    'turbulenceSolved',false,'steadyConverged',false,'physicalSolution',false, ...
    'wallPressureRangePa',[min(mapped.pressure.value),max(mapped.pressure.value)], ...
    'initialWallHeatRangeWm2',[min(mapped.heatFluxIntoWall.value),max(mapped.heatFluxIntoWall.value)], ...
    'mappedSignedHeatPowerW',mapped.summedKnownHeatPower,'heatPowerMappingDifferenceW',mapped.heatPowerMappingDifference, ...
    'newProductionSolvedAreaM2',0,'engineProcessID',feature('getpid'));
mkdir(folder);save(fullfile(folder,'initial_residual_evidence.mat'),'Q','rate','info','mapped','gas','boundary','report','-v7');
fid=fopen(fullfile(folder,'initial_residual_summary.json'),'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',jsonencode(report));fprintf('%s\n',jsonencode(report));
end
function value=fileSHA(path)
fid=fopen(path,'rb');assert(fid>=0);guard=onCleanup(@()fclose(fid));b=fread(fid,Inf,'*uint8');clear guard;
md=java.security.MessageDigest.getInstance('SHA-256');md.update(b);value=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
