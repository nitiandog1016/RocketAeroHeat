function report=testRocketAxisymmetricCase(folder)
%TESTROCKETAXISYMMETRICCASE 完整箭体工况的输入来源、初猜与真实五量初始算子合同。
% 模块一：项目默认飞行输入逐值沿用，真实完整壁面不替换为截断入口。
% 模块二：核对标准大气/EOS/实际输运与给定SA输入，初始五量账重新积分。
% 模块三：完整实际C域计算NS+SA残差和所有墙q/p，初猜不冒充已求解或稳态。
% 模块四：非零攻角/侧滑、周向突起、非法给定输入须在推进前拒绝。
root=fileparts(fileparts(mfilename('fullpath')));
addpath(root,fullfile(root,'regionalFlow','axisymmetric'),fullfile(root,'internalFlow'));
if nargin<1,folder=fullfile(root,'outputs','v68_validation','case');end
cfg=createCaseConfig;item=createRocketAxisymmetricCase;
assert(isequal(item.inputContract.flight,cfg.flight)&& ...
    item.inputContract.completeExternalDomain&&~item.initialization.forebodyProfileImported&& ...
    ~item.initialization.externalCFDSolutionImported&&~item.initialization.truncatedAfterbodyInletPrescribed);
assert(strcmp(item.boundary.iMin.type,'axis')&&strcmp(item.boundary.iMax.type,'axis')&& ...
    strcmp(item.boundary.iMin.symmetryGradient,'mirror-parity')&& ...
    strcmp(item.boundary.iMax.symmetryGradient,'mirror-parity')&& ...
    strcmp(item.boundary.jMin.type,'wall')&&strcmp(item.boundary.jMax.type,'riemannReservoir')&& ...
    item.boundary.jMin.temperature==cfg.flight.Twall&&isequal(item.boundary.jMin.velocity,[0 0])&& ...
    strcmp(item.boundary.jMin.thermalGradient,'dirichlet-tangent'));
atm=standardAtmosphere(cfg.flight.altitude);P=item.boundary.jMax.primitive;gas=item.gas;
assert(P(1)==atm.density&&P(4)==atm.temperature&&P(2)==-cfg.flight.Mach*atm.speedOfSound&&P(3)==0&& ...
    gas.R==atm.R&&gas.gamma==atm.gamma);
assert(abs(P(1)*gas.R*P(4)-atm.pressure)<=16*eps*atm.pressure);
transport=axisymmetricFVTransport(P(4),gas);
assert(abs(transport.mu/atm.dynamicViscosity-1)<32*eps&& ...
    item.boundary.jMax.nuTilde==5*transport.mu/P(1));
primitive=axisymmetricFVState(item.Q(:,1:4),gas);
assert(max(abs(primitive(:,1:4)-P)./max(abs(P),1),[],'all')<64*eps&& ...
    all(item.Q(:,5)==P(1)*item.boundary.jMax.nuTilde));
integral=sum(item.Q.*item.mesh.volumePerRadian,1);
assert(isequal(integral,item.initialization.initialConservedIntegralPerRadian)&& ...
    ~item.initialization.initialStateIsSolution&&item.initialization.timeStepsTaken==0&& ...
    ~item.inputContract.physicalSolution&&~item.inputContract.eligibleForSurfaceCoverage&& ...
    item.inputContract.newProductionSolvedAreaM2==0);

%% 一、完整真实几何上的五量残差：不是只测几何或边界helper
[rate,info]=axisymmetricRANSResidual(item.Q,item.mesh,gas,item.boundary);
assert(isequal(size(rate),[item.mesh.cellCount 5])&&all(isfinite(rate),'all')&& ...
    numel(info.wall.faceID)==nnz(item.mesh.faces.boundarySide==3)&& ...
    isequal(sort(info.wall.faceID),find(item.mesh.faces.boundarySide==3))&& ...
    all(isfinite(info.wall.pressure)&info.wall.pressure>0)&&all(isfinite(info.wall.heatFluxIntoWall))&& ...
    all(info.wall.temperatureInput==cfg.flight.Twall)&&info.turbulenceImplemented);
own=sum(rate.*item.mesh.volumePerRadian,1)+info.netBoundaryFlux-info.sourceIntegral;
budget=sum(abs(rate.*item.mesh.volumePerRadian),1)+abs(info.netBoundaryFlux)+abs(info.sourceIntegral);
assert(all(abs(own)<=2048*eps*max(budget,realmin)));
assert(isequal(info.conservationDefect,own));

%% 二、非法给定输入/几何必须明确拒绝，不能默默投影成零攻角或无突起
refusals=struct('label',{},'identifier',{});
reject('nonzero-alpha',struct('flight',struct('alpha',1)),'RocketAxis:Axisymmetry');
reject('nonzero-beta',struct('flight',struct('beta',1)),'RocketAxis:Axisymmetry');
reject('circumferential-protrusion',struct('geometry',struct('protrusionEnabled',true)),'RocketAxis:Axisymmetry');
reject('subsonic-unsupported-slice',struct('flight',struct('Mach',.5)),'RocketAxis:Flight');
reject('wall-temperature-outside-domain',struct('flight',struct('Twall',2500)),'RocketAxis:WallTemperature');
reject('negative-SA-input',struct('nuTildeRatio',-1),'RocketAxis:Turbulence');
reject('unknown-flight-input',struct('flight',struct('someInletProfile',1)),'RocketAxis:Flight');
report=struct('status','passed-complete-rocket-input-and-initial-five-quantity-operator-contract', ...
    'cellCount',item.mesh.cellCount,'wallFaceCount',numel(info.wall.faceID), ...
    'allWallFaceSourcesPresent',true,'flight',cfg.flight,'standardAtmosphereMatched',true, ...
    'uniformFiveQuantityInitializationVerified',true,'initialConservationDefect',own, ...
    'initialOriginalResidual',max(abs(rate)./item.residualScale,[],'all'), ...
    'refusals',refusals,'timeStepsTaken',0,'steadyConverged',false, ...
    'physicalSolution',false,'experimentalValidation',false,'eligibleForSurfaceCoverage',false, ...
    'newProductionSolvedAreaM2',0);
if ~exist(folder,'dir'),mkdir(folder);end
save(fullfile(folder,'rocket_case_evidence.mat'),'item','report','rate','info');
fid=fopen(fullfile(folder,'rocket_case_summary.json'),'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(report));clear guard;
fprintf('Complete rocket input/initial operator: %d cells, %d real wall faces, %d refusals; zero advancement, no solution claim.\n', ...
    item.mesh.cellCount,numel(info.wall.faceID),numel(refusals));
    function reject(label,options,identifier)
        try,createRocketAxisymmetricCase(options);catch exception
            assert(strcmp(exception.identifier,identifier),'RocketAxisTest:Refusal','非预期拒绝%s。',exception.identifier);
            refusals(end+1)=struct('label',label,'identifier',exception.identifier);return;
        end
        error('RocketAxisTest:Refusal','非法输入%s未拒绝。',label);
    end
end
