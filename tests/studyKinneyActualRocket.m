function studyKinneyActualRocket(out,baselineFile)
%STUDYKINNEYACTUALROCKET 用真实20度当前工况核对方法差异，不重新生成网格。
% 模块一：与已绑定基线逐字核对默认热流及压力/外缘，防止改变默认逻辑。
% 模块二：同一外流/壁温切换Kinney公开公式，导出完整当前结果与独立审计输入。
% 模块三：保留未知区、面积和方法；不把多方法对照称为全面积完成。
root=fileparts(fileparts(mfilename('fullpath')));addpath(root);
assert(~exist(out,'dir'));mkdir(out);
old=load(baselineFile,'current','fs','cfg');base=old.current;cfg=old.cfg;fs=old.fs;
replayed=calcSurfaceHeating(base,fs,cfg);
assert(isequaln(replayed.heating.heatFlux,base.heating.heatFlux));
assert(isequaln(replayed.heating.recoveryTemperature,base.heating.recoveryTemperature));
assert(isequal(replayed.heatingCoverage.reasonCode,base.heatingCoverage.reasonCode));
cfg.heating.sidewallModel='kinneyAcreage';current=calcSurfaceHeating(base,fs,cfg);
assert(isequaln(current.pressure,base.pressure) && isequaln(current.boundaryLayerEdge,base.boundaryLayerEdge));
assert(~any(current.heating.eligibleFace & ~base.heating.eligibleFace));
area=base.localGeometry.area;h=current.heating;k=h.kinneyAcreage;e=current.boundaryLayerEdge;
assert(all(isnan(h.heatFlux(base.continuumRegime.stateUnresolvedFace))));
summary=struct('status','completed','Mach',fs.Mach,'alphaDeg',fs.alpha, ...
    'altitudeM',fs.altitude,'prescribedWallTemperatureK',cfg.flight.Twall, ...
    'faceCount',size(current.F,1),'totalArea',sum(area), ...
    'baselineHeatAreaFraction',sum(area(base.heating.eligibleFace))/sum(area), ...
    'selectedHeatAreaFraction',sum(area(h.eligibleFace))/sum(area), ...
    'newlyComputedHeatArea',sum(area(h.eligibleFace & ~base.heating.eligibleFace)), ...
    'prefixAssumedArea',sum(area(k.acceptedFace & k.length.prefixAssumedFace)), ...
    'originAssumedArea',sum(area(k.acceptedFace & k.length.originAssumedFace)), ...
    'entryAssumedArea',sum(area(k.acceptedFace & k.length.entryAssumedFace)), ...
    'sourceURL',k.sourceURL,'experimentalValidation',false,'completePhysicalSolution',false);
same=k.acceptedFace & isfinite(k.baselineHeatFlux);
summary.areaWeightedRelativeHeatDifference=sum(area(same).*abs(h.heatFlux(same)-k.baselineHeatFlux(same)))/ ...
    sum(area(same).*abs(k.baselineHeatFlux(same)));
summary.coverage=current.heatingCoverage.summary;
rows=table((1:numel(area))',area,e.pressure,e.temperature,e.speed,e.density,e.dynamicViscosity, ...
    meshValue(current.surfaceStreamlines,'distance'),meshValue(current.surfaceStreamlines,'pathCost'), ...
    meshValue(current.surfaceStreamlines,'stepLength'),meshValue(current.surfaceStreamlines,'predecessorFace'), ...
    current.aerothermalRegion.incidenceAngleDeg,k.length.integral,k.length.weightedLength, ...
    k.length.selectedLength,k.length.blendWeight,k.length.prefixAssumedFace, ...
    k.acceptedFace,h.laminarFace,h.turbulentFace,h.recoveryTemperatureLaminar, ...
    h.recoveryTemperatureTurbulent,h.effectiveCpLaminar,h.effectiveCpTurbulent, ...
    h.wallTemperatureByFace,h.heatFlux,k.baselineHeatFlux,h.faceMethodID, ...
    current.heatingCoverage.reasonCode,'VariableNames',{'face','area_m2','edge_pressure_Pa', ...
    'edge_temperature_K','edge_speed_m_s','edge_density_kg_m3','edge_viscosity_Pa_s', ...
    'geometric_length_m','path_cost','step_length_m','parent_face','incidence_deg', ...
    'weight_integral','weighted_length_m','selected_length_m','blend_weight','prefix_assumed', ...
    'accepted','laminar','turbulent','recovery_laminar_K','recovery_turbulent_K','cp_laminar', ...
    'cp_turbulent','wall_input_K','heat_flux_W_m2','baseline_heat_flux_W_m2','heat_method_id','reason_code'});
writetable(rows,fullfile(out,'faces.csv'));
fid=fopen(fullfile(out,'summary.json'),'w','n','UTF-8');fprintf(fid,'%s\n',jsonencode(summary));fclose(fid);
save(fullfile(out,'current_case.mat'),'current','fs','cfg','summary','-v7');
exportAerothermalWeb(current,fullfile(out,'workbench'));
fprintf('Actual20 Kinney: heat %.12f%% vs %.12f%%; new heat area %.12g m2; relative method difference %.9g.\n', ...
    100*summary.selectedHeatAreaFraction,100*summary.baselineHeatAreaFraction, ...
    summary.newlyComputedHeatArea,summary.areaWeightedRelativeHeatDifference);
end
function value=meshValue(path,key)
value=double(path.(key)(:));
end
