function report=compareReferenceEnthalpyRocket(folder)
% 原19752面只读对照：仅切换参考性质模型，不改外流/原面/壁温。
data=load('outputs/v104_validation/baseline02/current_case.mat');
mesh=data.current; fs=data.fs; cfg=data.cfg;
legacyCfg=cfg; legacyCfg.heating.referencePropertyModel='linearTemperature';
currentCfg=cfg; currentCfg.heating.referencePropertyModel='referenceEnthalpy';
tic;
legacy=calcSurfaceHeating(mesh,fs,legacyCfg);
current=calcSurfaceHeating(mesh,fs,currentCfg);
assert(isequal(current.V,mesh.V)&&isequal(current.F,mesh.F));
assert(isequal(current.pressure,mesh.pressure));
assert(isequaln(current.externalFlow,mesh.externalFlow));
area=mesh.localGeometry.area(:); n=numel(area);
assert(n==19752 && abs(sum(area)-1.9646292565715551)<2e-13);
old=legacy.heating.heatFlux(:); now=current.heating.heatFlux(:);
common=isfinite(old)&isfinite(now);
assert(all(isnan(now(~current.heating.eligibleFace))));
assert(isequaln(current.heating.referenceTemperatureLaminar,current.boundaryLayer.referenceTemperature));
report=struct('passed',true,'faces',n,'totalAreaM2',sum(area), ...
    'legacyCalculatedAreaM2',sum(area(isfinite(old))), ...
    'currentCalculatedAreaM2',sum(area(isfinite(now))), ...
    'sameFaceComparisonAreaM2',sum(area(common)), ...
    'heatAreaL1RelativeChange',sum(area(common).*abs(now(common)-old(common)))/sum(area(common).*abs(old(common))), ...
    'legacySignedPowerW',sum(area(isfinite(old)).*old(isfinite(old))), ...
    'currentSignedPowerW',sum(area(isfinite(now)).*now(isfinite(now))), ...
    'newlyFiniteFaces',nnz(isfinite(now)&~isfinite(old)), ...
    'newlyUnknownFaces',nnz(~isfinite(now)&isfinite(old)), ...
    'externalFlowUnchanged',true,'newPhysicalQualification',false, ...
    'scope','same current code, old and new reference-property choice; not a reproduction of all v104 source', ...
    'elapsedSeconds',toc);
values=table((1:n)',area,old,now,'VariableNames', ...
    {'faceID','areaM2','linearReferenceHeatFluxWm2','enthalpyReferenceHeatFluxWm2'});
writetable(values,fullfile(folder,'face_comparison.csv'));
disp(report);
end
