function report=diagnoseRocketGraphKrylovDirection(folder,sourceCase)
%DIAGNOSEROCKETGRAPHKRYLOVDIRECTION 在实际失败方向上区分图近似误差与稳态线性缺陷。
% 模块一：只读取保存的完整NS方向和图预条件器，不新增NS调用或候选。
% 模块二：I/tau代数消去后比较Jgraph与Jfull；单列质量项的相消规模。
% 模块三：按真实层及原面定位误差，不能把一个方向的结果推广成完整谱证明。
root=fileparts(fileparts(mfilename('fullpath')));addpath(root,fullfile(root,'internalFlow'));setupCutCellFlow;
assert(~exist(folder,'dir'),'GraphDirection:Overwrite','不得覆盖实际失败方向诊断。');
assert(~isempty(regexp(sourceCase,'^krylov[0-9]+$','once')));
sourceFile=fullfile(root,'outputs','v83_validation',sourceCase,'wall_velocity_krylov_evidence.mat');
s=load(sourceFile,'result');r=s.result;
assert(strcmp(r.rightPreconditioner,'lateral-colored-line')&&numel(r.linearLog)==1&&r.acceptedNonlinearIterations==0);
linear=r.linearLog{1};e=linear.steadyDirectionEvidence;directionU=e.directionU;fullAction=e.value;rhs=r.initialRate./r.residualScale;
assert(e.baseAcceptedIteration==0);operator=r.firstOperator;tau=operator.pseudoTimeStepSeconds;
preconditionerAction=applyRocketShellGraphOperator(operator,directionU);massAction=directionU/tau;graphAction=massAction-preconditionerAction;
error=graphAction-fullAction;nf=operator.sourceFaces;nl=operator.layers;n=nf*nl;
layerErrorFraction=zeros(nl,1);layerFullActionFraction=layerErrorFraction;layerRhsFraction=layerErrorFraction;
for layer=1:nl
    ids=(layer-1)*nf+(1:nf);layerErrorFraction(layer)=sum(error(ids,:).^2,'all')/sum(error.^2,'all');
    layerFullActionFraction(layer)=sum(fullAction(ids,:).^2,'all')/sum(fullAction.^2,'all');
    layerRhsFraction(layer)=sum(rhs(ids,:).^2,'all')/sum(rhs.^2,'all');
end
[~,order]=sort(sum(error.^2,2),'descend');top=order(1:min(20,n));
report=struct('status','measured-actual-failed-graph-direction-approximation-and-linear-defect', ...
    'sourceCase',sourceCase,'graphActionRelativeToFullNS',norm(error(:))/norm(fullAction(:)), ...
    'equationActionRelativeErrors',vecnorm(error,2,1)./vecnorm(fullAction,2,1), ...
    'graphSteadyLinearDefect',norm(-graphAction(:)-rhs(:))/norm(rhs(:)), ...
    'fullNSSteadyLinearDefect',norm(-fullAction(:)-rhs(:))/norm(rhs(:)), ...
    'massActionNormRelativeToFullNS',norm(massAction(:))/norm(fullAction(:)), ...
    'preconditionerActionNormRelativeToFullNS',norm(preconditionerAction(:))/norm(fullAction(:)), ...
    'graphPreconditionerRelativeResidual',linear.graphRelativeResidual,'preconditionerPseudoDt',tau, ...
    'layerErrorFraction',layerErrorFraction,'layerFullActionFraction',layerFullActionFraction,'layerRhsFraction',layerRhsFraction, ...
    'largestErrorCellIDs',top,'largestErrorOriginalFaceIDs',mod(top-1,nf)+1,'largestErrorLayerIDs',floor((top-1)/nf)+1, ...
    'normalizedGMRESHistory',linear.gmresResidualHistory/norm(rhs(:)), ...
    'fullNSSolverCalledAgain',false,'newOriginalNSEvaluations',0,'newAcceptedIterations',0, ...
    'physicalSolution',false,'newProductionSolvedAreaM2',0,'engineProcessID',feature('getpid'));
assert(abs(report.fullNSSteadyLinearDefect-linear.fullSystemRelativeDefect)<1e-13);
mkdir(folder);save(fullfile(folder,'graph_direction_evidence.mat'),'report','sourceFile','rhs','directionU','fullAction','graphAction', ...
    'massAction','preconditionerAction','-v7');
fid=fopen(fullfile(folder,'graph_direction_summary.json'),'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(report));fprintf('%s\n',jsonencode(report));
end
