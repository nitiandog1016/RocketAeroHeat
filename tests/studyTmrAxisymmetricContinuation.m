function report=studyTmrAxisymmetricContinuation(source,folder,maxSteps,controls)
%STUDYTMRAXISYMMETRICCONTINUATION 从真实检查点续做预算稳态研究，不重跑初始段。
% 模块一：核对原网格、边界、尺度及保存残差；父文件SHA绑定到本次输入。
% 模块二：只调整Newton/Jacobian工作参数，保持原稳态及BE/守恒门槛。
% 模块三：本段与父段伪时间、工作量和四量账分开保存，再核对累计账。
% 模块四：预算终态不等于稳态、实验验证或生产区域资格。
root=fileparts(fileparts(mfilename('fullpath')));
addpath(root,fullfile(root,'regionalFlow','axisymmetric'),fullfile(root,'internalFlow'));
if nargin<4,controls=struct;end
validateattributes(maxSteps,{'numeric'},{'real','finite','scalar','integer','positive'});
sourceSHA=fileSHA(source);saved=load(source);
sourceFile=java.io.File(source).getCanonicalPath();
targetFile=java.io.File(fullfile(folder,'tmr_implicit_budget.mat')).getCanonicalPath();
assert(~strcmpi(char(sourceFile),char(targetFile)), ...
    'TmrContinuation:Overwrite','输出不能覆盖父检查点。');
assert(all(isfield(saved,{'implicit','mesh','gas','boundary'})), ...
    'TmrContinuation:Checkpoint','检查点缺少实际隐式结果和离散合同。');
parent=saved.implicit;mesh=saved.mesh;gas=saved.gas;boundary=saved.boundary;
assert(mesh.cellCount==1000&&~parent.physicalSolution&&~parent.eligibleForSurfaceCoverage&& ...
    ~parent.pseudoTimeIsPhysical&&parent.physicalTimeAdvanced==0&&~isfield(parent,'time'), ...
    'TmrContinuation:Identity','须是本研究的1000格伪时间检查点。');
assert(isequaln(parent.geometryBinding,struct('X',mesh.X,'R',mesh.R,'cells',mesh.cells, ...
    'volumePerRadian',mesh.volumePerRadian)),'TmrContinuation:Geometry','检查点几何身份不符。');
scale=parent.residualScale;
[rate,info]=axisymmetricNavierStokesResidual(parent.Q,mesh,gas,boundary);
assert(isequaln(info,parent.finalInfo)&&max(abs(rate)./scale,[],'all')==parent.residualNorm, ...
    'TmrContinuation:Replay','检查点不能用当前完整空间源码逐值重放。');
allowed={'initialPseudoCFL','maximumPseudoCFL','pseudoCFLGrowth','maximumPseudoStep', ...
    'maxNewtonIterations','jacobianRefreshEvery','differenceStep','differenceScheme','maxLineSearch'};
assert(isstruct(controls)&&isscalar(controls)&&all(ismember(fieldnames(controls),allowed)), ...
    'TmrContinuation:Controls','续算仅允许修改工作参数，不能放宽物理/非线性验收。');
opts=parent.options;opts.maxSteps=maxSteps;
assert(isequaln(opts.residualScale,scale),'TmrContinuation:Scale', ...
    '父选项尺度必须与保存的实际残差尺度一致。');
for item=fieldnames(controls)',opts.(item{1})=controls.(item{1});end
assert(opts.steadyResidualTolerance==2e-6,'TmrContinuation:Tolerance','原稳态门槛须保留。');
if ~exist(folder,'dir'),mkdir(folder);end
if isfield(saved,'cumulative')
    previous=saved.cumulative;
else
    previous=struct('initialConservedIntegral',parent.initialConservedIntegral, ...
        'boundaryIntegral',parent.accumulatedBoundaryIntegral,'sourceIntegral',parent.accumulatedSourceIntegral, ...
        'pseudoTime',parent.pseudoTime,'acceptedSteps',parent.acceptedSteps, ...
        'rejectedAttempts',parent.rejectedAttempts,'residualEvaluations',parent.residualEvaluations);
end
previousDefect=parent.finalConservedIntegral-previous.initialConservedIntegral+ ...
    previous.boundaryIntegral-previous.sourceIntegral;
assert(max(abs(previousDefect)./(sum(mesh.volumePerRadian)*scale))<=opts.conservationTolerance, ...
    'TmrContinuation:ParentConservation','父检查点已有累计四量账不闭合。');
clock=tic;implicit=advanceAxisymmetricSteady(parent.Q,mesh,gas,boundary,opts);implicitSeconds=toc(clock);
cumulative=previous;
cumulative.boundaryIntegral=previous.boundaryIntegral+implicit.accumulatedBoundaryIntegral;
cumulative.sourceIntegral=previous.sourceIntegral+implicit.accumulatedSourceIntegral;
cumulative.pseudoTime=previous.pseudoTime+implicit.pseudoTime;
cumulative.acceptedSteps=previous.acceptedSteps+implicit.acceptedSteps;
cumulative.rejectedAttempts=previous.rejectedAttempts+implicit.rejectedAttempts;
cumulative.residualEvaluations=previous.residualEvaluations+implicit.residualEvaluations;
cumulative.balanceDefect=implicit.finalConservedIntegral-previous.initialConservedIntegral+ ...
    cumulative.boundaryIntegral-cumulative.sourceIntegral;
cumulative.balanceRelative=max(abs(cumulative.balanceDefect)./(sum(mesh.volumePerRadian)*scale));
assert(cumulative.balanceRelative<=opts.conservationTolerance, ...
    'TmrContinuation:Conservation','跨检查点累计四量账不闭合。');
assert(strcmp(sourceSHA,fileSHA(source)),'TmrContinuation:Mutation','父检查点在续算期间改变。');
report=struct('status','completed-budgeted-continuation-not-experimental-validation', ...
    'parentFile',source,'parentSHA256',sourceSHA,'parentResidual',parent.residualNorm, ...
    'originalResidual',implicit.residualNorm,'steadyConverged',implicit.steadyConverged, ...
    'stopReason',implicit.stopReason,'requiredSteadyTolerance',opts.steadyResidualTolerance, ...
    'requiredConsecutiveSteps',opts.steadyRequiredSteps,'segmentAcceptedSteps',implicit.acceptedSteps, ...
    'segmentRejectedAttempts',implicit.rejectedAttempts,'segmentResidualEvaluations',implicit.residualEvaluations, ...
    'diagnosticReplayResidualEvaluations',1, ...
    'segmentElapsedSeconds',implicitSeconds,'segmentPseudoTime',implicit.pseudoTime, ...
    'cumulative',cumulative,'pseudoTimeIsPhysical',false,'physicalTimeAdvanced',0, ...
    'physicalSolution',false,'experimentalValidation',false,'newProductionSolvedAreaM2',0);
save(fullfile(folder,'tmr_implicit_budget.mat'),'implicit','mesh','gas','boundary','report','cumulative','sourceSHA','implicitSeconds');
fid=fopen(fullfile(folder,'tmr_continuation.json'),'w','n','UTF-8');assert(fid>=0);
fprintf(fid,'%s',jsonencode(report));fclose(fid);
fprintf('TMR continuation: original %.9g -> %.9g; steady=%d; total BE ledger %.3g.\n', ...
    parent.residualNorm,implicit.residualNorm,implicit.steadyConverged,cumulative.balanceRelative);
end
function digest=fileSHA(path)
fid=fopen(path,'rb');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));bytes=fread(fid,Inf,'*uint8');clear cleanup;
md=java.security.MessageDigest.getInstance('SHA-256');md.update(bytes);
digest=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
