function report=studyRocketWallVelocityKrylov(folder,integrationFolder,options)
%STUDYROCKETWALLVELOCITYKRYLOV 从真实三维静止墙约束基线开展原完整NS有界修正。
% 模块一：同一v82保守三次末态作内部初猜，墙应力离散改变后重新计数。
% 模块二：初始Q/rate/info须精确复现已测集成证据，原所有验收门槛保持。
% 模块三：保存接受/拒绝和完整通量，不把伪时间、有限场值或耗散检查当物理解。
if nargin<3,options=struct;end
root=fileparts(fileparts(mfilename('fullpath')));addpath(root,fullfile(root,'internalFlow'));setupCutCellFlow;
assert(~exist(folder,'dir'),'WallVelocityKrylov:Overwrite','不得覆盖真实修正。');mkdir(folder);
d=load(fullfile(root,'outputs','v80_validation','domain02','shell_domain_evidence.mat'),'domain');
s=load(fullfile(integrationFolder,'wall_velocity_integration_evidence.mat'),'Q','rate','info','gas','boundary','scale');
assert(strcmp(cutCellWallVelocityPolicy(s.boundary.solidWall),'dirichlet-tangent'));
options.residualScale=s.scale;
if ~isfield(options,'initialPseudoDt'),options.initialPseudoDt=1e-8;end
if ~isfield(options,'maximumIterations'),options.maximumIterations=3;end
if ~isfield(options,'maximumKrylovIterations'),options.maximumKrylovIterations=6;end
lineage=struct('sourceState','v82-exact-conservative-three-corrections-internal-initial-guess', ...
    'sourceHistoryAppended',false,'newEquationInitialCounter',0,'wallVelocityGradientChanged',true, ...
    'interiorEulerFlux','exact-godunov','viscousWorkVelocity','arithmetic','wallVelocityGradient','dirichlet-tangent', ...
    'physicalWallVelocityAndTemperatureKept',true,'externalCFDImported',false);
timer=tic;
try
    result=solveRocketShellSteadyKrylov(s.Q,d.domain,s.gas,s.boundary,options);
catch ex
    failure=struct('status','failed-actual-static-wall-velocity-complete-NS-study','identifier',ex.identifier,'message',ex.message, ...
        'elapsedSeconds',toc(timer),'lineage',lineage,'physicalSolution',false,'newProductionSolvedAreaM2',0);
    write(fullfile(folder,'failure.json'),jsonencode(failure));rethrow(ex);
end
elapsed=toc(timer);
assert(isequaln(result.initialQ,s.Q)&&isequaln(result.initialRate,s.rate)&&isequaln(result.initialInfo,s.info), ...
    'WallVelocityKrylov:Source','初始完整算子没有精确复现同Q集成基线。');
mapped=mapCutCellWallFields(d.domain,result.info,result.steadyConverged);assert(~mapped.eligibleForSurfaceCoverage);
report=struct('status','bounded-real-20deg-static-wall-velocity-gradient-full-NS-Krylov-study', ...
    'sourceFaces',size(d.domain.inputGeometry.F,1),'cellCount',size(result.Q,1), ...
    'acceptedNonlinearIterations',result.acceptedNonlinearIterations,'candidateTrials',result.candidateTrials, ...
    'residualEvaluations',result.residualEvaluations,'operatorBuilds',result.operatorBuilds, ...
    'initialMaximumResidual',result.initialMaximumResidual,'maximumResidual',result.maximumResidual, ...
    'initialRmsMerit',result.initialRmsMerit,'rmsMerit',result.rmsMerit,'elapsedSeconds',elapsed, ...
    'matrixVectorProducts',result.matrixVectorProducts,'jacobianResidualEvaluations',result.jacobianResidualEvaluations, ...
    'preconditionerApplications',result.preconditionerApplications,'lineage',lineage,'wallVelocityGradient','dirichlet-tangent', ...
    'steadyConverged',result.steadyConverged,'stopReason',result.stopReason,'spatialConservationRelative',result.spatialConservationRelative, ...
    'steadyBoundaryFluxBalance',result.steadyBoundaryFluxBalance,'signedHeatPowerW',mapped.summedKnownHeatPower, ...
    'wallHeatRangeWm2',[min(mapped.heatFluxIntoWall.value),max(mapped.heatFluxIntoWall.value)], ...
    'physicalTimeAdvanced',0,'BETimeStepsClaimed',0,'physicalSolution',false,'newProductionSolvedAreaM2',0,'engineProcessID',feature('getpid'));
gas=s.gas;boundary=s.boundary;
save(fullfile(folder,'wall_velocity_krylov_evidence.mat'),'result','mapped','report','gas','boundary','lineage','-v7');
write(fullfile(folder,'wall_velocity_krylov_summary.json'),jsonencode(report));fprintf('%s\n',jsonencode(report));
end
function write(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',value);
end
