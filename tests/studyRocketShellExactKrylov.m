function report=studyRocketShellExactKrylov(folder,integrationFolder,options)
%STUDYROCKETSHELLEXACTKRYLOV 从已验收的真实三维精确通量基线开展有界稳态修正。
% 模块一：保留v81六次末态作为内部初猜，显式切换离散方法后重新开始计数。
% 模块二：初始Q、完整rate/info必须精确复现v82集成证据，不拼接旧HLLC残差历史。
% 模块三：原温域、空间守恒、线性目标和稳态门槛保持；未收敛不增加合格面积。
if nargin<3,options=struct;end
root=fileparts(fileparts(mfilename('fullpath')));addpath(root,fullfile(root,'internalFlow'));setupCutCellFlow;
assert(~exist(folder,'dir'),'ShellExactStudy:Overwrite','不得覆盖真实试算证据。');mkdir(folder);
domainPath=fullfile(root,'outputs','v80_validation','domain02','shell_domain_evidence.mat');
sourcePath=fullfile(root,'outputs','v81_validation','arithmetic02','steady_krylov_evidence.mat');
integrationPath=fullfile(integrationFolder,'exact_integration_evidence.mat');
d=load(domainPath,'domain');source=load(sourcePath,'result');
s=load(integrationPath,'Q','rate','info','gas','boundary');
assert(isequaln(s.Q,source.result.Q),'ShellExactStudy:Source','新基线未保留旧方法的实际完整初猜。');
options.residualScale=source.result.residualScale;clear source;
assert(strcmp(cutCellInteriorEulerPolicy(s.boundary),'exact-godunov')&& ...
    strcmp(cutCellViscousWorkPolicy(s.boundary),'arithmetic'),'ShellExactStudy:Policy','需要显式精确Godunov与算术功策略。');
if ~isfield(options,'initialPseudoDt'),options.initialPseudoDt=1e-8;end
if ~isfield(options,'maximumIterations'),options.maximumIterations=3;end
if ~isfield(options,'maximumKrylovIterations'),options.maximumKrylovIterations=6;end
lineage=struct('sourceState','v81-arithmetic02-six-HLLC-corrections-internal-initial-guess', ...
    'sourceAcceptedIterations',6,'discretizationChangedFromSource',true,'sourceHistoryAppended',false, ...
    'interiorEulerFlux','exact-godunov','viscousWorkVelocity','arithmetic', ...
    'newEquationInitialCounter',0,'samePhysicalBoundary',true,'externalCFDImported',false);
if isfield(options,'trialStateCoordinates'),lineage.nonlinearTrialStateCoordinates=options.trialStateCoordinates;end
t=tic;
try
    result=solveRocketShellSteadyKrylov(s.Q,d.domain,s.gas,s.boundary,options);
catch ex
    failure=struct('status','failed-explicit-exact-Godunov-actual-3D-study','identifier',ex.identifier, ...
        'message',ex.message,'elapsedSeconds',toc(t),'lineage',lineage,'physicalSolution',false,'newProductionSolvedAreaM2',0);
    write(fullfile(folder,'failure.json'),jsonencode(failure));rethrow(ex);
end
elapsed=toc(t);
assert(isequaln(result.initialQ,s.Q)&&isequaln(result.initialRate,s.rate)&&isequaln(result.initialInfo,s.info), ...
    'ShellExactStudy:Identity','新方程初始完整算子没有精确复现集成基线。');
mapped=mapCutCellWallFields(d.domain,result.info,result.steadyConverged);
assert(~mapped.eligibleForSurfaceCoverage&&result.physicalTimeAdvanced==0&&result.BETimeStepsClaimed==0);
report=struct('status','bounded-actual-20deg-explicit-exact-Godunov-full-NS-Krylov-study', ...
    'sourceFaces',size(d.domain.inputGeometry.F,1),'cellCount',numel(d.domain.cells.volume), ...
    'acceptedNonlinearIterations',result.acceptedNonlinearIterations,'candidateTrials',result.candidateTrials, ...
    'residualEvaluations',result.residualEvaluations,'operatorBuilds',result.operatorBuilds, ...
    'initialMaximumResidual',result.initialMaximumResidual,'maximumResidual',result.maximumResidual, ...
    'initialRmsMerit',result.initialRmsMerit,'rmsMerit',result.rmsMerit,'elapsedSeconds',elapsed, ...
    'matrixVectorProducts',result.matrixVectorProducts,'jacobianResidualEvaluations',result.jacobianResidualEvaluations, ...
    'preconditionerApplications',result.preconditionerApplications,'lineage',lineage, ...
    'interiorEulerFlux','exact-godunov','viscousWorkVelocity','arithmetic', ...
    'steadyConverged',result.steadyConverged,'stopReason',result.stopReason, ...
    'spatialConservationRelative',result.spatialConservationRelative, ...
    'steadyBoundaryFluxBalance',result.steadyBoundaryFluxBalance, ...
    'wallHeatRangeWm2',[min(mapped.heatFluxIntoWall.value),max(mapped.heatFluxIntoWall.value)], ...
    'signedHeatPowerW',mapped.summedKnownHeatPower,'physicalTimeAdvanced',0,'BETimeStepsClaimed',0, ...
    'physicalSolution',false,'newProductionSolvedAreaM2',0,'engineProcessID',feature('getpid'));
gas=s.gas;boundary=s.boundary;
save(fullfile(folder,'steady_krylov_evidence.mat'),'result','mapped','report','gas','boundary','lineage','-v7');
write(fullfile(folder,'steady_krylov_summary.json'),jsonencode(report));fprintf('%s\n',jsonencode(report));
end
function write(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',value);
end
