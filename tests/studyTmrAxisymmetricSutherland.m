function report=studyTmrAxisymmetricSutherland(folder,maxSteps)
%STUDYTMRAXISYMMETRICSUTHERLAND 从真实v63状态重启局部变输运NS，不导入CFD。
% 模块一：冻结v63检查点SHA和原WIND总量边界；只更换显式层流输运模型。
% 模块二：旧Q仅作新方程初场，旧墙热不复用；实际求解到原稳态门槛。
% 模块三：保存新气体/边界、BE四量账、原残差、输入Re差异及完整方法来源。
% 模块四：仍为粗网格层流数值研究，缺少湍流/域敏感性/实验验收，不计生产面积。
root=fileparts(fileparts(mfilename('fullpath')));
addpath(root,fullfile(root,'regionalFlow','axisymmetric'),fullfile(root,'internalFlow'));
if nargin<1,folder=fullfile(root,'outputs','v64_validation','tmr_sutherland');end
if nargin<2,maxSteps=80;end
validateattributes(maxSteps,{'numeric'},{'real','finite','scalar','integer','positive'});
source=fullfile(root,'outputs','v63_validation','tmr_hlle_continue1','tmr_implicit_budget.mat');
if ~exist(source,'file'),source=fullfile(root,'validation','v63','tmr_hlle_continue1','tmr_implicit_budget.mat');end
parent=load(source,'implicit','mesh','gas','boundary');parentSHA=fileSHA(source);
assert(parent.implicit.steadyConverged&&parent.mesh.cellCount==1000&&~parent.implicit.physicalSolution);
mesh=parent.mesh;boundary=parent.boundary;Q=parent.implicit.Q;scale=parent.implicit.residualScale;
[gas,transportProvenance]=createTmrAxisymmetricAirGas;
assert(gas.gamma==parent.gas.gamma&&gas.R==parent.gas.R&&gas.Pr==parent.gas.Pr, ...
    'TmrTransport:EOS','本切片不改变EOS/热容及Pr，不能沿用不同能量定义的Q。');
[rate,initialInfo]=axisymmetricNavierStokesResidual(Q,mesh,gas,boundary);
initialResidual=max(abs(rate)./scale,[],'all');
reservoir=boundary.iMin.primitive;inputTransport=axisymmetricFVTransport(reservoir(4),gas);
inletRe=reservoir(1)*norm(reservoir(2:3))/inputTransport.mu;
opts=struct('maxSteps',maxSteps,'initialPseudoCFL',500,'maximumPseudoCFL',1e7,'pseudoCFLGrowth',2, ...
    'residualScale',scale,'differenceScheme','central','jacobianRefreshEvery',1,'maxNewtonIterations',24, ...
    'steadyResidualTolerance',2e-6,'steadyRequiredSteps',3,'minimumSteadySteps',3);
if ~exist(folder,'dir'),mkdir(folder);end
clock=tic;implicit=advanceAxisymmetricSteady(Q,mesh,gas,boundary,opts);seconds=toc(clock);
[replayRate,replayInfo]=axisymmetricNavierStokesResidual(implicit.Q,mesh,gas,boundary);
assert(isequaln(replayInfo,implicit.finalInfo)&& ...
    max(abs(replayRate)./scale,[],'all')==implicit.residualNorm&&strcmp(parentSHA,fileSHA(source)));
report=struct('status','completed-budgeted-Sutherland-NS-restart-not-turbulent-validation', ...
    'sourceCheckpointSHA256',parentSHA,'sourceCheckpoint',source, ...
    'initialOriginalResidual',initialResidual,'finalOriginalResidual',implicit.residualNorm, ...
    'steadyConverged',implicit.steadyConverged,'stopReason',implicit.stopReason, ...
    'acceptedSteps',implicit.acceptedSteps,'rejectedAttempts',implicit.rejectedAttempts, ...
    'solverResidualEvaluations',implicit.residualEvaluations,'diagnosticResidualEvaluations',2, ...
    'elapsedSeconds',seconds,'globalBEFourQBalanceRelative',implicit.globalBalanceRelative, ...
    'wallSignedHeatRangeWm2',[min(replayInfo.wall.heatFluxIntoWall),max(replayInfo.wall.heatFluxIntoWall)], ...
    'transportProvenance',transportProvenance,'prescribedInletPrimitive',reservoir, ...
    'derivedInletRePerM',inletRe,'diagramRoundedInletRePerM',5.706e6, ...
    'relativeReDifference',inletRe/5.706e6-1,'inletDensityWasResetToDiagram',false, ...
    'pseudoTimeIsPhysical',false,'physicalTimeAdvanced',0,'turbulenceImplemented',false, ...
    'physicalSolution',false,'eligibleForSurfaceCoverage',false,'experimentalValidation',false, ...
    'newProductionSolvedAreaM2',0);
save(fullfile(folder,'tmr_sutherland_evidence.mat'),'report','implicit','mesh','gas','boundary', ...
    'Q','initialInfo','parentSHA','transportProvenance');
fid=fopen(fullfile(folder,'tmr_sutherland_summary.json'),'w','n','UTF-8');assert(fid>=0);
fprintf(fid,'%s',jsonencode(report));fclose(fid);
fprintf('TMR local Sutherland: original %.9g -> %.9g, steady=%d; Re/m %.9g (diagram difference %.6g%%).\n', ...
    initialResidual,implicit.residualNorm,implicit.steadyConverged,inletRe,100*report.relativeReDifference);
end
function digest=fileSHA(path)
fid=fopen(path,'rb');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));bytes=fread(fid,Inf,'*uint8');clear cleanup;
md=java.security.MessageDigest.getInstance('SHA-256');md.update(bytes);
digest=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
