function report=testRocketAxisymmetricWallCase(folder)
%TESTROCKETAXISYMMETRICWALLCASE 核对完整箭体静止壁速度梯度受控对照工况。
% 模块一：两工况严格共享真实几何、均匀Q、气体、Tw和远场，不借用旧终态。
% 模块二：同一Q只允许墙牵引及动量rate变化；能量/质量/SA和墙热保持。
% 模块三：新策略的完整真实初算、五量账和115墙段约束分别检查，不宣称能降低温度。
root=fileparts(fileparts(mfilename('fullpath')));
addpath(root,fullfile(root,'regionalFlow','axisymmetric'));
if nargin<1,folder=fullfile(root,'outputs','v69_validation','wall_case');end
old=createRocketAxisymmetricCase;item=createRocketAxisymmetricWallCase;
for key={'mesh','domain','surfaceMesh','geometryTruth','gas','Q','residualScale','freestream','options','initialization'}
    assert(isequaln(item.(key{1}),old.(key{1})),'RocketWallCaseTest:Control','对照不应改变%s。',key{1});
end
boundary=item.boundary;boundary.jMin=rmfield(boundary.jMin,'velocityGradient');
assert(isequaln(boundary,old.boundary)&&strcmp(item.caseFactory,'createRocketAxisymmetricWallCase')&& ...
    strcmp(item.boundary.jMin.velocityGradient,'dirichlet-tangent'));
[oldRate,oldInfo]=axisymmetricRANSResidual(old.Q,old.mesh,old.gas,old.boundary);
[rate,info]=axisymmetricRANSResidual(item.Q,item.mesh,item.gas,item.boundary);
assert(all(isfinite(rate),'all')&&isequal(size(rate),[item.mesh.cellCount 5])&& ...
    isequal(rate(:,[1 4 5]),oldRate(:,[1 4 5]))&&isequaln(info.sa,oldInfo.sa)&& ...
    isequal(info.cellSourceIntegral,oldInfo.cellSourceIntegral)&& ...
    isequal(info.wall.heatFluxIntoWall,oldInfo.wall.heatFluxIntoWall)&& ...
    any(info.wall.viscousTraction~=oldInfo.wall.viscousTraction,'all'), ...
    'RocketWallCaseTest:Control','同一初Q只应改变真实墙牵引和动量方程。');
assert(all(info.wall.mechanicalPowerIntoFluidPerRadian==0)&& ...
    isequal(info.wall.totalEnergyFluxOutPerRadian,oldInfo.wall.totalEnergyFluxOutPerRadian));
work=createRocketAxisymmetricWallCase(struct('wallVelocityGradient','legacy','viscousWorkVelocity','arithmetic'));
both=createRocketAxisymmetricWallCase(struct('viscousWorkVelocity','arithmetic'));
[workRate,workInfo]=axisymmetricRANSResidual(work.Q,work.mesh,work.gas,work.boundary);
[bothRate,bothInfo]=axisymmetricRANSResidual(both.Q,both.mesh,both.gas,both.boundary);
assert(isequal(workRate(:,[1 2 3 5]),oldRate(:,[1 2 3 5]))&& ...
    isequal(workInfo.sa,oldInfo.sa)&&isequal(workInfo.cellSourceIntegral,oldInfo.cellSourceIntegral)&& ...
    isequal(workInfo.wall.heatFluxIntoWall,oldInfo.wall.heatFluxIntoWall)&& ...
    any(workRate(:,4)~=oldRate(:,4))&& ...
    isequal(bothRate(:,[1 2 3 5]),rate(:,[1 2 3 5]))&&isequal(bothRate(:,4),workRate(:,4))&& ...
    isequal(bothInfo.wall.heatFluxIntoWall,oldInfo.wall.heatFluxIntoWall), ...
    'RocketWallCaseTest:WorkControl','同一Q下内面功速度只应改能量方程，两个旋钮须能独立追溯。');
assert(isfield(info,'wallVelocityGradient'));
audit=info.wallVelocityGradient;
assert(isequal(sort(audit.faceID),sort(item.domain.wallBoundaryFaceID))&& ...
    numel(audit.faceID)==115&&~info.physicalSolution&&~info.eligibleForSurfaceCoverage);
defect=sum(rate.*item.mesh.volumePerRadian,1)+info.netBoundaryFlux-info.sourceIntegral;
budget=2048*eps*(sum(abs(rate).*item.mesh.volumePerRadian,1)+ ...
    abs(info.netBoundaryFlux)+abs(info.sourceIntegral));
assert(all(abs(defect)<=budget),'RocketWallCaseTest:Ledger','完整初态五量账不成立。');
report=struct('status','passed-complete-rocket-controlled-static-wall-case-initial-operator', ...
    'cellCount',item.mesh.cellCount,'wallFaces',numel(info.wall.faceID), ...
    'sameGeometryGasInitialQAndInputs',true,'onlyWallMomentumRateChangedAtSameQ',true, ...
    'sameInitialHeatAndSA',true,'wallAndWorkKnobsIndependentAtSameQ',true, ...
    'oldResidualByQuantity',max(abs(oldRate)./old.residualScale,[],1), ...
    'wallResidualByQuantity',max(abs(rate)./item.residualScale,[],1), ...
    'workResidualByQuantity',max(abs(workRate)./work.residualScale,[],1), ...
    'temperatureImprovementProven',false, ...
    'initialOriginalResidual',max(abs(rate)./item.residualScale,[],'all'), ...
    'oldInitialOriginalResidual',max(abs(oldRate)./old.residualScale,[],'all'), ...
    'fiveQuantityConservationDefect',defect,'fiveQuantityRoundoffBudget',budget, ...
    'timeStepsTaken',0,'steadyConverged',false,'physicalSolution',false, ...
    'eligibleForSurfaceCoverage',false,'newProductionSolvedAreaM2',0);
if ~exist(folder,'dir'),mkdir(folder);end
save(fullfile(folder,'rocket_wall_case_evidence.mat'),'item','old','work','both','rate','oldRate','workRate','bothRate', ...
    'info','oldInfo','workInfo','bothInfo','report');
fid=fopen(fullfile(folder,'rocket_wall_case_summary.json'),'w','n','UTF-8');assert(fid>=0);
guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',jsonencode(report));clear guard;
fprintf('Rocket static-wall velocity controlled initial operator passed: %d cells, same Q/geometry/gas/heat/SA; no temperature improvement claim.\n',item.mesh.cellCount);
end
