function report=studyRocketShellAdvance(folder,domainFolder,initialFolder)
%STUDYROCKETSHELLADVANCE 在真实20度三维新域做有界完整NS耦合启动，原正性/账/时间身份保持。
% 模块一：只使用内部均匀来流初猜和完整远场储库，显式选择已校核的墙温切向约束。
% 模块二：真实共享dt SSP-RK2，保存全部三步阶段与边界账；工作上限不算稳态。
% 模块三：温度为定gamma/冻结mu层流模型派生，未认证真实飞行、湍流或近壁精度。
root=fileparts(fileparts(mfilename('fullpath')));addpath(root,fullfile(root,'internalFlow'));setupCutCellFlow;
assert(~exist(folder,'dir'),'RocketShellAdvance:Overwrite','不能覆盖真实启动试验。');mkdir(folder);
d=load(fullfile(domainFolder,'shell_domain_evidence.mat'),'domain','fs');cut=d.domain;
s=load(fullfile(initialFolder,'initial_residual_evidence.mat'),'Q','gas','boundary');boundary=s.boundary;
boundary.solidWall.thermalGradient='dirichlet-tangent';
L=max(cut.inputGeometry.V(:,1))-min(cut.inputGeometry.V(:,1));reference=L/d.fs.speed;
options=struct('targetTime',reference,'maxSteps',3,'maxRetries',6,'saveStageTrace',true, ...
    'conservationTolerance',1e-9,'steadyResidualTolerance',2e-6,'steadyRequiredSteps',5,'minimumSteadySteps',5,'logEvery',1);
t=tic;
try
    result=advanceCutCellNavierStokes(s.Q,cut,s.gas,boundary,options);
catch ex
    report=struct('status','rejected-bounded-actual-three-dimensional-startup','identifier',ex.identifier, ...
        'message',ex.message,'elapsedSeconds',toc(t),'physicalSolution',false,'newProductionSolvedAreaM2',0);
    fid=fopen(fullfile(folder,'advance_failure.json'),'w','n','UTF-8');assert(fid>=0);fprintf(fid,'%s',jsonencode(report));fclose(fid);rethrow(ex);
end
elapsed=toc(t);mapped=mapCutCellWallFields(cut,result.finalSpatialInfo,result.steadyConverged);
assert(result.acceptedSteps==3&&~result.steadyConverged&&~result.completedRequestedTime&& ...
    result.globalBalanceRelative<=1e-9&&result.positivityClippingCount==0&&~mapped.eligibleForSurfaceCoverage);
rho=result.Q(:,1);velocity=result.Q(:,2:4)./rho;cv=s.gas.R/(s.gas.gamma-1);
T=(result.Q(:,5)-.5*rho.*sum(velocity.^2,2))./(rho*cv);
report=struct('status','completed-three-real-shared-RK2-startup-steps-not-steady-or-physical-solution', ...
    'cellCount',size(result.Q,1),'sourceFaces',numel(cut.walls.area),'alphaDeg',20, ...
    'acceptedSteps',result.acceptedSteps,'rejectedAttempts',result.rejectedAttempts,'startupIntegrationTimeSeconds',result.time, ...
    'referenceLoverUSeconds',reference,'fractionOfReferenceConvectiveTime',result.time/reference, ...
    'initialResidualPerSecond',result.initialResidualNorm,'finalResidualPerSecond',result.residualNorm, ...
    'fiveQuantityBalanceRelative',result.globalBalanceRelative,'elapsedSeconds',elapsed, ...
    'diffusionStencilBuilds',result.stencilBuilds,'minDensityKgM3',min(rho),'fluidTemperatureRangeK',[min(T),max(T)], ...
    'wallPressureRangePa',[min(mapped.pressure.value),max(mapped.pressure.value)], ...
    'wallHeatFluxRangeWm2',[min(mapped.heatFluxIntoWall.value),max(mapped.heatFluxIntoWall.value)], ...
    'heatPowerW',mapped.summedKnownHeatPower,'wallTemperatureKind','prescribed', ...
    'startupTimeIsFlightTime',false,'steadyConverged',false,'physicalSolution',false, ...
    'newProductionSolvedAreaM2',0,'engineProcessID',feature('getpid'));
gas=s.gas;save(fullfile(folder,'advance_evidence.mat'),'result','mapped','report','gas','boundary','-v7');
fid=fopen(fullfile(folder,'advance_summary.json'),'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',jsonencode(report));fprintf('%s\n',jsonencode(report));
end
