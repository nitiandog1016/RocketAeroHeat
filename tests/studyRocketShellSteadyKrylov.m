function report=studyRocketShellSteadyKrylov(folder,options,workPolicy)
%STUDYROCKETSHELLSTEADYKRYLOV 从v80真实20度完整三步状态做有界法向线预条件试算。
% 模块一：初态、原域、物性、墙和三分量远场完全保持，不借轴对称解。
% 模块二：只做原稳态空间方程的非线性修正；伪步不算飞行或BE时间。
% 模块三：完整状态/残差/候选日志保存，未收敛不计生产面积。
if nargin<2,options=struct;end
if nargin<3,workPolicy='legacy-wls';end
root=fileparts(fileparts(mfilename('fullpath')));addpath(root,fullfile(root,'internalFlow'));setupCutCellFlow;
assert(~exist(folder,'dir'),'ShellSteadyStudy:Overwrite','不得覆盖实际试算。');mkdir(folder);
base=fullfile(root,'outputs','v80_validation');
if ~exist(fullfile(base,'advance01','advance_evidence.mat'),'file'),base=fullfile(root,'validation','v80');end
d=load(fullfile(base,'domain02','shell_domain_evidence.mat'),'domain');
s=load(fullfile(base,'advance01','advance_evidence.mat'),'result','gas','boundary');
boundary=s.boundary;
if ~strcmp(workPolicy,'legacy-wls'),boundary.viscousWorkVelocity=workPolicy;end
assert(strcmp(cutCellViscousWorkPolicy(boundary),workPolicy),'ShellSteadyStudy:Policy','黏性功策略未被明确接受。');
options.residualScale=s.result.residualScale;
if ~isfield(options,'maximumIterations'),options.maximumIterations=2;end
t=tic;result=solveRocketShellSteadyKrylov(s.result.Q,d.domain,s.gas,boundary,options);elapsed=toc(t);
assert(isequal(result.initialQ,s.result.Q),'ShellSteadyStudy:Source','初始完整状态改变。');
if strcmp(workPolicy,'legacy-wls')
    assert(isequal(result.initialRate,s.result.residual)&&isequaln(result.initialInfo,s.result.finalSpatialInfo), ...
        'ShellSteadyStudy:Source','旧路径初始完整算子身份改变。');
else
    assert(isequal(result.initialRate(:,1:4),s.result.residual(:,1:4))&& ...
        isequal(result.initialInfo.gradient,s.result.finalSpatialInfo.gradient)&& ...
        isequal(result.initialInfo.wallFlux,s.result.finalSpatialInfo.wallFlux)&& ...
        strcmp(result.initialInfo.viscousWorkAudit.policy,workPolicy),'ShellSteadyStudy:Scope','新功策略改变了非能量空间量/边界。');
end
mapped=mapCutCellWallFields(d.domain,result.info,result.steadyConverged);
assert(result.physicalTimeAdvanced==0&&result.BETimeStepsClaimed==0&&~mapped.eligibleForSurfaceCoverage);
report=struct('status','bounded-actual-20deg-original-five-quantity-line-preconditioned-Krylov-study', ...
    'sourceFaces',19752,'cellCount',numel(d.domain.cells.volume),'acceptedNonlinearIterations',result.acceptedNonlinearIterations, ...
    'candidateTrials',result.candidateTrials,'residualEvaluations',result.residualEvaluations,'operatorBuilds',result.operatorBuilds, ...
    'initialMaximumResidual',result.initialMaximumResidual,'maximumResidual',result.maximumResidual, ...
    'initialRmsMerit',result.initialRmsMerit,'rmsMerit',result.rmsMerit,'elapsedSeconds',elapsed, ...
    'matrixVectorProducts',result.matrixVectorProducts,'jacobianResidualEvaluations',result.jacobianResidualEvaluations, ...
    'preconditionerApplications',result.preconditionerApplications,'viscousWorkVelocity',workPolicy, ...
    'steadyConverged',result.steadyConverged,'stopReason',result.stopReason, ...
    'spatialConservationRelative',result.spatialConservationRelative,'steadyBoundaryFluxBalance',result.steadyBoundaryFluxBalance, ...
    'physicalTimeAdvanced',0,'BETimeStepsClaimed',0,'newProductionSolvedAreaM2',0,'physicalSolution',false, ...
    'wallHeatRangeWm2',[min(mapped.heatFluxIntoWall.value),max(mapped.heatFluxIntoWall.value)], ...
    'signedHeatPowerW',mapped.summedKnownHeatPower,'engineProcessID',feature('getpid'));
gas=s.gas;save(fullfile(folder,'steady_krylov_evidence.mat'),'report','result','mapped','gas','boundary','-v7');
fid=fopen(fullfile(folder,'steady_krylov_summary.json'),'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',jsonencode(report));fprintf('%s\n',jsonencode(report));
end
