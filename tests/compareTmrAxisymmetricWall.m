function comparison=compareTmrAxisymmetricWall(folder,evidenceFile,inputs)
%COMPARETMRAXISYMMETRICWALL 当前Sutherland层流稳态与TMR湍流实验的诊断比较。
% 模块一：只读真实证据，核对原2e-6连续3步及当前完整空间逐值重放，不求稳态。
% 模块二：按合同名义20度S到X映射，在40条原jMin墙边取分片常值，不外推。
% 模块三：保留压力原27行但只给24个独立点权重；27热流点保持原signed q。
% 模块四：导出原比值、SI量、来源、缺失mask和偏差；不设置精度通过或实验验收。
% inputs仅供传入真实证据的内存副本作拒绝测试；任何改动仍须通过当前空间重放。
root=fileparts(fileparts(mfilename('fullpath')));
addpath(root,fullfile(root,'tests'),fullfile(root,'regionalFlow','axisymmetric'),fullfile(root,'internalFlow'));
if nargin<1,folder=fullfile(root,'outputs','v64_validation','tmr_wall_comparison');end
if nargin<2
    evidenceFile=fullfile(root,'outputs','v64_validation','tmr_sutherland','tmr_sutherland_evidence.mat');
    if ~exist(evidenceFile,'file')
        evidenceFile=fullfile(root,'validation','v64','tmr_sutherland','tmr_sutherland_evidence.mat');
    end
end
if nargin<3,inputs=struct;end
assert(isstruct(inputs)&&isscalar(inputs)&&all(ismember(fieldnames(inputs), ...
    {'mesh','gas','boundary','implicit','report'})), 'AxisFV:TmrWallInputs','内存输入只允许真实证据的五项字段。');
assert((ischar(evidenceFile)&&isrow(evidenceFile))||(isstring(evidenceFile)&&isscalar(evidenceFile)), ...
    'AxisFV:TmrWallEvidence','证据路径必须为单个文本。');
evidenceFile=char(evidenceFile);
assert(exist(evidenceFile,'file')==2,'AxisFV:TmrWallEvidence', ...
    '需要等待真实Sutherland稳态结果：%s；本比较器不生成占位解或假测点。',evidenceFile);
assert((ischar(folder)&&isrow(folder))||(isstring(folder)&&isscalar(folder)), ...
    'AxisFV:TmrWallInputs','输出目录必须为单个路径。');folder=char(folder);
sourceSHA=fileSHA(evidenceFile);source=load(evidenceFile,'mesh','gas','boundary','implicit','report');
required={'mesh','gas','boundary','implicit','report'};
assert(all(isfield(source,required)),'AxisFV:TmrWallEvidence','真实证据缺少mesh/gas/boundary/implicit/report。');
diskSource=source;
for key=fieldnames(inputs)',source.(key{1})=inputs.(key{1});end

%% 一、冻结数据合同、网格真值及当前原方程；拒绝预算终态和陈旧墙热
b=loadTmrMach7Benchmark;grid=loadTmrMach7Grid(4);mesh=source.mesh;result=source.implicit;boundary=source.boundary;
assert(isstruct(mesh)&&isscalar(mesh)&&isfield(mesh,'kind')&& ...
    strcmp(mesh.kind,'axisymmetric-body-fitted-fv-v1')&&mesh.cellCount==1000&&~mesh.periodicI&& ...
    isequal(mesh.X,grid.X)&&isequal(mesh.R,grid.R), ...
    'AxisFV:TmrWallGeometry','只接受冻结TMR最粗原节点的1000格轴对称网格。');
assert(isequaln(buildAxisymmetricFVGeometry(mesh.X,mesh.R),mesh), ...
    'AxisFV:TmrWallGeometry','当前FV度量/梯度不能从原节点逐值重建。');
names={'Q','gas','geometryBinding','steadyConverged','stopReason','acceptedSteps','residualNorm', ...
    'residualScale','history','options','finalInfo','pseudoTime','pseudoTimeIsPhysical','physicalTimeAdvanced', ...
    'physicalSolution','eligibleForSurfaceCoverage','wallTemperatureValueKind','globalBalanceRelative'};
assert(isstruct(result)&&isscalar(result)&&all(isfield(result,names))&& ...
    isequal(result.steadyConverged,true)&&strcmp(result.stopReason,'steady-residual-converged')&& ...
    isequal(result.physicalSolution,false)&&isequal(result.eligibleForSurfaceCoverage,false)&& ...
    strcmp(result.wallTemperatureValueKind,'prescribed')&&~isfield(result,'time')&& ...
    isequal(result.pseudoTimeIsPhysical,false)&&isequal(result.physicalTimeAdvanced,0), ...
    'AxisFV:TmrWallIdentity','必须是真实稳态层流数值研究；伪时间、给定壁温和物理解身份不可改写。');
assert(isstruct(source.report)&&isscalar(source.report)&&isfield(source.report,'steadyConverged')&& ...
    isequal(source.report.steadyConverged,true)&&~source.report.physicalSolution&& ...
    ~source.report.eligibleForSurfaceCoverage&&~source.report.experimentalValidation&& ...
    source.report.newProductionSolvedAreaM2==0,'AxisFV:TmrWallIdentity','报告身份与真实稳态数值研究不一致。');
assert(all(isfield(result.options,{'steadyResidualTolerance','steadyRequiredSteps','minimumSteadySteps','conservationTolerance'}))&& ...
    result.options.steadyResidualTolerance==2e-6&&result.options.steadyRequiredSteps==3&& ...
    result.acceptedSteps>=max(3,result.options.minimumSteadySteps)&&numel(result.history.residual)>=4&& ...
    isreal(result.history.residual)&&all(isfinite(result.history.residual))&& ...
    isreal(result.residualNorm)&&isscalar(result.residualNorm)&&isfinite(result.residualNorm)&& ...
    result.residualNorm==result.history.residual(end)&&result.residualNorm<=2e-6&& ...
    all(result.history.residual(end-2:end)<=2e-6)&&isfinite(result.globalBalanceRelative)&& ...
    result.globalBalanceRelative<=result.options.conservationTolerance, ...
    'AxisFV:TmrWallConvergence','须保留原2e-6连续3步原残差和四量账，NaN不是通过。');
assert(isreal(result.Q)&&isequal(size(result.Q),[1000 4])&&all(isfinite(result.Q),'all')&& ...
    isreal(result.residualScale)&&all(isfinite(result.residualScale),'all')&&all(result.residualScale>0,'all'), ...
    'AxisFV:TmrWallFinite','状态/残差尺度须有限、尺度须正，不能用NaN或零冒充有效解。');
assert(isequaln(result.geometryBinding,struct('X',mesh.X,'R',mesh.R,'cells',mesh.cells, ...
    'volumePerRadian',mesh.volumePerRadian)), 'AxisFV:TmrWallGeometry','终态几何绑定已改变。');
[gas,transportProvenance]=createTmrAxisymmetricAirGas;
assert(isequaln(axisymmetricFVGas(source.gas),gas)&&isequaln(result.gas,gas), ...
    'AxisFV:TmrWallGas','本比较只接受冻结定比热/Pr/Sutherland层流合同，不能复用旧常输运墙热。');
assert(isstruct(boundary)&&isscalar(boundary)&&all(isfield(boundary,{'iMin','iMax','jMin','jMax'}))&& ...
    strcmp(boundary.jMin.type,'wall')&&isequal(boundary.jMin.velocity,[0 0])&& ...
    isequal(boundary.jMin.temperature,b.contract.geometry.wall_condition.temperature_K), ...
    'AxisFV:TmrWallBoundary','须保留原jMin静止、给定311K等温墙。');
for key={'iMin','iMax','jMax'}
    entry=boundary.(key{1});
    assert(strcmp(entry.type,'riemannReservoir')&&isnumeric(entry.primitive)&&isreal(entry.primitive)&& ...
        isequal(size(entry.primitive),[1 4])&&all(isfinite(entry.primitive)), ...
        'AxisFV:TmrWallBoundary','三条开放边须显式保留四量HLLE储库，不能冒充测得剖面或外推出口。');
end
assert(isequaln(axisymmetricFVState(result.Q,gas),result.finalInfo.primitive), ...
    'AxisFV:TmrWallReplay','当前Q与EOS原语量不一致。');
[rate,info]=axisymmetricNavierStokesResidual(result.Q,mesh,gas,boundary);
assert(isequaln(info,result.finalInfo)&& ...
    isequal(rate,(-mesh.incidence*info.faceFluxIntegralPerRadian+info.cellSourceIntegral)./mesh.volumePerRadian)&& ...
    max(abs(rate)./result.residualScale,[],'all')==result.residualNorm, ...
    'AxisFV:TmrWallReplay','当前完整空间算子不能逐值重放壁面p/q、边界及原残差。');
w=info.wall;
assert(all(isfield(w,{'faceID','ownerCell','pressure','heatFluxIntoWall','centroid','normal', ...
    'areaPerRadian','temperatureInput','viscosity','thermalConductivity'}))&& ...
    numel(w.faceID)==40&&numel(unique(w.faceID))==40&& ...
    isequal(sort(w.faceID),find(mesh.faces.boundarySide==3))&& ...
    isequal(w.ownerCell,mesh.faces.owner(w.faceID))&& ...
    isreal(w.pressure)&&all(isfinite(w.pressure))&&all(w.pressure>0)&& ...
    isreal(w.heatFluxIntoWall)&&all(isfinite(w.heatFluxIntoWall)), ...
    'AxisFV:TmrWallFinite','必须使用完整40条jMin原墙面的有限压力和有符号墙热。');
wallTransport=axisymmetricFVTransport(w.temperatureInput,gas);
assert(isequaln(w.viscosity,wallTransport.mu)&&isequaln(w.thermalConductivity,wallTransport.k), ...
    'AxisFV:TmrWallGas','墙面输运系数须在给定Tw处重新求值。');
x=mesh.X(:,1);r=mesh.R(:,1);dx=diff(x);dr=diff(r);L=hypot(dx,dr);
assert(all(dx<0),'AxisFV:TmrWallGeometry','原壁节点必须沿流向X递减。');
expectedCentroid=([x(1:end-1),r(1:end-1)].*(2*r(1:end-1)+r(2:end))+ ...
    [x(2:end),r(2:end)].*(r(1:end-1)+2*r(2:end)))./(3*(r(1:end-1)+r(2:end)));
segmentToWallIndex=nan(40,1);tolerance=2048*eps(max(abs([x;r])));
for j=1:40
    match=find(abs((r(1:end-1)+r(2:end)).*L/2-w.areaPerRadian(j))<=tolerance& ...
        vecnorm(expectedCentroid-w.centroid(j,:),2,2)<=tolerance);
    assert(isscalar(match)&&isnan(segmentToWallIndex(match)), ...
        'AxisFV:TmrWallGeometry','源face/owner不能唯一绑定原jMin节点区间。');segmentToWallIndex(match)=j;
end
assert(all(isfinite(segmentToWallIndex)),'AxisFV:TmrWallGeometry','40条真实墙边必须完整映射。');

%% 二、实验S按名义20度转X；场值按原面分片常值，不插值、不外推、不取绝对值
p=makePoints(b.pressure.S_m,b.pressure.projectX_m,b.pressure.radius_m,b.pressure.ratio, ...
    b.pressure.pressure_Pa,b.pressure.independentComparisonPoint);
p.experimentalPressurePa=p.experimentalDimensionalValue;p=rmfield(p,'experimentalDimensionalValue');
p.computedPressurePa=sample(w.pressure,p.sourceWallIndex);p.computedRatio=p.computedPressurePa/576;
p.differencePa=p.computedPressurePa-p.experimentalPressurePa;
p.ratioDifference=p.computedRatio-p.experimentalRatio;p.relativeDifference=p.differencePa./p.experimentalPressurePa;
p.experimentalEstimatedLowerPa=.9*p.experimentalPressurePa;p.experimentalEstimatedUpperPa=1.1*p.experimentalPressurePa;
q=makePoints(b.heating.S_m,b.heating.projectX_m,b.heating.radius_m,b.heating.ratio, ...
    b.heating.reportedMagnitude_W_m2,true(27,1));
q.experimentalReportedHeatingMagnitudeWm2=q.experimentalDimensionalValue;q=rmfield(q,'experimentalDimensionalValue');
q.computedSignedHeatFluxIntoWallWm2=sample(w.heatFluxIntoWall,q.sourceWallIndex);
q.computedSignedRatio=q.computedSignedHeatFluxIntoWallWm2/9300;
q.signedMinusReportedMagnitudeWm2=q.computedSignedHeatFluxIntoWallWm2-q.experimentalReportedHeatingMagnitudeWm2;
q.signedMinusReportedRatio=q.computedSignedRatio-q.experimentalRatio;
q.signedRelativeDifference=q.signedMinusReportedMagnitudeWm2./q.experimentalReportedHeatingMagnitudeWm2;
q.positiveHeatingMagnitudeAvailable=~q.missingMask&q.computedSignedHeatFluxIntoWallWm2>=0;
q.computedPositiveHeatingMagnitudeWm2=q.computedSignedHeatFluxIntoWallWm2;
q.computedPositiveHeatingMagnitudeWm2(~q.positiveHeatingMagnitudeAvailable)=NaN;
q.positiveHeatingMinusReportedMagnitudeWm2=q.computedPositiveHeatingMagnitudeWm2-q.experimentalReportedHeatingMagnitudeWm2;
q.positiveHeatingRelativeDifference=q.positiveHeatingMinusReportedMagnitudeWm2./q.experimentalReportedHeatingMagnitudeWm2;
q.experimentalEstimatedLowerWm2=.9*q.experimentalReportedHeatingMagnitudeWm2;
q.experimentalEstimatedUpperWm2=1.1*q.experimentalReportedHeatingMagnitudeWm2;
pt=struct2table(p);qt=struct2table(q);
summary=struct('pressure',statistics(p.relativeDifference,p.independentComparisonPoint&~p.missingMask), ...
    'heatSignedVersusReportedPositiveMagnitude',statistics(q.signedRelativeDifference,~q.missingMask), ...
    'heatPositiveHeatingMagnitudeOnly',statistics(q.positiveHeatingRelativeDifference,q.positiveHeatingMagnitudeAvailable), ...
    'rawPressureRows',27,'independentPressurePoints',24,'excludedDuplicatePressureSourceRows',[25;26;27], ...
    'rawHeatingRows',27,'pressureMissingSourceRows',p.sourceRow(p.missingMask), ...
    'heatingMissingSourceRows',q.sourceRow(q.missingMask), ...
    'negativeComputedHeatSourceRows',q.sourceRow(~q.missingMask&q.computedSignedHeatFluxIntoWallWm2<0));
reservoir=boundary.iMin.primitive;tr=axisymmetricFVTransport(reservoir(4),gas);
inletMach=norm(reservoir(2:3))/sqrt(gas.gamma*gas.R*reservoir(4));inletRe=reservoir(1)*norm(reservoir(2:3))/tr.mu;
angles=atand(-dr(abs(dr)>tolerance)./dx(abs(dr)>tolerance));
model=struct('gas',gas,'transportProvenance',transportProvenance,'boundaryInput',boundary, ...
    'caloricIdentity','calorically perfect gamma=1.4, R=287.05, constant cp; not NASA7', ...
    'conductivityIdentity','k(T)=cp*mu(T)/Pr, Pr=0.72; no independent conductivity fit', ...
    'flowIdentity','axisymmetric no-swirl laminar NS; turbulent experiment and incoming turbulence are not modelled', ...
    'openBoundaryIdentity','explicit four-primitive HLLE riemannReservoir on iMin/iMax/jMax; not source NMF extrapolation outlet', ...
    'inletMach',inletMach,'inletStaticTemperatureK',reservoir(4),'inletPressurePa',reservoir(1)*gas.R*reservoir(4), ...
    'inletTotalTemperatureK',reservoir(4)+norm(reservoir(2:3))^2/(2*gas.cp), ...
    'inletTotalPressurePa',reservoir(1)*gas.R*reservoir(4)*(1+(gas.gamma-1)*inletMach^2/2)^(gas.gamma/(gas.gamma-1)), ...
    'derivedInletRePerM',inletRe,'diagramRoundedInletRePerM',5.706e6,'relativeInletReDifference',inletRe/5.706e6-1, ...
    'experimentalLocalReference',b.contract.experimental_local_reference, ...
    'computationalTruncatedInflowContract',b.contract.computational_truncated_inflow, ...
    'nominalFlareAngleDeg',20,'actualOriginalGridFlareAnglesDeg',angles, ...
    'actualMinusNominalAngleDeg',angles-20,'originalWallXRangeM',[x(end) x(1)], ...
    'originalNodesPreserved',true,'incomingTurbulenceProfiles',[], ...
    'upstreamProfileAgreementVerified',false,'gridAndDomainSensitivityVerified',false);
wall=struct('segment',(1:40)','sourceWallIndex',segmentToWallIndex,'faceID',w.faceID(segmentToWallIndex), ...
    'ownerCell',w.ownerCell(segmentToWallIndex),'upstreamXM',x(1:end-1),'downstreamXM',x(2:end), ...
    'upstreamRadiusM',r(1:end-1),'downstreamRadiusM',r(2:end), ...
    'pressurePa',w.pressure(segmentToWallIndex),'signedHeatFluxIntoWallWm2',w.heatFluxIntoWall(segmentToWallIndex), ...
    'temperatureInputK',w.temperatureInput(segmentToWallIndex),'viscosityPaS',w.viscosity(segmentToWallIndex), ...
    'conductivityWmK',w.thermalConductivity(segmentToWallIndex));
comparison=struct('schema','RocketAeroHeat.tmr-wall-diagnostic.v1', ...
    'status','diagnostic-laminar-vs-turbulent-experiment-mismatches', ...
    'evidenceFile',evidenceFile,'evidenceSHA256',sourceSHA,'sourceSnapshotMatchesEvidenceFile',isequaln(source,diskSource), ...
    'inputOverrideFields',{fieldnames(inputs)},'sourceReport',source.report,'sourceBindings',currentBindings(root), ...
    'contractFile',fullfile(root,'tests','data','tmr_mach7','contract.json'), ...
    'contractSHA256',fileSHA(fullfile(root,'tests','data','tmr_mach7','contract.json')), ...
    'sourceManifestSHA256',b.contract.source_manifest_sha256,'gridSource',grid.source, ...
    'sourceHashesVerified',true,'currentSpatialResidualReplayPassed',true,'diagnosticResidualEvaluations',1, ...
    'steadyConverged',true,'originalResidualNorm',result.residualNorm,'steadyTolerance',2e-6,'steadyRequiredSteps',3, ...
    'lastThreeOriginalResiduals',result.history.residual(end-2:end),'pseudoTimeIsPhysical',false,'physicalTimeAdvancedS',0, ...
    'pressureNormalizationPa',576,'heatNormalizationReportedMagnitudeWm2',9300, ...
    'samplePolicy','piecewise constant original jMin face value; Xdownstream < X <= Xupstream; final outlet endpoint included; no extrapolation', ...
    'coordinatePolicy','contract nominal S<0: X=-S; S>=0: X=-S*cosd(20); original grid is not adjusted to nominal angle', ...
    'pressureValueIdentity',['current owner-cell EOS pressure trace; ' info.method], ...
    'computedHeatValueIdentity',['signed q=-k(Tw)*grad(T) dot n_fluid; positive enters wall; original value without abs or scaling; ' info.method], ...
    'experimentalHeatValueIdentity','reported positive heating magnitude; raw positive ratios do not establish a solver-normal signed Fourier conversion', ...
    'positiveHeatingIdentity','only computed signed q>=0 is reported as positive heating magnitude; cooling remains signed and magnitude comparison is missing', ...
    'uncertainty',struct('relativeSurfacePressureEstimate',.1,'relativeSurfaceHeatEstimate',.1, ...
        'confidenceLevel',[],'pointCovariance',[],'isStatisticalConfidenceInterval',false, ...
        'ratioUncertaintyIndependenceAssumed',false,'identity','reported experimental +/-10 percent estimate; descriptive interval only'), ...
    'pressure',table2struct(pt),'heating',table2struct(qt),'summary',summary,'modelDifferences',model,'originalWall',wall, ...
    'physicalSolution',false,'eligibleForSurfaceCoverage',false,'experimentalValidation',false, ...
    'newProductionSolvedAreaM2',0);
assert(strcmp(sourceSHA,fileSHA(evidenceFile)),'AxisFV:TmrWallEvidence','读取期间真实证据字节发生改变。');

%% 三、全部检查通过后才写出；未解点在MAT/CSV为NaN、JSON为null并保留显式mask
if ~exist(folder,'dir'),mkdir(folder);end
comparison.files=struct('pressureCSV',fullfile(folder,'tmr_pressure_comparison.csv'), ...
    'heatingCSV',fullfile(folder,'tmr_heating_comparison.csv'),'wallCSV',fullfile(folder,'tmr_original_wall.csv'), ...
    'summaryCSV',fullfile(folder,'tmr_wall_comparison_summary.csv'), ...
    'json',fullfile(folder,'tmr_wall_comparison.json'),'mat',fullfile(folder,'tmr_wall_comparison.mat'));
writetable(pt,comparison.files.pressureCSV);writetable(qt,comparison.files.heatingCSV);
writetable(struct2table(wall),comparison.files.wallCSV);
summaryNames={'pressure-independent-points';'heat-signed-versus-reported-positive';'heat-positive-heating-only'};
summaryRows=[summary.pressure;summary.heatSignedVersusReportedPositiveMagnitude;summary.heatPositiveHeatingMagnitudeOnly];
summaryTable=struct2table(summaryRows);summaryTable.variable=summaryNames;writetable(summaryTable,comparison.files.summaryCSV);
writeText(comparison.files.json,jsonencode(comparison,'ConvertInfAndNaN',true));
save(comparison.files.mat,'comparison','pt','qt','wall','model','summary','summaryTable');
fprintf('TMR diagnostic comparison: pressure %d independent / 27 raw, heat 27; missing p=%d q=%d; no experimental-validation claim.\n', ...
    summary.independentPressurePoints,nnz(p.missingMask),nnz(q.missingMask));

    function points=makePoints(S,X,radius,ratio,dimensional,independent)
        % 模块用途：名义坐标只用于定位原区间；几何半径插值不用于p/q场插值。
        n=numel(S);segment=nan(n,1);index=nan(n,1);actualRadius=nan(n,1);
        for k=1:n
            j=find(X(k)<=x(1:end-1)&X(k)>x(2:end));
            if isempty(j)&&X(k)==x(end),j=40;end
            assert(numel(j)<=1,'AxisFV:TmrWallSampling','一个测点落入多个原墙区间。');
            if isempty(j),continue;end
            segment(k)=j;index(k)=segmentToWallIndex(j);
            actualRadius(k)=r(j)+(X(k)-x(j))/dx(j)*dr(j);
        end
        points=struct('sourceRow',(1:n)','independentComparisonPoint',logical(independent), ...
            'S_m',S,'sourceX_m',-X,'projectX_m',X,'nominalRadiusM',radius, ...
            'actualGridRadiusAtXM',actualRadius,'gridMinusNominalRadiusM',actualRadius-radius, ...
            'experimentalRatio',ratio,'experimentalDimensionalValue',dimensional, ...
            'missingMask',isnan(index),'sourceSegment',segment,'sourceWallIndex',index, ...
            'faceID',sample(w.faceID,index),'ownerCell',sample(w.ownerCell,index), ...
            'faceUpstreamXM',sample(x(1:end-1),segment),'faceDownstreamXM',sample(x(2:end),segment));
    end
end

function sampled=sample(values,index)
% 模块用途：只映射真实存在的原数组条目；未覆盖位置保留NaN。
sampled=nan(size(index));valid=isfinite(index);sampled(valid)=values(index(valid));
end
function summary=statistics(relativeDifference,mask)
% 模块用途：只汇总独立且有值测点的描述性偏差，不作精度通过或统计置信推断。
value=relativeDifference(mask);assert(all(isfinite(value)),'AxisFV:TmrWallFinite','汇总样本含NaN或Inf。');
summary=struct('comparedPointCount',numel(value),'meanRelativeDifference',NaN, ...
    'meanAbsoluteRelativeDifference',NaN,'rootMeanSquareRelativeDifference',NaN,'maximumAbsoluteRelativeDifference',NaN);
if isempty(value),return;end
summary.meanRelativeDifference=mean(value);summary.meanAbsoluteRelativeDifference=mean(abs(value));
summary.rootMeanSquareRelativeDifference=sqrt(mean(value.^2));summary.maximumAbsoluteRelativeDifference=max(abs(value));
end
function writeText(path,value)
% 模块用途：以UTF-8保存可追溯的诊断结果，输出失败不能冒充完成。
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'AxisFV:TmrWallWrite','无法写出比较结果。');cleanup=onCleanup(@()fclose(fid));
assert(fprintf(fid,'%s',value)>=0,'AxisFV:TmrWallWrite','比较结果写出失败。');
end
function out=currentBindings(root)
% 模块用途：锁定当前比较、合同、原空间算子和热物性源码，不改冻结v63包。
paths={'tests/compareTmrAxisymmetricWall.m','tests/loadTmrMach7Benchmark.m', ...
    'regionalFlow/axisymmetric/loadTmrMach7Grid.m','regionalFlow/axisymmetric/axisymmetricNavierStokesResidual.m', ...
    'regionalFlow/axisymmetric/axisymmetricFVGas.m','regionalFlow/axisymmetric/axisymmetricFVState.m', ...
    'regionalFlow/axisymmetric/axisymmetricFVTransport.m','regionalFlow/axisymmetric/axisymmetricFVTemperatureTrace.m', ...
    'regionalFlow/axisymmetric/createTmrAxisymmetricAirGas.m','regionalFlow/axisymmetric/buildAxisymmetricFVGeometry.m'};
out=struct('path',{},'sha256',{});
for j=1:numel(paths),out(end+1)=struct('path',paths{j},'sha256',fileSHA(fullfile(root,paths{j})));end %#ok<AGROW>
end
function digest=fileSHA(path)
% 模块用途：核对文件真实字节；SHA只证明来源身份，不证明物理精度。
fid=fopen(path,'rb');assert(fid>=0,'AxisFV:TmrWallEvidence','无法读取来源文件：%s',path);
cleanup=onCleanup(@()fclose(fid));bytes=fread(fid,Inf,'*uint8');clear cleanup;
md=java.security.MessageDigest.getInstance('SHA-256');md.update(bytes);
digest=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
