function [current,fs,report]=runPhaseAwareNoseHeatingCase(mesh,cfg,progressFcn)
%RUNPHASEAWARENOSEHEATINGCASE 主工况的相态鼻部热流入口及来源一致缓存。
% 模块用途：新工况由内部外缘生产器求解；显式复用时核对当前工况与原面。
if nargin<3,progressFcn=[];end
started=tic;
reuse=isfield(cfg,'reusePhaseAwareNoseEdge')&&isequal(cfg.reusePhaseAwareNoseEdge,true);
if reuse
    assert(isfield(mesh,'phaseAwareNoseEdge'),'RAH:PhaseNoseHeat:Cache','缺少待复用外缘。');
    e=mesh.phaseAwareNoseEdge;old=calcFreestream(cfg.flight);
    assert(abs(old.Mach-e.condition.Mach)<1e-12&&abs(old.pressure/e.condition.pressurePa-1)<1e-12 ...
        &&abs(old.temperature/e.condition.temperatureK-1)<1e-12 ...
        &&max(abs(old.unitFlowDirection(:)-e.condition.flowDirection(:)))<1e-12, ...
        'RAH:PhaseNoseHeat:Condition','当前工况与保存外缘不同，禁止复用。');
    current=mesh;air=phaseAwareAirState('PT',old.pressure,old.temperature,'linearTable');
    fs=struct('Mach',old.Mach,'alpha',old.alpha,'beta',old.beta,'altitude',old.altitude, ...
        'pressure',old.pressure,'temperature',old.temperature,'unitFlowDirection',old.unitFlowDirection, ...
        'speed',old.Mach*air.soundSpeedMps,'density',air.densityKgm3,'model',air.model, ...
        'transportModel',air.transportModel,'energyReference',air.energyReference);
    stale={'pressure','externalFlow','boundaryLayerEdge','axisymmetricMarch','surfaceStreamlines','stagnation', ...
        'stagnationShock','bowShockPreview','boundaryLayer','heating','heatingCoverage','stagnationHeating', ...
        'aerodynamicLoads','phaseAwareLaminar','phaseAwareEdge','wallThermal','flightHeatingHistory', ...
        'aerothermalExposure','aerothermalRegion','continuumRegime'};
    for name=stale,if isfield(current,name{1}),current=rmfield(current,name{1});end,end
else
    [current,fs]=runPhaseAwareNoseCase(mesh,cfg,[]);e=current.phaseAwareNoseEdge;
end
Tw=surfaceWallTemperature(size(mesh.F,1),cfg);
h=solvePhaseAwareNoseHeating(current,e,Tw);current.phaseAwareNoseHeating=h;
current.phaseAwareWallTemperature=Tw;current.aerothermalResultMode='phaseAwareNoseHeating';
report=struct('status','completed-region-heat-candidate','faceCount',size(mesh.F,1), ...
    'totalArea',h.summary.totalAreaM2,'heatComputedAreaFraction',h.summary.heatCandidateAreaFraction, ...
    'heatComputedAreaM2',h.summary.heatCandidateAreaM2,'signedHeatPowerW',h.summary.signedPowerW, ...
    'physicalQualification',false,'loadsAvailable',false,'edgeSnapshotReused',reuse,'elapsedSeconds',toc(started), ...
    'scope',h.scope);
if ~isempty(progressFcn)
    progressFcn(struct('phase','heating','status','completed','fraction',1, ...
        'message','鼻部热候选已完成；未解区域保持原面积责任','elapsedSeconds',toc(started), ...
        'errorIdentifier','','errorMessage',''));
end
end
