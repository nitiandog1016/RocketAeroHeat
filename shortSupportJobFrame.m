function frame=shortSupportJobFrame(folder,binding,boundary)
% 模块一：只读已完成任务的回执、时间层与两种步长，绑定本次几何和实际源帧。
ackFile=fullfile(folder,'completed.json');pairFile=fullfile(folder,'export','pair.json');
assert(isfile(ackFile) && isfile(pairFile),'RAH:Short:Incomplete','所选目录还没有完成回执和两套时间层。');
seal=cm011FileSHA256(ackFile);ack=jsondecode(fileread(ackFile));
assert(strcmp(cm011FileSHA256(pairFile),ack.pairSHA256),'RAH:Short:Job','时间层清单与完成回执不符。');
p=jsondecode(fileread(pairFile));branch=boundary.branch;
assert(strcmp(p.schema,'short65-supported-time-pair-v1') && ...
    strcmp(p.caseSHA256,boundary.caseSHA256) && strcmp(p.meshSHA256,binding.meshSHA256) && ...
    strcmp(p.bodySHA256,binding.bodySHA256) && strcmp(p.transferSHA256,binding.transferSHA256) && ...
    p.faces==size(binding.referenceFaceID,1) && ack.faces==p.faces && p.elapsedS==boundary.elapsedS && ...
    strcmp(p.fullFrame,ack.fullFrame) && strcmp(p.halfFrame,ack.halfFrame) && ...
    strcmp(p.fullEnergy.old,p.seed) && strcmp(p.firstHalfEnergy.old,p.seed) && strcmp(p.halfEnergy.old,p.firstHalfFrame) && ...
    p.fullEnergy.elapsedS==p.halfEnergy.elapsedS && p.fullEnergy.dt==2*p.halfEnergy.dt, ...
    'RAH:Short:Job','任务的面网、温界或物理时间与当前工况不符。');
% 两个步长共用同一完成回执。即使只看其中一步，也要核对两套面表是否完整。
for name={'full','half'}
    key=name{1};archive=fullfile(folder,'export',key,'surface.zip');
    assert(isfile(archive) && strcmp(cm011FileSHA256(archive),p.([key 'Archive'])), ...
        'RAH:Short:Job','%s 的面表缺失或与完成回执不符。',key);
end
% 模块二：新安装的初帧取自本次合格基流，随任务保存来源；旧任务核对发布的冻结初场。
if isfield(ack,'constructionSHA256')
    file=fullfile(folder,'construction.json');
    assert(isfile(file) && strcmp(cm011FileSHA256(file),ack.constructionSHA256),'RAH:Short:Job','初场构造记录已改变。');
    c=jsondecode(fileread(file));
    assert(strcmp(c.schema,'short65-cold-start-v1') && strcmp(c.meshSHA256,binding.meshSHA256) && ...
        strcmp(c.caseSHA256,p.caseSHA256) && strcmp(c.transferSHA256,p.transferSHA256) && ...
        strcmp(c.steadyFrame,p.steadyFrame) && strcmp(c.seed,p.seed) && ...
        strcmp(c.coldSHA256,'82eb4bee259a454cbfaf3a3728b396cf30a92456b636a3a245c1f0f5f0e084c0'), ...
        'RAH:Short:Job','生成的冷态、基流或初始扰动与实际任务不符。');
else
    assert(strcmp(p.seed,boundary.initialFrame),'RAH:Short:Job','历史任务的初帧与冻结工况不符。');
end
assert(strcmp(cm011FileSHA256(ackFile),seal),'RAH:Short:Job','读取期间完成回执已改变。');
frame=struct('initial',p.seed,'steady',p.steadyFrame,'terminal',p.([branch 'Frame']),'receipt',seal);
end
