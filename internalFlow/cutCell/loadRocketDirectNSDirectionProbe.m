function [direction,report]=loadRocketDirectNSDirectionProbe(config,Q,cut,gas,boundary,scale)
%LOADROCKETDIRECTNSDIRECTIONPROBE 读取同Q/同边界原NS探针，不依赖或伪造旧粗层像。
% 模块一：原始基态文件和独立完整几何绑定；验证15项空间算子来源。
% 模块二：从保存原NS差分率重算原分母缺陷和下降界，原0.1与温域保持。
% 模块三：仅返回候选方向，主求解器仍重新调用原NS，不继承探针的接受资格。
s=load(config.file);required={'Q','baseRate','scale','gas','boundary','directionU','nsEvidence','report','sourceBinding','geometryBinding','sourceIdentity'};
assert(all(isfield(s,required))&&isequaln(s.Q,Q)&&isequaln(s.scale,scale)&&isequaln(s.gas,gas)&&isequaln(s.boundary,boundary), ...
    'SteadyGuess:DirectState','原NS探针不是当前同Q、尺度、物性或边界。');
assert(isequaln(s.sourceIdentity,rocketNSProbeSourceIdentity)&&s.report.originalNSDirectionTargetMet&& ...
    s.report.originalNSDirectionTarget==.1&&~s.report.physicalStateChanged&&s.report.newFlowAcceptances==0, ...
    'SteadyGuess:DirectSource','原NS探针来源或未接受身份不符。');
assert(isfile(s.sourceBinding.file)&&strcmp(rocketStreamingFileSHA256(s.sourceBinding.file),s.sourceBinding.sha256), ...
    'SteadyGuess:DirectSource','基态来源SHA不符。');
stateLocation='root';if isfield(s.sourceBinding,'stateLocation'),stateLocation=s.sourceBinding.stateLocation;end
b=readRocketNSProbeBase(s.sourceBinding.file,stateLocation);
assert(isequaln(b.Q,Q)&&isequaln(b.rate,s.baseRate)&&isequaln(b.gas,gas)&&isequaln(b.boundary,boundary), ...
    'SteadyGuess:DirectSource','探针基态没有复现实际NS来源。');clear b;
g=s.geometryBinding;assert(isfile(g.file)&&ismember(g.variable,{'cut','domain'})&&strcmp(rocketStreamingFileSHA256(g.file),g.sha256), ...
    'SteadyGuess:DirectGeometry','完整几何来源非法或SHA不符。');
d=load(g.file,g.variable);assert(isequaln(d.(g.variable),cut),'SteadyGuess:DirectGeometry','原NS探针的完整几何不符。');clear d;
e=s.nsEvidence;
assert(isequal(size(s.directionU),size(Q))&&all(isfinite(s.directionU),'all')&&isequaln(e.directionU,s.directionU)&& ...
    e.fullThreeDimensionalResidualCalled&&ismember(e.scheme,{'forward','central'})&&isfinite(e.actualScalarStep)&&e.actualScalarStep>0, ...
    'SteadyGuess:DirectDirection','保存原NS方向或实际差分身份不符。');
if strcmp(e.scheme,'forward'),assert(isequaln(e.rateMinusOrBase,s.baseRate),'SteadyGuess:DirectRates','原NS前向基态率不符。');end
rhs=s.baseRate./scale;jv=(e.ratePlus-e.rateMinusOrBase)./scale/e.actualScalarStep;
if strcmp(e.scheme,'central'),jv=jv/2;end
assert(isequal(size(jv),size(Q))&&all(isfinite(jv),'all')&&norm(jv-e.value,'fro')/max(1,norm(jv,'fro'))<1e-12, ...
    'SteadyGuess:DirectRates','原NS差分值不符。');
defect=norm(rhs+jv,'fro')/norm(rhs,'fro');slope=dot(rhs(:),jv(:))/dot(rhs(:),rhs(:));
assert(defect<=.1&&abs(defect-s.report.originalNSDirectionDefect)<1e-12&&slope<0&&slope<=-1+defect+512*eps, ...
    'SteadyGuess:DirectQualification','原NS探针没有达到原分母线性/下降门槛。');
check(Q+e.actualScalarStep*s.directionU.*scale);if strcmp(e.scheme,'central'),check(Q-e.actualScalarStep*s.directionU.*scale);end
direction=config.scale*s.directionU;assert(all(isfinite(direction),'all'),'SteadyGuess:DirectDirection','方向缩放非有限。');
report=struct('sourceFile',config.file,'sourceVariant',config.variant,'directionScale',config.scale,'sourceFileSHA256',rocketStreamingFileSHA256(config.file), ...
    'sourceGeometryFile',g.file,'sourceGeometryFileSHA256',g.sha256,'sourceStateAndGeometryVerified',true, ...
    'sourceSavedActualNSRelativeDefect',defect,'originalNSProbeArithmeticVerified',true,'oldDerivativeReused',false, ...
    'originalNSAcceptanceClaimed',false,'newModelApplications',0,'newActualNSEvaluations',0,'coarseImageRequired',false, ...
    'sourceStateLocation',stateLocation);
    function check(q)
        rho=q(:,1);energy=q(:,5)-.5*sum(q(:,2:4).^2,2)./rho;T=energy./(rho*gas.R/(gas.gamma-1));
        assert(all(isfinite(q),'all')&&all(rho>0)&&all(energy>0)&&all(T>=80&T<=2000), ...
            'SteadyGuess:DirectState','原NS扰动正性或80—2000K温域不符。');
    end
end
