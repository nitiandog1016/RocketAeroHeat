function [gradient,audit]=cutCellWallVelocityGradient(cellCenter,wallCenter,normal,Ucell,Uwall,boundary,wallID)
%CUTCELLWALLVELOCITYGRADIENT 草稿：由静止壁零切向导数及真实正法向距构造三维速度梯度。
% 模块一：三个笛卡尔速度分量分别满足壁面切向导数为0，不以单条斜位移代替全部约束。
% 模块二：G=(Uw-Uc)外积n/dn，矩阵行是速度分量、列是空间方向；不裁梯度或状态。
% 模块三：记录给定值、几何、点代理身份与精确线性owner导数，不授予物理或面积资格。
% 本草稿须先完成仿射/旋转/拒绝/默认兼容，再接真实完整NS；不属于v82交付库。
assert(strcmp(cutCellWallVelocityPolicy(boundary),'dirichlet-tangent'));
N=size(Ucell,1);wallID=wallID(:);
assert(N>0&&isequal(size(cellCenter),[N 3])&&isequal(size(wallCenter),[N 3])&& ...
    isequal(size(normal),[N 3])&&isequal(size(Ucell),[N 3])&&isequal(size(Uwall),[N 3])&& ...
    all(cellfun(@isnumeric,{cellCenter,wallCenter,normal,Ucell,Uwall}))&& ...
    isreal([cellCenter,wallCenter,normal,Ucell,Uwall])&& ...
    all(isfinite([cellCenter,wallCenter,normal,Ucell,Uwall]),'all'), ...
    'CutNS:WallVelocityState','需要完整有限的三维真实几何和速度。');
assert(numel(wallID)==N&&isnumeric(wallID)&&isreal(wallID)&&all(isfinite(wallID))&& ...
    all(wallID>=1&wallID==fix(wallID))&&numel(unique(wallID))==N&& ...
    all(abs(sum(normal.^2,2)-1)<1e-10),'CutNS:WallVelocityGeometry','真实墙ID或单位法向非法。');
assert(all(Uwall==0,'all'),'CutNS:WallVelocityBoundary','传入实际墙速与常数静止边界不一致。');
delta=wallCenter-cellCenter;dn=sum(delta.*normal,2);
assert(all(isfinite(dn)&dn>0),'CutNS:WallVelocityGeometry','真实法向墙距必须为正，不加epsilon。');
gn=(Uwall-Ucell)./dn;gradient=zeros(3,3,N);
for component=1:3
    gradient(component,:,:)=reshape((gn(:,component).*normal)',1,3,N);
end
assert(all(isfinite(gradient),'all'),'CutNS:WallVelocityState','约束速度梯度非有限，不裁剪。');
audit=struct('kind','explicit-three-dimensional-static-Dirichlet-tangent-wall-velocity-gradient', ...
    'policy','dirichlet-tangent','wallID',wallID,'normal',normal,'delta',delta,'normalDistanceM',dn, ...
    'cellVelocityProxyXYZ',Ucell,'wallVelocityInputXYZ',Uwall,'normalGradientPerS',gn, ...
    'gradientXYZ',gradient,'ownerVelocityDerivativeXYZ',-normal./dn, ...
    'prescribedTangentialDerivative',0,'cellStateClipped',false,'physicalValidation',false, ...
    'wallValueKind','prescribed-static-Dirichlet-input', ...
    'tangentDerivativeSource','exact derivative of prescribed constant Cartesian zero wall velocity', ...
    'cellVelocityMeaning','conservative-mean-derived velocity as a point proxy; not an exact FV mean velocity');
end
