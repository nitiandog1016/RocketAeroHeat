function [coarse,report]=loadRocketLocalCoarseOperator(filename,cache,space,primitiveSpace,selected,columns,maximumImageBytes)
%LOADROCKETLOCALCOARSEOPERATOR 显式验证局部像、原CV身份、逐列提升及当前完整作用。
% 模块一：外层与嵌套提升必须属于同Q/空间/边界物性，不能复用旧状态数值。
% 模块二：完整小Gram/因子、原面/层、单位像及预算分别核对，再执行新模型探针。
n=size(cache.Q,1);nc=5*space.groupCount;np=numel(selected);
columns=validateRocketLocalCoarseColumns(columns,n,nc,np);
assert(ischar(filename)&&isfile(filename),'LocalCoarse:File','局部像来源不存在。');s=load(filename,'coarse');assert(isfield(s,'coarse'),'LocalCoarse:File','局部像文件缺少coarse。');coarse=s.coarse;
assert(strcmp(coarse.kind,'local-conservative-enriched-mixed-fine-L2-minimum-residual-coarse-correction')&& ...
    isequaln(coarse.baseQ,cache.Q)&&isequaln(coarse.space,space)&&isequaln(coarse.gas,cache.gas)&& ...
    isequaln(coarse.boundary,cache.boundary)&&isequaln(coarse.scale,cache.scale)&&coarse.baseConservativeColumns==nc, ...
    'LocalCoarse:Cache','局部像不属于当前Q/空间/边界物性。');
assert(isequaln(coarse.sourceIdentity,rocketSelectedDirectionSourceIdentity)&&isequaln(coarse.liftSourceIdentity,rocketLocalCoarseLiftIdentity), ...
    'LocalCoarse:Source','原完整作用或逐列提升来源已改变。');
actualColumns=struct('retainedMixedColumns',coarse.retainedMixedColumns,'cellIDs',coarse.localCellIDs,'equationIDs',coarse.localEquationIDs);
actualColumns=validateRocketLocalCoarseColumns(actualColumns,n,nc,np);
assert(isequaln(columns,actualColumns),'LocalCoarse:Columns','保存与显式局部列身份或顺序不同。');
m=coarse.mixedLift;mini=struct('groupCount',space.groupCount,'prolongation',space.prolongation);
assert(isequaln(m.baseQ,cache.Q)&&isequaln(m.gas,cache.gas)&&isequaln(m.scale,cache.scale)&& ...
    isequaln(m.space,mini)&&isequaln(m.primitiveSpace,rmfield(primitiveSpace,'geometry'))&& ...
    isequaln(m.selectedPrimitiveColumns(:),selected(:)),'LocalCoarse:NestedLift','嵌套混合提升不属于同一基态/父空间/原始变量列。');
nr=numel(columns.retainedMixedColumns);nl=numel(columns.cellIDs);d=nr+nl;image=coarse.image;buffers=whos('image');
assert(issparse(image)&&isreal(image)&&isequal(size(image),[5*n d])&&all(isfinite(nonzeros(image)))&& ...
    buffers.bytes==coarse.imageBytes&&nnz(image)==coarse.imageNonzeros&&buffers.bytes<=maximumImageBytes,'LocalCoarse:Budget','局部像形状/非零数/存储超界。');
assert(numel(m.columnLiftScale)==nc+np&&all(isfinite(m.columnLiftScale)&m.columnLiftScale>0)&& ...
    numel(coarse.localColumnLiftScale)==nl&&all(isfinite(coarse.localColumnLiftScale)&coarse.localColumnLiftScale>0)&& ...
    isequaln(coarse.columnLiftScale,[m.columnLiftScale(columns.retainedMixedColumns);coarse.localColumnLiftScale]), ...
    'LocalCoarse:Lift','局部/继承列的提升归一化尺度不符。');
nf=size(space.geometry.inputGeometry.F,1);
assert(isequaln(coarse.localOriginalFaceIDs,mod(columns.cellIDs-1,nf)+1)&& ...
    isequaln(coarse.localLayerIDs,floor((columns.cellIDs-1)/nf)+1),'LocalCoarse:Mapping','局部原CV到原面/层的映射不符。');
G=full(image'*image);G=.5*(G+G');U=coarse.upper;
assert(isequal(size(U),[d d])&&all(isfinite(U),'all')&&isequal(U,triu(U))&&all(diag(U)>0)&&rcond(G)>1e-12&& ...
    max(abs(diag(G)-1))<1e-10&&norm(G-coarse.normalMatrix,'fro')<1e-11*max(1,norm(G,'fro'))&& ...
    norm(U'*U-G,'fro')<1e-11*max(1,norm(G,'fro')),'LocalCoarse:Factor','局部小Gram或因子失败。');
weights=sin((1:d)'*.37);direction=liftRocketLocalCoarse(coarse,weights);actual=-applyCutCellSelectedDirection(cache,direction);
error=norm(actual(:)-image*weights)/max(1,norm(actual(:)));assert(error<1e-9,'LocalCoarse:Probe','当前完整模型没有复现保存局部像。');
% 候选字典只用于离线证据；运行时仅保留冻结后的最终像和逐列提升。
remove={'candidateImage','candidateColumnLiftScale','candidateCellIDs','candidateEquationIDs','selectionRemaining'};
for entry=remove,if isfield(coarse,entry{1}),coarse=rmfield(coarse,entry{1});end,end
report=struct('sourceFile',filename,'sourceAndStateVerified',true,'freshFineModelProbeRelativeDifference',error, ...
    'reuseVerificationModelApplications',1,'constructionModelApplications',0,'actualOriginalNSEvaluations',0, ...
    'imageBytes',buffers.bytes,'maximumImageBytes',maximumImageBytes,'newProductionSolvedAreaM2',0);
end
