function metric=buildRocketPrimitiveUpdateMetric(Q,scale,gas)
%BUILDROCKETPRIMITIVEUPDATEMETRIC 构造当前状态的相对密度、声速归一速度和相对温度更新度量。
% 模块一：由真实守恒初态推导原始变量的一阶链式导数，不改变状态或物理方程。
% 模块二：度量只约束方向幅度；不能替代实际候选正性、温域或原NS验收。
assert(size(Q,2)==5&&isreal(Q)&&all(isfinite(Q),'all')&& ...
    (isequal(size(scale),[1 5])||isequal(size(scale),size(Q)))&&all(isfinite(scale)&scale>0,'all'), ...
    'PrimitiveMetric:Input','守恒初态或残差尺度非法。');
rho=Q(:,1);assert(all(rho>0),'PrimitiveMetric:State','初态密度必须为正。');
cv=gas.R/(gas.gamma-1);u=Q(:,2:4)./rho;T=(Q(:,5)-.5*rho.*sum(u.^2,2))./(rho*cv);
assert(all(isfinite(T)&T>0),'PrimitiveMetric:State','初态温度必须为正。');
a=sqrt(gas.gamma*gas.R*T);momentumScale=scale(:,2:4);densityScale=scale(:,1);
metric=struct('kind','current-state-linear-primitive-relative-update-metric','cellCount',size(Q,1), ...
    'diagonal',[1./rho repmat(1./(rho.*a),1,3) 1./(rho*cv.*T)].*scale, ...
    'densityToVelocity',-u./(rho.*a).*densityScale, ...
    'densityToTemperature',(.5*sum(u.^2,2)-cv*T)./(rho*cv.*T).*densityScale, ...
    'momentumToTemperature',-u./(rho*cv.*T).*momentumScale, ...
    'sourceStateChanged',false,'physicalEquationChanged',false);
end
