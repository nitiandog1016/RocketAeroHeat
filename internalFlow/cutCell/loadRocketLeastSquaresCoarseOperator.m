function [coarse,report]=loadRocketLeastSquaresCoarseOperator(filename,cache,space,maximumImageBytes)
%LOADROCKETLEASTSQUARESCOARSEOPERATOR 复用同一基态粗像，核对来源、代数结构与新方向探针。
% 模块一：基态、原几何、边界、物性、缩放及计算源码逐项一致，否则拒绝复用。
% 模块二：重新核对稀疏像内存、小Gram及Cholesky，不能以旧成功标签代替检查。
% 模块三：用当前完整细层作用重算确定性粗方向；仅模型核对，不调用原NS或更新Q。
assert(ischar(filename)&&isfile(filename),'RocketCoarse:File','粗层来源文件不存在。');
s=load(filename,'coarse');assert(isfield(s,'coarse')&&isstruct(s.coarse)&&isscalar(s.coarse),'RocketCoarse:File','来源缺少粗像算子。');coarse=s.coarse;
assert(strcmp(coarse.kind,'volume-based-fine-L2-minimum-residual-coarse-correction')&& ...
    isequaln(coarse.baseQ,cache.Q)&&isequaln(coarse.space,space)&&isequaln(space.geometry,cache.geometry)&& ...
    isequaln(coarse.gas,cache.gas)&&isequaln(coarse.boundary,cache.boundary)&&isequaln(coarse.scale,cache.scale), ...
    'RocketCoarse:Cache','来源粗像不属于当前基态、原几何、传递算子或边界物性。');
assert(isequaln(coarse.sourceIdentity,rocketSelectedDirectionSourceIdentity),'RocketCoarse:Source','细层计算源码已改变，不能复用旧粗像。');
n=size(cache.Q,1);d=5*space.groupCount;image=coarse.image;buffers=whos('image');
assert(issparse(image)&&isreal(image)&&isequal(size(image),[5*n d])&&all(isfinite(nonzeros(image)))&& ...
    buffers.bytes<=maximumImageBytes&&buffers.bytes==coarse.imageBytes&&nnz(image)==coarse.imageNonzeros, ...
    'RocketCoarse:ImageBudget','粗像形状、非零数或实际存储预算不符。');
assert(isequal(size(coarse.columnLiftScale),[d 1])&&all(isfinite(coarse.columnLiftScale)&coarse.columnLiftScale>0)&& ...
    isequal(size(coarse.normalMatrix),[d d])&&isequal(size(coarse.upper),[d d]), ...
    'RocketCoarse:Factor','粗像归一化或小因子形状不符。');
G=full(image'*image);G=.5*(G+G');factor=coarse.upper;
assert(all(isfinite(G),'all')&&all(isfinite(factor),'all')&&all(diag(factor)>0)&&isequal(factor,triu(factor))&& ...
    max(abs(diag(G)-1))<1e-10&&rcond(G)>1e-12&& ...
    norm(G-coarse.normalMatrix,'fro')<=1e-11*max(1,norm(G,'fro'))&& ...
    norm(factor'*factor-G,'fro')<=1e-11*max(1,norm(G,'fro')), ...
    'RocketCoarse:Factor','当前稀疏像、小Gram或固定Cholesky核对失败。');
coefficients=sin((1:d)'*.37);direction=space.prolongation*reshape(coefficients.*coarse.columnLiftScale,space.groupCount,5);
actual=-applyCutCellSelectedDirection(cache,direction);predicted=image*coefficients;
probeError=norm(actual(:)-predicted)/max(1,norm(actual(:)));
assert(probeError<1e-9,'RocketCoarse:Probe','当前细层作用没有复现保存的粗像，不复用。');
report=struct('sourceFile',filename,'sourceAndStateVerified',true,'freshFineModelProbeRelativeDifference',probeError, ...
    'reuseVerificationModelApplications',1,'constructionModelApplications',0,'actualOriginalNSEvaluations',0, ...
    'imageBytes',buffers.bytes,'maximumImageBytes',maximumImageBytes,'newProductionSolvedAreaM2',0);
end
