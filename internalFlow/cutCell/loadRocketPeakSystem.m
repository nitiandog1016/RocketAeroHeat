function preparation=loadRocketPeakSystem(file,expectedStateFile)
%LOADROCKETPEAKSYSTEM 核对当前状态、几何、算法及全部准备产物，拒绝跨状态缓存。
if nargin<2,expectedStateFile='';end
assert(ischar(file)&&isfile(file),'PeakSystem:Binding','方向准备清单不存在。');
preparation=jsondecode(fileread(file));p=preparation;
assert(strcmp(p.kind,'current-state-peak-direction-system-v1')&& ...
    isequaln(p.sourceIdentity,rocketSelectedDirectionSourceIdentity)&&isequaln(p.methodIdentity,rocketPeakSystemSourceIdentity)&& ...
    strcmp(p.sourceBinding.stateLocation,'result')&&~p.referenceReusedAsInitialGuess&&~p.oldDerivativeOrQualificationInherited, ...
    'PeakSystem:Binding','方向系统类型、算法身份或参考方向身份不符。');
assert(strcmp(rocketStreamingFileSHA256(p.sourceBinding.sourceFile),p.sourceBinding.sourceFileSHA256)&& ...
    strcmp(rocketStreamingFileSHA256(p.geometryBinding.file),p.geometryBinding.sha256), ...
    'PeakSystem:Binding','准备状态或几何已经改变。');
if ~isempty(expectedStateFile)
    assert(strcmp(rocketStreamingFileSHA256(expectedStateFile),p.sourceBinding.sourceFileSHA256), ...
        'PeakSystem:Binding','该准备系统不属于所选当前状态。');
end
for key=fieldnames(p.artifacts)'
    a=p.artifacts.(key{1});assert(isfile(a.file)&&strcmp(rocketStreamingFileSHA256(a.file),a.sha256), ...
        'PeakSystem:Binding','方向准备产物丢失或内容已经改变。');
end
end
