function [coarse,report]=loadRocketMixedCoarseOperator(filename,cache,space,primitiveSpace,selected,maximumImageBytes)
%LOADROCKETMIXEDCOARSEOPERATOR 核对混合像的基态、逐列提升/来源及当前完整作用探针。
% 模块一：两种空间和筛选列必须与显式配置相同，不从旧文件隐式选择算法。
% 模块二：稀疏像、小Gram/因子及原NS/提升源码分别检查；不接受跨Q缓存。
assert(ischar(filename)&&isfile(filename),'MixedCoarse:File','混合粗像来源不存在。');s=load(filename,'coarse');assert(isfield(s,'coarse'));coarse=s.coarse;
assert(strcmp(coarse.kind,'mixed-conservative-primitive-fine-L2-minimum-residual-coarse-correction')&& ...
    isequaln(coarse.baseQ,cache.Q)&&isequaln(coarse.space,space)&&isequaln(coarse.primitiveSpace,rmfield(primitiveSpace,'geometry'))&& ...
    isequaln(coarse.selectedPrimitiveColumns(:),selected(:))&&isequaln(coarse.gas,cache.gas)&&isequaln(coarse.boundary,cache.boundary)&&isequaln(coarse.scale,cache.scale), ...
    'MixedCoarse:Cache','混合基态、空间、列身份或边界物性不符。');
assert(isequaln(coarse.sourceIdentity,rocketSelectedDirectionSourceIdentity)&&isequaln(coarse.liftSourceIdentity,rocketMixedCoarseLiftIdentity), ...
    'MixedCoarse:Source','完整作用或逐列提升源码已改变。');
d=5*space.groupCount+numel(selected);image=coarse.image;buffers=whos('image');
assert(issparse(image)&&isreal(image)&&isequal(size(image),[numel(cache.Q) d])&&all(isfinite(nonzeros(image)))&& ...
    buffers.bytes==coarse.imageBytes&&nnz(image)==coarse.imageNonzeros&&buffers.bytes<=maximumImageBytes,'MixedCoarse:Budget','混合像形状/非零数/预算不符。');
assert(numel(coarse.columnLiftScale)==d&&all(isfinite(coarse.columnLiftScale)&coarse.columnLiftScale>0)&&coarse.baseConservativeColumns==5*space.groupCount,'MixedCoarse:Lift','混合提升尺度或保守底空间列数不符。');
G=full(image'*image);G=.5*(G+G');U=coarse.upper;
assert(isequal(size(U),[d d])&&all(isfinite(U),'all')&&isequal(U,triu(U))&&all(diag(U)>0)&&rcond(G)>1e-12&& ...
    max(abs(diag(G)-1))<1e-10&&norm(G-coarse.normalMatrix,'fro')<=1e-11*max(1,norm(G,'fro'))&& ...
    norm(U'*U-G,'fro')<=1e-11*max(1,norm(G,'fro')),'MixedCoarse:Factor','混合小Gram或因子检查失败。');
coefficients=sin((1:d)'*.37);direction=liftRocketMixedCoarse(coarse,coefficients);actual=-applyCutCellSelectedDirection(cache,direction);
error=norm(actual(:)-image*coefficients)/max(1,norm(actual(:)));assert(error<1e-9,'MixedCoarse:Probe','混合像没有复现当前完整空间作用。');
report=struct('sourceFile',filename,'sourceAndStateVerified',true,'freshFineModelProbeRelativeDifference',error, ...
    'reuseVerificationModelApplications',1,'constructionModelApplications',0,'actualOriginalNSEvaluations',0, ...
    'imageBytes',buffers.bytes,'maximumImageBytes',maximumImageBytes,'newProductionSolvedAreaM2',0);
end
