function [face,flux,info]=resolveNSRiemannReservoir3D(cellPrimitive,b,normal,gas)
%RESOLVENSRIEMANNRESERVOIR3D 用内部三维精确Riemann波系定义显式开放储库。
% 模块一：左侧为域内状态，右侧为给定储库，法向必须指向域外，全部使用SI。
% 模块二：在xi=0真实采样原态/星区/稀疏扇，以实际质量方向选择黏性入口约束。
% 模块三：原80—2000K/正性/真空/根容差不放宽；不采用旧特征公式的跨声速外推。
% 这是新的显式数值边界；储库不是外部CFD或已求外流，尚无非反射/物理精度保证。
assert(isstruct(b)&&isscalar(b)&&isfield(b,'type')&&strcmp(b.type,'riemannReservoir')&& ...
    isequal(sort(fieldnames(b)),sort({'type';'primitive'})), ...
    'NSRiemann:Input','储库只接受明确type和五量primitive，不能混入压力出口或旧特征参数。');
N=size(cellPrimitive,1);validateattributes(cellPrimitive,{'numeric'},{'real','finite','2d','ncols',5,'nonempty'});
assert(isequal(size(normal),[N 3])&&all(isfinite(normal),'all')&&all(abs(sum(normal.^2,2)-1)<1e-12), ...
    'NSRiemann:Normal','需要每个边界面指向域外的单位法向。');
validateattributes(b.primitive,{'numeric'},{'real','finite','2d','ncols',5,'nonempty'});
assert(size(b.primitive,1)==1||size(b.primitive,1)==N,'NSRiemann:Input','储库状态须为1×5或与面数相同。');
reservoir=b.primitive;if size(reservoir,1)==1,reservoir=repmat(reservoir,N,1);end
cv=gas.R/(gas.gamma-1);L=conservative(cellPrimitive);R=conservative(reservoir);
[flux,waves]=cutCellExactEulerFlux(L,R,normal,gas);face=waves.samplePrimitive;
incoming=flux(:,1)<0;
info=struct('method','显式三维储库 / 定gamma精确Godunov Riemann xi=0采样', ...
    'scope','数值开放边界；黏性按实际质量方向闭合，非反射/外域/物性/湍流与实验精度尚未验证', ...
    'normal',normal,'sampleRegion',waves.sampleRegion,'isInflow',incoming, ...
    'normalVelocity',sum(face(:,2:4).*normal,2),'normalMach',sum(face(:,2:4).*normal,2)./sqrt(gas.gamma*gas.R*face(:,5)), ...
    'reservoirPrimitiveInput',reservoir,'pressureStarPa',waves.pressureStarPa, ...
    'vacuumVelocityMarginMs',waves.vacuumVelocityMarginMs,'pressureRootResidualMs',waves.pressureRootResidualMs, ...
    'pressureRootIterations',waves.pressureRootIterations,'pressureClipped',false,'temperatureClipped',false, ...
    'oldCharacteristicGuardRelaxed',false,'physicalSolution',false,'newProductionSolvedAreaM2',0);
    function q=conservative(p)
        assert(all(p(:,1)>0)&&all(p(:,5)>=gas.temperatureRange(1)&p(:,5)<=gas.temperatureRange(2)), ...
            'NSRiemann:State','域内/储库密度或温度非法，不裁剪输入。');
        q=[p(:,1),p(:,1).*p(:,2:4),p(:,1).*(cv*p(:,5)+.5*sum(p(:,2:4).^2,2))];
    end
end
