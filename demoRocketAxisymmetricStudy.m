function report=demoRocketAxisymmetricStudy(folder)
%DEMOROCKETAXISYMMETRICSTUDY 从已交付真实检查点重新生成完整箭体研究工作台。
% 模块一：优先使用工程包内冻结证据，开发工作区可使用outputs中的同一真实链。
% 模块二：逐端点重放后导出五步骤同窗快照；不隐式继续长时求解。
% 模块三：返回htmlFile供用户打开，未稳态研究不会晋升为物理解或全面积资格。
root=fileparts(mfilename('fullpath'));addpath(root,fullfile(root,'regionalFlow','axisymmetric'));
if nargin<1,folder=fullfile(root,'outputs','rocket_axisymmetric_study');end
candidates={fullfile(root,'validation','v75','root_confirmed'), ...
    fullfile(root,'outputs','v75_validation','root_confirmed'), ...
    fullfile(root,'validation','v74','local_Q23'), ...
    fullfile(root,'outputs','v74_validation','local_Q23'), ...
    fullfile(root,'validation','v73','hlle_uniform'), ...
    fullfile(root,'outputs','v73_validation','hlle_uniform'), ...
    fullfile(root,'validation','v72','constant_uniform'), ...
    fullfile(root,'outputs','v72_validation','constant_uniform'), ...
    fullfile(root,'validation','v70','normal_collar_continued'), ...
    fullfile(root,'validation','v70','normal_collar'), ...
    fullfile(root,'outputs','v70_validation','normal_collar_continued'), ...
    fullfile(root,'outputs','v70_validation','normal_collar'), ...
    fullfile(root,'validation','v69','work_arithmetic'), ...
    fullfile(root,'outputs','v69_validation','work_arithmetic')};
source='';
for k=1:numel(candidates)
    if exist(fullfile(candidates{k},'rocket_axisymmetric_evidence.mat'),'file'),source=candidates{k};break;end
end
assert(~isempty(source),'RocketStudyDemo:Evidence','需要与当前求解源码一致的完整箭体真实检查点，初猜不能代替。');
report=exportRocketAxisymmetricWorkbench(source,folder,struct('azimuthSegments',32));
fprintf('完整箭体研究工作台：%s\n',report.htmlFile);
fprintf('仅冻结数值研究；是否达到原残差稳态见页面，物理精度未验收，新增合格生产面积0。\n');
end
