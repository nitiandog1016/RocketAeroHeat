function verifyThermistorWorkbenchMesh(mesh,cells)
%VERIFYTHERMISTORWORKBENCHMESH 在使用结果前分别核对全珠原面和已生成的求解体网。
assert(isscalar(cells) && ismember(cells,[2 4 48]) && isfield(mesh,'thermistorPrepared'), ...
    'RAH:Bead:Mesh','请先生成所选热敏珠网格。');
p=mesh.thermistorPrepared;
[canonical,source]=thermistorWorkbenchModel();
assert(isequal(mesh.V,canonical.V) && isequal(mesh.F,canonical.F) && strcmp(p.bodySHA256,source.bodySHA256), ...
    'RAH:Bead:Geometry','原面几何或原编号与名义试件不符。');
root=fileparts(mfilename('fullpath'));
if cells==48
    % 网格阶段核对原体网和节点映射，登记初场身份。计算前后端会核对实际种子。
    grid=jsondecode(fileread(fullfile(root,'docs','validation','v293','evidence','grid.json')));
    data=jsondecode(fileread(p.manifest));
    cache=fullfile(root,'outputs','thermistor_inputs','B6-56','grid56');
    legacy=fullfile(root,'outputs','v293_validation','grid01');
    seed=fullfile(p.directory,'seed_00000.csv');
    assert(strcmp(cm011FileSHA256(p.manifest),p.manifestSHA256) && ...
        isequal(data,rmfield(p,{'manifest','manifestSHA256'})) && p.angularCells==48 && ...
        p.radialCells==grid.newLayers && p.cells==grid.cells && p.nodes==grid.nodes && ...
        any(strcmp(p.directory,{cache,legacy})) && ...
        strcmp(p.meshSHA256,grid.gridSHA256) && strcmp(p.seedSHA256,grid.seedSHA256) && ...
        strcmp(p.nodeMapSHA256,grid.nodeMapSHA256) && ...
        strcmp(cm011FileSHA256(fullfile(p.directory,'mesh.su2')),p.meshSHA256) && ...
        strcmp(cm011FileSHA256(fullfile(p.directory,'nodes.npz')),p.nodeMapSHA256) && ...
        ((strcmp(p.directory,cache) && ~isfile(seed)) || strcmp(cm011FileSHA256(seed),p.seedSHA256)), ...
        'RAH:Bead:Mesh','56 层体网、种子或准备记录发生变化。');return;
end
contract=jsondecode(fileread(fullfile(root,'cases','thermistor_b','grids.json')));
if cells==2,fixed=contract.grids.outer;else,fixed=contract.grids.outerAngular4;end
manifest=fullfile(p.directory,'prepared.json');g=jsondecode(fileread(manifest));
assert(cells==p.angularCells && g.angularCells==cells && strcmp(cm011FileSHA256(manifest),p.manifestSHA256) && ...
    strcmp(p.meshSHA256,fixed.mesh_su2) && strcmp(cm011FileSHA256(fullfile(p.directory,'mesh.su2')),fixed.mesh_su2) && ...
    strcmp(cm011FileSHA256(fullfile(p.directory,'nodes.npz')),fixed.nodes_npz), ...
    'RAH:Bead:Mesh','所选体网、节点或预处理回执已改变，请重新生成。');
end
