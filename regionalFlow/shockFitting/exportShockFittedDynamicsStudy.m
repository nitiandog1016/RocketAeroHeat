function report=exportShockFittedDynamicsStudy(dynamicsFile,dynamicsAudit,capFiles,capAudits,legacyFile,legacyAudit,folder)
%EXPORTSHOCKFITTEDDYNAMICSSTUDY 把实际非均匀基准和曲面候选接回同一五步骤科研工作台。
% 模块一：每个算例单独绑定实际MAT与独立审核；不重算流场、不把研究值映射到原箭体。
% 模块二：保留相邻流体压力/温度和独立Riemann壁压；Te/Tr/给定Tw/求解Tw/热流分别未求。
% 模块三：只导出真实保存的初末帧，粗细网格采用同一固定压力色标。
% 模块四：加入真实X截面周向曲线，固定复用已发布截面内核，不混入并发修改。
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
assert(iscell(capFiles)&&iscell(capAudits)&&numel(capFiles)==numel(capAudits)&&~isempty(capFiles), ...
    'ShockFit:ExportSource','每个曲面MAT必须配有同源独立审核。');
d=load(dynamicsFile);a=jsondecode(fileread(dynamicsAudit));
assert(strcmp(a.status,'passed-independent-Riemann-Sod-volume-average-ALE-CFL-and-conservation-audit')&& ...
    strcmp(a.evidenceSHA256,rocketStreamingFileSHA256(dynamicsFile))&&~a.productionQualified, ...
    'ShockFit:ExportSource','非均匀研究缺少同源已完成审核。');
% 复用实际旧基准和原箭体几何，来源各自保留；新文件只在全新目录构造。
exportShockFittedKernelStudy(legacyFile,legacyAudit,folder);
web=fullfile(folder,'workbench');data=jsondecode(fileread(fullfile(web,'ale-data.json')));
originalSource=data.source;cases=cell(numel(data.cases),1);
for j=1:numel(data.cases)
    cases{j}=data.cases(j);cases{j}.source=originalSource;
    cases{j}.pressureRangePa=data.pressureRangePa;
    cases{j}.methods=thermalUnknowns(cases{j}.methods);
end
capEvidence=cell(numel(capFiles),1);
for j=1:numel(capFiles)
    saved=load(capFiles{j},'study','report');study=saved.study;check=jsondecode(fileread(capAudits{j}));
    assert(strcmp(check.status,'passed-conservative-curved-transient-audit-not-steady-qualification')&& ...
        strcmp(check.evidenceSHA256,rocketStreamingFileSHA256(capFiles{j}))&&~check.productionQualified&& ...
        ~study.productionQualified,'ShockFit:ExportSource','曲面研究缺少同源审核或被误授予资格。');
    shell=study.cap.shell;mesh=shell.mesh;b=mesh.boundaryFaces;N=numel(b);
    first=frame(study.initialNodes,study.initialQ,nan(N,1),0,mesh,study.gas, ...
        '给定初始外壳的RH初始化；不是已求得的稳态外流');
    last=frame(study.nodes,study.Q,study.lastStep.wallPressurePa,study.timeS,mesh,study.gas, ...
        '实际三维ALE非稳态候选；激波相容与区域资格未通过');
    method=methods('三维ALE共享面五量推进；常gamma状态方程恢复邻接单元压力', ...
        '固定无穿透滑移壁面/镜像精确Riemann求得的瞬态壁压；不是给定壁压');
    source=sourceRecord(capFiles{j},capAudits{j});capEvidence{j}=source;
    cases{end+1}=struct('id',sprintf('sphere-r%d-a%d-l%d-t%.8g',study.cap.rings,study.cap.azimuths,shell.layers,study.timeS), ...
        'caption',sprintf('球鼻 · %d面 / %d单元 · t=%.6g s',size(study.cap.F,1),mesh.cellCount,study.timeS), ...
        'faces',mesh.faces(b,:)-1,'boundaryKind',study.boundary.kind, ...
        'sourceFaceIDs',shell.cellOriginalFaceIDs(mesh.owner(b)),'sourceFaceLabel','所属球鼻基准面号（非原箭体）', ...
        'frames',{{first,last}},'methods',method,'source',source,'pressureRangePa',[0 45000], ...
        'defaultView','wall','defaultField','wallPressurePa','timeKind','transient', ...
        'conditionLabel',sprintf('M=5；α=0°；球半径%.6g m；常gamma；原20°输入仅复用p/T/rho和速率',study.cap.radiusM), ...
        'modelRole','参数化球鼻独立基准；固定三角壁面，不是原箭体已解面', ...
        'scope','有限角度三维球鼻候选；未稳态、非精确解析球面，不能作为合格边界层外缘或新增正式热流面积', ...
        'stateRole','瞬态研究值；原箭体、外缘Te、恢复Tr、壁温与黏性热流均未由本研究求出', ...
        'fieldStateLabel','未稳态候选；未授予区域资格', ...
        'coordinateNote','SI / m · 球鼻沿+X，零攻角来流−X · 仅球鼻基准面号', ...
        'geometryNote','球鼻非稳态候选 · 灰色为未求 · 截面交线不代表流线', ...
        'boundaryDescription','固定滑移壁面 / 共同激波RH / 仅全部特征出流的侧边界', ...
        'unsolvedNote','激波相容、稳态、网格/外域和真实体形门槛仍未通过；黏性热流未求', ...
        'diagnostic',sprintf('真实接受%d步；残差%.4g；激波压力相容差%.3g；投影残差%.3g m/s；区域数组预算%.3f MiB（不是进程峰值）。', ...
            size(study.history,1),check.finalResidual,check.finalShockPressureMismatch, ...
            check.sharedNodeMotion.maximumUnrepresentedFaceSpeedMS,study.maximumDeclaredRegionArrayBytes/1024^2), ...
        'productionQualified',false); %#ok<AGROW>
end
data.defaultCaseIndex=numel(cases)-1;
for j=1:numel(d.tubes)
    tube=d.tubes{j};mesh=tube.box.mesh;b=mesh.boundaryFaces;N=numel(b);grid=tube.box.counts(1);
    first=frame(tube.nodes0,tube.initialQ,nan(N,1),0,mesh,tube.gas,'给定的Riemann初始数据；不是推进结果');
    last=frame(tube.nodes1,tube.Q,tube.lastStep.wallPressurePa,tube.timeS,mesh,tube.gas,'已核验的三维波管数值基准；不是箭体区域解');
    cases{end+1}=struct('id',sprintf('sod-nx%d',grid),'caption',sprintf('Sod型波管 · Nx=%d · %d步',grid,size(tube.history,1)), ...
        'faces',mesh.faces(b,:)-1,'boundaryKind',tube.boundary.kind,'sourceFaceIDs',zeros(N,1), ...
        'frames',{{first,last}},'methods',methods('实际三维Godunov-ALE五量推进/常gamma压力恢复；未施加内部解析场', ...
            '侧面滑移镜像精确Riemann压力；不是给定壁压'), ...
        'source',sourceRecord(dynamicsFile,dynamicsAudit),'pressureRangePa',[0 110000],'timeKind','transient', ...
        'conditionLabel','ρL/ρR=1/0.125 kg/m³；pL/pR=100000/10000 Pa；初始静止；γ=1.4', ...
        'modelRole','独立盒域解析波管基准，不对应原箭体面元', ...
        'scope','非均匀三维推进及Sod解析体平均加密校核；不是箭体物理解或热流结果', ...
        'stateRole','保留三维横向数值速度；初末帧均来自同一实际保存MAT', ...
        'fieldStateLabel','解析基准的实际数值解；不授予箭体区域资格', ...
        'coordinateNote','SI / m · 独立波管沿+X传播；箭体坐标与来流约定保持', ...
        'geometryNote','Sod型三维数值基准 · 未复制解析场 · 灰色为未求', ...
        'boundaryDescription','侧面移动滑移/左右明确远端储库；波系未到达远端', ...
        'unsolvedNote','此基准不计算箭体、黏性热流或壁温', ...
        'diagnostic',sprintf('密度体平均L1/rhoL=%.4g；能量L1/eL=%.4g；横向RMS速度%.4g m/s。', ...
            a.tubes(j).conservedCellAverageL1ByPhysicalScale(1),a.tubes(j).conservedCellAverageL1ByPhysicalScale(5),a.tubes(j).transverseRmsVelocityMS), ...
        'productionQualified',false); %#ok<AGROW>
end
data.kind='shock-fitted-dynamics-study-v102';data.cases=cases;data.source=capEvidence{end};
data.originalGeometrySource=originalSource;data.pressureRangePa=[0 45000];
data.NASA7Scope='本页动态推进只采用明确的常gamma模型；NASA7此前只核验移动RH/活塞相容，未实现NASA7 ALE。曲面结果均未授予物理区域资格。';
data.experimentalValidation=false;data.productionQualified=false;data.newProductionSolvedAreaM2=0;
text=jsonencode(data);write(fullfile(web,'ale-data.json'),text);write(fullfile(web,'ale-data.js'),['window.ALE_STUDY=' text ';' newline]);
report=struct('status','exported-actual-nonuniform-and-curved-transient-studies-with-true-circumferential-sections', ...
    'cases',numel(cases),'frames',2*numel(cases),'dataSHA256',rocketStreamingFileSHA256(fullfile(web,'ale-data.json')), ...
    'sectionCoreSHA256',rocketStreamingFileSHA256(fullfile(root,'web/ale-section-core.js')), ...
    'productionQualified',false,'newProductionSolvedAreaM2',0);
write(fullfile(folder,'ale_export.json'),jsonencode(report));disp(report);
end
function value=frame(X,Q,wallPressure,timeS,mesh,gas,role)
state=shockFittedState3D(Q,gas,'conservative');owner=mesh.owner(mesh.boundaryFaces);empty=nan(numel(owner),1);
assert(isequal(size(wallPressure),size(empty)),'ShockFit:ExportShape','壁压必须逐真实边界面保留。');
value=struct('position',X,'pressurePa',state.pressure(owner),'temperatureK',state.temperature(owner), ...
    'speedMS',vecnorm(state.velocity(owner,:),2,2),'wallPressurePa',wallPressure, ...
    'heatFluxWm2',empty,'wallTemperatureK',empty,'edgeTemperatureK',empty, ...
    'recoveryTemperatureK',empty,'inputWallTemperatureK',empty,'timeS',timeS,'valueRole',role);
end
function value=methods(pressure,wall)
value=struct('pressurePa',pressure, ...
    'temperatureK','保存五量的常gamma状态方程恢复；这是相邻单元流体温度，不是Te、Tr或壁温', ...
    'speedMS','保存的三维动量/密度恢复速度幅值；保留全部横向数值分量', ...
    'wallPressurePa',wall,'heatFluxWm2','本研究未计算黏性热流，不能用无黏模型的零值替代气动热结果', ...
    'wallTemperatureK','未求解壁体温度，也未把流体温度充当壁温');
value=thermalUnknowns(value);
end
function value=thermalUnknowns(value)
value.edgeTemperatureK='未完成合格边界层外缘匹配；层内流体温度不能代替Te';
value.recoveryTemperatureK='本研究未计算恢复温度或恢复焓';
value.inputWallTemperatureK='无黏滑移区域研究未设置壁温边界';
end
function value=sourceRecord(evidence,audit)
value=struct('evidenceFile',strrep(evidence,'\','/'),'evidenceSHA256',rocketStreamingFileSHA256(evidence), ...
    'auditFile',strrep(audit,'\','/'),'auditSHA256',rocketStreamingFileSHA256(audit));
end
function write(file,value)
fid=fopen(file,'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',value);
end
