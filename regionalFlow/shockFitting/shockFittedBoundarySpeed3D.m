function boundary=shockFittedBoundarySpeed3D(interiorQ,normalOut,upstream,gas)
%SHOCKFITTEDBOUNDARYSPEED3D 由下游声学相容和上游RH共同求三维激波法向速度。
% 模块一：normalOut指向上游；左侧为当前下游单元，右侧为明确均匀上游。
% 模块二：精确Riemann压力根包含下游声学信息，使用右压缩波速度，不直接复制单元压力。
% 模块三：用所得速度重新回代移动RH；切向/熵来自上游，投影到共享节点前单独保留。
assert(strcmp(gas.thermalPropertyMode,'caloricallyPerfect'),'ShockFit:ShockSpeedGas', ...
    '当前下游Riemann相容只实现常gamma；NASA7不能静默回退。');
N=size(interiorQ,1);
assert(isa(normalOut,'double')&&isreal(normalOut)&&isequal(size(normalOut),[N 3])&& ...
    all(isfinite(normalOut),'all')&&all(abs(sum(normalOut.^2,2)-1)<1e-12), ...
    'ShockFit:Normal','需要面向上游的真实单位法向。');
first=shockFittedState3D([upstream.density upstream.velocityVector' upstream.temperature],gas,'primitive');
assert(abs(first.pressure-upstream.pressure)<1e-10*upstream.pressure,'ShockFit:EOS','上游状态方程不一致。');
constant=struct('gamma',gas.gamma,'R',gas.R,'temperatureRange',gas.temperatureRangeK);
[~,riemann]=cutCellExactEulerFlux(interiorQ,repmat(first.Q,N,1),normalOut,constant);
p=riemann.pressureStarPa;u=riemann.normalVelocityStarMs;
assert(all(p>upstream.pressure),'ShockFit:ShockBoundaryWave', ...
    '边界右侧不是压缩激波；不能将稀疏波或接触面冒充拟合激波。');
un=normalOut*upstream.velocityVector;
speed=un+first.soundSpeed*sqrt((gas.gamma+1)/(2*gas.gamma)*p/upstream.pressure+(gas.gamma-1)/(2*gas.gamma));
jump=movingShockJump3D(upstream,gas,-normalOut,-speed);
pressureError=(jump.state.pressure-p)./p;
normalError=(sum(jump.state.velocity.*normalOut,2)-u)/first.soundSpeed;
assert(max(abs(pressureError))<2e-11&&max(abs(normalError))<2e-11, ...
    'ShockFit:ShockCompatibility','下游压力曲线与移动RH未同时相容。');
boundary=struct('normalOut',normalOut,'normalSpeedMS',speed,'pressureStarPa',p, ...
    'normalVelocityStarMS',u,'jump',jump,'riemann',riemann, ...
    'pressureCompatibilityRelative',pressureError,'normalCompatibilityBySoundSpeed',normalError, ...
    'method','当前下游/均匀上游的常gamma精确Riemann右压缩波速度；移动RH五量回代', ...
    'pressureGivenAsBoundaryCondition',false,'sharedNodeProjectionApplied',false, ...
    'steadyConverged',false,'productionQualified',false,'newProductionSolvedAreaM2',0);
end
