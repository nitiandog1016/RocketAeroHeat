function [GxU,GrU,audit]=axisymmetricWallVelocityGradient(mesh,cellVelocity,boundary,wallFaces,wallVelocity,GxU,GrU)
%AXISYMMETRICWALLVELOCITYGRADIENT 显式静止壁Dirichlet切向约束的两分量速度梯度。
% 模块一：缺省/legacy原样返回；只有wall.velocityGradient='dirichlet-tangent'选中墙才改梯度。
% 模块二：当前只接收常数静止[0 0]，两个笛卡尔速度分量沿壁给定导数均为0。
% 模块三：按真实t=[-nr,nx]、delta和正dn解g·t=0、g·delta=uw-uowner。
% 模块四：仅覆盖所选墙面Newton应力梯度，不改内场WLS、SA、Fourier或单元Q。
% 模块五：保留新旧梯度、真实几何和给定壁值；守恒均值导出的速度仅作单点代理。
% 非零/函数壁速和velocityTangentialGradient尚未支持，必须拒绝而不能虚构导数。
% 本模块是显式数值离散策略，不建立稳态、实验或生产求解面积资格。
f=mesh.faces;nf=numel(f.owner);nc=mesh.cellCount;wallFaces=wallFaces(:);
assert(isnumeric(cellVelocity)&&isreal(cellVelocity)&&isequal(size(cellVelocity),[nc 2])&& ...
    isnumeric(GxU)&&isreal(GxU)&&isequal(size(GxU),[nf 2])&& ...
    isnumeric(GrU)&&isreal(GrU)&&isequal(size(GrU),[nf 2])&& ...
    isnumeric(wallVelocity)&&isreal(wallVelocity)&&isequal(size(wallVelocity),[numel(wallFaces) 2]), ...
    'AxisFV:WallVelocityState','速度和梯度必须为完整实数数组，列顺序均为ux、ur。');
assert(all(isfinite([cellVelocity;wallVelocity;GxU;GrU]),'all'), ...
    'AxisFV:WallVelocityState','速度和输入梯度须有限；不裁剪或静默替代状态。');
assert(isnumeric(wallFaces)&&isreal(wallFaces)&&numel(unique(wallFaces))==numel(wallFaces)&& ...
    all(isfinite(wallFaces)&wallFaces>=1&wallFaces<=nf&wallFaces==fix(wallFaces)), ...
    'AxisFV:WallVelocityGeometry','墙面索引必须唯一且属于当前真实网格。');
assert(all(f.neighbour(wallFaces)==0)&&all(ismember(f.boundarySide(wallFaces),1:4))&& ...
    all(f.owner(wallFaces)>=1&f.owner(wallFaces)<=nc&f.owner(wallFaces)==fix(f.owner(wallFaces))), ...
    'AxisFV:WallVelocityGeometry','只接受有真实owner的边界墙，不能将内部共享面或轴当墙。');
names={'iMin','iMax','jMin','jMax'};
assert(isstruct(boundary)&&isscalar(boundary)&&all(isfield(boundary,names)), ...
    'AxisFV:WallVelocityBoundary','须给出四条逻辑边的完整边界合同。');
selected=false(numel(wallFaces),1);

%% 一、显式策略及静止给定量；legacy不消费或忽略额外导数
for side=1:4
    bc=boundary.(names{side});
    assert(isstruct(bc)&&isscalar(bc)&&isfield(bc,'type'), ...
        'AxisFV:WallVelocityBoundary','每条逻辑边必须有单一明确type。');
    local=find(f.boundarySide(wallFaces)==side);
    assert(isempty(local)||strcmp(bc.type,'wall'), ...
        'AxisFV:WallVelocityGeometry','给定墙面编号与真实边界type不一致。');
    hasPolicy=isfield(bc,'velocityGradient');hasTangent=isfield(bc,'velocityTangentialGradient');
    if ~hasPolicy&&~hasTangent,continue;end
    assert(strcmp(bc.type,'wall')&&hasPolicy, ...
        'AxisFV:WallVelocityBoundary','速度梯度策略只属于wall，导数字段不能单独出现。');
    policy=bc.velocityGradient;
    assert(((ischar(policy)&&isrow(policy))||(isstring(policy)&&isscalar(policy)&&~ismissing(policy)))&& ...
        ismember(char(policy),{'legacy','dirichlet-tangent'}), ...
        'AxisFV:WallVelocityBoundary','velocityGradient只允许legacy或dirichlet-tangent。');
    assert(~hasTangent,'AxisFV:WallVelocityBoundary', ...
        '当前静止壁策略不接收velocityTangentialGradient；非零/函数壁速尚未支持。');
    if strcmp(policy,'legacy'),continue;end
    assert(isfield(bc,'velocity')&&isnumeric(bc.velocity)&&isreal(bc.velocity)&& ...
        numel(bc.velocity)==2&&all(isfinite(bc.velocity(:)))&&all(bc.velocity(:)==0), ...
        'AxisFV:WallVelocityBoundary','当前dirichlet-tangent仅支持明确常数静止velocity=[0 0]。');
    assert(all(wallVelocity(local,:)==0,'all'), ...
        'AxisFV:WallVelocityBoundary','实际传入的墙速度必须与给定静止壁值一致。');
    selected(local)=true;
end

%% 二、只在真实所选墙面求约束梯度；不以epsilon代替法向距离
ids=wallFaces(selected);o=f.owner(ids);normal=f.normal(ids,:);tangent=[-normal(:,2),normal(:,1)];
delta=f.delta(ids,:);physicalDelta=f.centroid(ids,:)-mesh.volumeCentroid(o,:);
assert(isequal(delta,physicalDelta)&&all(isfinite([normal,delta]),'all')&& ...
    all(abs(sum(normal.^2,2)-1)<=1e-10)&&all(f.areaPerRadian(ids)>0), ...
    'AxisFV:WallVelocityGeometry','墙梯度必须使用真实面至r权体质心位移与单位流体外法向。');
dn=sum(delta.*normal,2);ds=sum(delta.*tangent,2);
assert(all(isfinite(dn)&dn>0),'AxisFV:WallVelocityGeometry', ...
    '墙面真实法向距离必须严格为正，不改变几何或以epsilon替代。');
Uc=cellVelocity(o,:);Uw=wallVelocity(selected,:);gt=zeros(numel(ids),2);
gn=(Uw-Uc)./dn;oldX=GxU(ids,:);oldR=GrU(ids,:);
newX=gt.*tangent(:,1)+gn.*normal(:,1);newR=gt.*tangent(:,2)+gn.*normal(:,2);
assert(all(isfinite([newX,newR,gn]),'all'),'AxisFV:WallVelocityState', ...
    '约束墙速度梯度非有限，未裁梯度或改变单元速度。');
GxU(ids,:)=newX;GrU(ids,:)=newR;

%% 三、完整原始审计；默认/legacy调用的空审计不应附加到NS旧info
audit=struct('kind','explicit-Dirichlet-tangent-static-wall-velocity-gradient-v1', ...
    'policy','dirichlet-tangent','faceID',ids,'ownerCell',o, ...
    'normalXR',normal,'tangentXR',tangent,'normalDistanceM',dn,'tangentialOffsetM',ds, ...
    'cellVelocityProxyXR',Uc,'wallVelocityInputXR',Uw, ...
    'tangentialGradientInputPerS',gt,'normalGradientPerS',gn, ...
    'oldGradientXPerS',oldX,'oldGradientRPerS',oldR,'gradientXPerS',newX,'gradientRPerS',newR, ...
    'oldTangentialGradientPerS',oldX.*tangent(:,1)+oldR.*tangent(:,2), ...
    'oldNormalGradientPerS',oldX.*normal(:,1)+oldR.*normal(:,2), ...
    'skewRatio',vecnorm(delta,2,2)./dn,'cellStateClipped',false, ...
    'cellVelocityIsExactFVMean',false,'wallValueKind','prescribed-static-Dirichlet-input', ...
    'tangentialDerivativeSource','exact derivative of prescribed constant zero wall velocity', ...
    'cellVelocityMeaning','conservative-mean-derived velocity used as point proxy, not an exact cell-mean velocity', ...
    'scope','explicit selected static-wall Newton stress gradient only; cell WLS, SA and Fourier unchanged; no physical validation');
end
