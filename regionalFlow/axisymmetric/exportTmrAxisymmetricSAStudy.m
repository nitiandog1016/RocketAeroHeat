function report=exportTmrAxisymmetricSAStudy(mesh,result,boundary,folder,options)
%EXPORTTMRAXISYMMETRICSASTUDY 将真实收敛TMR圆柱/20度外扩墙接入离线科研工作台。
% 模块一：原2e-6连续3步稳态、五量BE账及完整SA-RANS空间逐值重放。
% 模块二：只接收四档官方嵌套原节点，旋转完整jMin真实壁边；入口/出口不补端盖。
% 模块三：原signed q不缩放；逐参数三角形真曲面积与显示弦面面积分列。
% 模块四：复用既有WebGL/探针/周向交线/CSV；仅副本显示“数值研究”。
% 模块五：明确SA候选、Prt、给定nuTilde/nu=5及墙muT=0；局部分子mu/k与未知温度分开。
% 模块六：显式Dirichlet切向热梯度须完整重放，保存原audit与逐显示面来源及单点代理限制。
% 本模块不是湍流实验验收或完整箭体求解，新增生产物理解面积始终为0。
if nargin<5,options=struct;end
defaults=struct('azimuthSegments',48,'name','TMR Mach7 圆柱/20°外扩SA-noft2耦合五量数值研究', ...
    'title','RocketAeroHeat · TMR五量SA稳态数值研究','evidenceSource','调用者提供的冻结稳态检查点');
assert(isstruct(options)&&isscalar(options)&&all(ismember(fieldnames(options),fieldnames(defaults))), ...
    'AxisFV:TmrSAViewOptions','存在未知导出选项。');
nameWasProvided=isfield(options,'name');
for k=fieldnames(defaults)',if ~isfield(options,k{1}),options.(k{1})=defaults.(k{1});end,end
validateattributes(options.azimuthSegments,{'numeric'},{'real','finite','scalar','integer','>=',8,'<=',4096});
for k={'name','title','evidenceSource'}
    assert((ischar(options.(k{1}))&&isrow(options.(k{1})))|| ...
        (isstring(options.(k{1}))&&isscalar(options.(k{1}))), 'AxisFV:TmrSAViewOptions','显示说明须为单个文本。');
    options.(k{1})=char(options.(k{1}));
end
assert((ischar(folder)&&isrow(folder))||(isstring(folder)&&isscalar(folder)),'AxisFV:TmrSAViewOptions','输出目录须为路径。');
folder=char(folder);root=fileparts(fileparts(fileparts(mfilename('fullpath'))));

%% 一、绑定实际网格/气体/边界及原残差历史；任何改输运或墙热后沿用旧结果均拒绝
assert(isstruct(mesh)&&isscalar(mesh)&&all(isfield(mesh,{'kind','cellCount','X','R','periodicI'}))&& ...
    strcmp(mesh.kind,'axisymmetric-body-fitted-fv-v1')&&ismatrix(mesh.X)&& ...
    ismember(size(mesh.X,1),[41 81])&&ismember(size(mesh.X,2),[26 51])&& ...
    isequal(size(mesh.R),size(mesh.X))&&mesh.cellCount==(size(mesh.X,1)-1)*(size(mesh.X,2)-1)&&~mesh.periodicI, ...
    'AxisFV:TmrSAViewGeometry','专用研究页只接受41/81乘26/51节点的四档非周期官方TMR嵌套网格。');
ni=size(mesh.X,1);nj=size(mesh.X,2);expectedWallCount=ni-1;
gridIdentity=validateOfficialGrid(mesh);
required={'Q','gas','geometryBinding','steadyConverged','stopReason','acceptedSteps','residualNorm', ...
    'residualScale','history','options','finalInfo','pseudoTime','pseudoTimeIsPhysical','physicalTimeAdvanced', ...
    'physicalSolution','eligibleForSurfaceCoverage','wallTemperatureValueKind','globalBalanceRelative', ...
    'initialQ','initialConservedIntegral','finalConservedIntegral','accumulatedBoundaryIntegral','accumulatedSourceIntegral'};
assert(isstruct(result)&&isscalar(result)&&all(isfield(result,required))&& ...
    isequal(result.steadyConverged,true)&&strcmp(result.stopReason,'steady-residual-converged')&& ...
    isequal(result.physicalSolution,false)&&isequal(result.eligibleForSurfaceCoverage,false)&& ...
    strcmp(result.wallTemperatureValueKind,'prescribed')&&isnumeric(result.Q)&&isreal(result.Q)&& ...
    isequal(size(result.Q),[mesh.cellCount 5])&&all(isfinite(result.Q),'all')&&all(result.Q(:,5)>=0), ...
    'AxisFV:TmrSAViewIdentity','必须是实际残差稳态且未晋升物理解的数值研究终态。');
assert(~isfield(result,'time')&&isequal(result.pseudoTimeIsPhysical,false)&&isequal(result.physicalTimeAdvanced,0), ...
    'AxisFV:TmrSAViewTime','求稳态伪时间不可冒充物理推进时间。');
validateattributes(result.pseudoTime,{'numeric'},{'real','finite','scalar','positive'});
assert(all(isfield(result.options,{'steadyResidualTolerance','steadyRequiredSteps','minimumSteadySteps','conservationTolerance','nonlinearAbsoluteTolerance','nonlinearRelativeTolerance'}))&& ...
    result.options.steadyResidualTolerance==2e-6&&result.options.steadyRequiredSteps==3&& ...
    result.options.conservationTolerance==5e-10&&result.options.nonlinearAbsoluteTolerance==1e-11&& ...
    result.options.nonlinearRelativeTolerance==1e-9&& ...
    result.acceptedSteps>=max(3,result.options.minimumSteadySteps)&&numel(result.history.residual)>=4&& ...
    result.residualNorm==result.history.residual(end)&&result.residualNorm<=2e-6&& ...
    all(result.history.residual(end-2:end)<=2e-6)&&isfinite(result.globalBalanceRelative)&& ...
    result.globalBalanceRelative<=result.options.conservationTolerance, ...
    'AxisFV:TmrSAViewConvergence','须保留原2e-6连续3步残差、五量BE和原非线性门槛。');
validateFiveQuantityLedger(result,mesh);
binding=struct('X',mesh.X,'R',mesh.R,'cells',mesh.cells,'volumePerRadian',mesh.volumePerRadian);
assert(isequaln(result.geometryBinding,binding),'AxisFV:TmrSAViewBinding','结果几何绑定改变。');
fresh=buildAxisymmetricFVGeometry(mesh.X,mesh.R);
assert(isequaln(fresh,mesh),'AxisFV:TmrSAViewBinding','完整FV度量/梯度与原节点不能逐值重建。');
assert(isstruct(boundary)&&isscalar(boundary)&&all(isfield(boundary,{'iMin','iMax','jMin','jMax'}))&& ...
    strcmp(boundary.jMin.type,'wall')&&isequal(boundary.jMin.velocity,[0 0])&& ...
    isnumeric(boundary.jMin.temperature)&&isscalar(boundary.jMin.temperature), ...
    'AxisFV:TmrSAViewBoundary','须明确jMin静止等温墙。');
for key={'iMin','iMax','jMax'}
    entry=boundary.(key{1});
    assert(strcmp(entry.type,'riemannReservoir')&&isnumeric(entry.primitive)&& ...
        isreal(entry.primitive)&&isequal(size(entry.primitive),[1 4])&&all(isfinite(entry.primitive)), ...
        'AxisFV:TmrSAViewBoundary','三条开放边须显式给四量常储库，不暗补边界。');
end
assert(isstruct(result.gas)&&isfield(result.gas,'transport'),'AxisFV:TmrSAViewTransport', ...
    'SA研究页要求显式Sutherland气体，不能伪造四量常输运适配。');
variableTransport=true;
if variableTransport
    try
        gas=axisymmetricFVGas(result.gas);
    catch exception
        error('AxisFV:TmrSAViewTransport','显式局部输运输入无效，不能沿用旧墙热：%s',exception.message);
    end
    if ~nameWasProvided,options.name='TMR Mach7 圆柱/20°外扩Sutherland-SA-noft2耦合五量数值研究';end
end
P=axisymmetricFVState(result.Q(:,1:4),gas);info=result.finalInfo;
assert(isfield(info,'sa')&&isfield(info,'turbulenceImplemented')&&info.turbulenceImplemented&& ...
    isfield(info,'turbulenceValidated')&&~info.turbulenceValidated&& ...
    strcmp(info.sa.modelID,'SA-noft2-nonnegative-AJS2012-v1'), ...
    'AxisFV:TmrSAViewIdentity','须是真实五量SA候选数值研究，不能当已验证湍流场。');
boundaryInputs=validateSABoundary(boundary,gas);
assert(isequaln(P,info.primitive)&&~info.physicalSolution&&~info.eligibleForSurfaceCoverage, ...
    'AxisFV:TmrSAViewState','Q、EOS和终态身份不一致。');
try
    [replayRate,replayInfo]=axisymmetricRANSResidual(result.Q,mesh,gas,boundary);
catch exception
    error('AxisFV:TmrSAViewReplay','完整五量SA方程拒绝当前检查点：%s。',exception.message);
end
assert(isequaln(replayInfo,info)&& ...
    isequal(replayRate,(-mesh.incidence*info.faceFluxIntegralPerRadian+info.cellSourceIntegral)./mesh.volumePerRadian)&& ...
    max(abs(replayRate)./result.residualScale,[],'all')==result.residualNorm, ...
    'AxisFV:TmrSAViewReplay','当前完整五量SA算子不能逐值重放气体/边界/壁热/原残差。');
assert(size(replayRate,2)==5&&size(info.faceFluxIntegralPerRadian,2)==5&& ...
    size(info.cellSourceIntegral,2)==5&&info.sa.cellModel.constants.turbulentPrandtl==.90&& ...
    all(info.sa.nuTilde==result.Q(:,5)./result.Q(:,1))&&info.sa.wallMuTIsZero&& ...
    ~info.sa.wallHeatEnhancementFactorApplied, ...
    'AxisFV:TmrSAViewCoupling','五量完整源/共享通量或原SA耦合身份不一致。');
w=info.wall;ids=w.faceID(:);wallCount=numel(ids);
assert(all(info.sa.faceMuT(ids)==0)&&all(info.sa.faceNuTilde(ids)==0)&& ...
    isequal(info.sa.effectiveFaceMu(ids),w.viscosity)&&isequal(info.sa.effectiveFaceK(ids),w.thermalConductivity), ...
    'AxisFV:TmrSAViewWall','解析墙N=0，muT及湍流导热必须为零；墙热不乘增强因子。');
if variableTransport
    assert(all(isfield(w,{'viscosity','thermalConductivity'}))&&isfield(info,'transport')&& ...
        isequaln(info.transport.model,gas.transport), ...
        'AxisFV:TmrSAViewTransport','局部变输运终态缺少真实墙面mu/k及输入模型绑定。');
    wallTransport=axisymmetricFVTransport(w.temperatureInput,gas);
    assert(isequaln(w.viscosity,wallTransport.mu)&&isequaln(w.thermalConductivity,wallTransport.k)&& ...
        isequaln(info.transport.faceMu(ids),w.viscosity)&& ...
        isequaln(info.transport.faceK(ids),w.thermalConductivity)&& ...
        isequaln(info.transport.faceTemperature(ids),w.temperatureInput), ...
        'AxisFV:TmrSAViewTransport','墙面mu/k须由给定Tw逐面求值，不得用muRef/kRef替代。');
end
assert(wallCount==expectedWallCount&&numel(unique(ids))==expectedWallCount&& ...
    isequal(sort(ids),find(mesh.faces.boundarySide==3))&& ...
    isequal(w.ownerCell,mesh.faces.owner(ids))&&isequal(w.areaPerRadian,mesh.faces.areaPerRadian(ids)), ...
    'AxisFV:TmrSAViewWall','仅接受本档完整jMin墙边，不能遗漏或添加端面。');
% 新策略只对本档完整墙面显式启用；旧缺省数据不新增策略对象或改写旧热流。
wallThermalEnabled=isfield(info,'wallThermalGradient')&&~isempty(info.wallThermalGradient.faceID);
thermalAudit=struct;wallAuditIndex=[];
if wallThermalEnabled
    thermalAudit=info.wallThermalGradient;
    requiredThermal={'kind','faceID','ownerCell','normalXR','tangentXR','normalDistanceM','tangentialOffsetM', ...
        'cellTemperatureK','wallTemperatureInputK','tangentialGradientInputKm','normalGradientKm', ...
        'oldGradientXR','gradientXR','oldTangentialGradientKm','skewRatio','cellStateClipped','scope'};
    assert(all(isfield(thermalAudit,requiredThermal))&& ...
        strcmp(thermalAudit.kind,'explicit-Dirichlet-tangent-wall-temperature-gradient-v1')&& ...
        isfield(boundary.jMin,'thermalGradient')&&strcmp(boundary.jMin.thermalGradient,'dirichlet-tangent')&& ...
        numel(thermalAudit.faceID)==wallCount&&numel(unique(thermalAudit.faceID))==wallCount&& ...
        isequal(sort(thermalAudit.faceID),sort(ids))&&~thermalAudit.cellStateClipped, ...
        'AxisFV:TmrSAViewWallThermal','显式墙热策略需要本档全部墙面的原始Dirichlet切向audit，不能省略或改成旧策略。');
    [present,wallAuditIndex]=ismember(ids,thermalAudit.faceID);assert(all(present));
    assert(isequal(thermalAudit.ownerCell(wallAuditIndex),w.ownerCell)&& ...
        isequal(thermalAudit.wallTemperatureInputK(wallAuditIndex),w.temperatureInput)&& ...
        isequal(thermalAudit.normalXR(wallAuditIndex,:),w.normal)&& ...
        all(thermalAudit.tangentialGradientInputKm==0)&&all(thermalAudit.normalDistanceM>0)&& ...
        all(isfinite(thermalAudit.gradientXR),'all'), ...
        'AxisFV:TmrSAViewWallThermal','等温墙gt必须为0，audit须逐面绑定owner/Tw/真实法向和正距离。');
    thermalQ=-w.thermalConductivity.*thermalAudit.normalGradientKm(wallAuditIndex);
    heatBudget=128*eps*(abs(thermalQ)+abs(w.heatFluxIntoWall));
    assert(all(abs(thermalQ-w.heatFluxIntoWall)<=heatBudget), ...
        'AxisFV:TmrSAViewWallThermal','墙signed热流不能脱离显式audit法向梯度及当前分子k(Tw)。');
end
x=mesh.X(:,1);r=mesh.R(:,1);dx=diff(x);dr=diff(r);L=hypot(dx,dr);slope=dr./dx;
assert(all(dx<0)&&all(r>0)&&all(abs(slope)<1e-12|abs(slope+tand(20))<1e-5)&& ...
    any(abs(slope)<1e-12)&&any(abs(slope+tand(20))<1e-5), ...
    'AxisFV:TmrSAViewGeometry','专用页要求原X递减圆柱加20度外扩壁，不用于任意箭体。');
wallSegment=zeros(wallCount,1);tol=2048*eps(max(abs([x;r])));
for j=1:wallCount
    candidates=find(abs((r(1:end-1)+r(2:end)).*L/2-w.areaPerRadian(j))<=tol);
    expectedPoint=([x(1:end-1),r(1:end-1)].*(2*r(1:end-1)+r(2:end))+ ...
        [x(2:end),r(2:end)].*(r(1:end-1)+2*r(2:end)))./(3*(r(1:end-1)+r(2:end)));
    candidates=candidates(vecnorm(expectedPoint(candidates,:)-w.centroid(j,:),2,2)<=tol);
    assert(isscalar(candidates),'AxisFV:TmrSAViewWall','源墙面无法唯一对应原jMin节点边。');wallSegment(j)=candidates;
end
assert(isequal(sort(wallSegment),(1:wallCount)'),'AxisFV:TmrSAViewWall','源墙边映射不完整。');

%% 二、旋转共享圆环；锥面参数对角划分的两个真面积分别按r0+2r1和2r0+r1积分
ns=double(options.azimuthSegments);theta=(0:ns-1)'*(2*pi/ns);deltaTheta=2*pi/ns;
visualMesh=struct('V',zeros(ni*ns,3),'F',zeros(wallCount*2*ns,3));nf=wallCount*2*ns;
for ix=1:ni
    row=(ix-1)*ns+(1:ns);visualMesh.V(row,:)=[x(ix)*ones(ns,1),r(ix)*cos(theta),r(ix)*sin(theta)];
end
sourceWallIndex=zeros(nf,1);curvedArea=zeros(nf,1);surfaceKind=cell(nf,1);parameterTriangle=zeros(nf,1);
for j=1:wallCount
    ix=wallSegment(j);base=(ix-1)*ns;
    for k=1:ns
        next=mod(k,ns)+1;a=base+k;b=base+ns+k;c=base+ns+next;d=base+next;
        rows=(j-1)*2*ns+(k-1)*2+(1:2);triangles=[a b c;a c d];
        for t=1:2
            xyz=visualMesh.V(triangles(t,:),:);center=mean(xyz,1);rr=hypot(center(2),center(3));
            expected=[w.normal(j,1),w.normal(j,2)*center(2:3)/rr];
            if dot(cross(xyz(2,:)-xyz(1,:),xyz(3,:)-xyz(1,:)),expected)<0,triangles(t,:)=triangles(t,[1 3 2]);end
        end
        visualMesh.F(rows,:)=triangles;sourceWallIndex(rows)=j;parameterTriangle(rows)=[1;2];
        curvedArea(rows)=L(ix)*deltaTheta*[r(ix)+2*r(ix+1);2*r(ix)+r(ix+1)]/6;
    end
    rows=(j-1)*2*ns+(1:2*ns);label='数值研究 · 圆柱墙';
    if abs(dr(ix))>tol,label='数值研究 · 20°外扩墙';end
    surfaceKind(rows)={label};
end
visualMesh.localGeometry=struct('region',{surfaceKind});data=buildAerothermalViewerData(visualMesh);
template=data.fields(1);data.fields=struct([]);area=data.faceArea;wallArea=2*pi*w.areaPerRadian;
sourceAreaFromTriangles=accumarray(sourceWallIndex,curvedArea,[wallCount 1]);
assert(max(abs(sourceAreaFromTriangles-wallArea))<1e-12*sum(wallArea),'AxisFV:TmrSAViewArea','逐参数三角形真面积未还原源旋转曲面积。');
trueArea=sum(wallArea);facetArea=sum(area);trueHeat=sum(wallArea.*w.heatFluxIntoWall);
facetHeat=sum(area.*w.heatFluxIntoWall(sourceWallIndex));
audit=struct('kind','piecewise-linear-surface-of-revolution-versus-faceted-display', ...
    'azimuthSegments',ns,'sourceWallFaces',wallCount,'displayTriangleCount',nf, ...
    'physicalCurvedWallAreaM2',trueArea,'displayFacetedAreaM2',facetArea,'displayToCurvedAreaRatio',facetArea/trueArea, ...
    'physicalCurvedWallHeatW',trueHeat,'displayFacetedHeatIntegralW',facetHeat, ...
    'sourceWallHeatPerRadianW',sum(w.areaPerRadian.*w.heatFluxIntoWall), ...
    'physicalMovingWallPowerW',2*pi*sum(w.mechanicalPowerIntoFluidPerRadian), ...
    'physicalWallEnergyFluxOutW',2*pi*sum(w.totalEnergyFluxOutPerRadian), ...
    'renderedHeatFluxWasRenormalized',false,'endcapFaces',0,'newProductionSolvedAreaM2',0, ...
    'parameterTriangleAreaFormula','L*deltaTheta*(r0+2*r1)/6 and L*deltaTheta*(2*r0+r1)/6', ...
    'actualExpansionAngleDeg',atand(-slope(abs(dr)>tol)), ...
    'areaNote','逐墙真面积2*pi*integral(r ds)；锥面参数对角三角真面积不相等。显示/CSV使用弦面平三角面积，signed q原值不缩放。');
data.coordinateNote='SI · 主轴X · 来流-X · 仅TMR圆柱和20°外扩墙；两端开口，无鼻部/底面';
data.flowDirection=[-1 0 0];data.missingReason=repmat({''},nf,1);data.heatingGaps=struct([]);
data.gridIdentity=gridIdentity;
sourceBindings=currentBindings(root,variableTransport);
data.researchIdentity=struct('kind','TMR-axisymmetric-SA-noft2-five-quantity-numerical-study', ...
    'source',options.evidenceSource,'currentSourceBindings',sourceBindings,'currentSpatialResidualReplayPassed',true, ...
    'steadyConverged',true,'physicalSolution',false,'eligibleForSurfaceCoverage',false,'experimentalValidation',false, ...
    'wholeRocketValidated',false,'turbulentTmrBenchmarkValidated',false,'newProductionSolvedAreaM2',0, ...
    'newSolvedSurfaceAreaM2',0,'axialEndsArePhysicalWalls',false,'timeKind','pseudo-time-steady-search', ...
    'pseudoTimeIsPhysical',false,'physicalTimeAdvancedS',0);
data.wallBinding=struct('sourceWallIndex',sourceWallIndex,'sourceFaceID',ids(sourceWallIndex), ...
    'ownerCell',w.ownerCell(sourceWallIndex),'meridionalSegment',wallSegment(sourceWallIndex), ...
    'parameterTriangle',parameterTriangle,'curvedAreaPerTriangleM2',curvedArea, ...
    'sourceAreaPerRadianM2',w.areaPerRadian(sourceWallIndex),'sourceFluidNormalXR',w.normal(sourceWallIndex,:), ...
    'sourcePressurePa',w.pressure(sourceWallIndex),'sourceHeatFluxIntoWallWm2',w.heatFluxIntoWall(sourceWallIndex), ...
    'sourceTemperatureInputK',w.temperatureInput(sourceWallIndex),'sourceVelocityInputXR',w.velocityInput(sourceWallIndex,:));
if wallThermalEnabled
    % 完整原audit不压缩为通过标志；另外保存逐显示面索引，探针/CSV可追到源梯度。
    data.wallThermalGradient=thermalAudit;sourceThermalIndex=wallAuditIndex(sourceWallIndex);
    data.wallThermalBinding=struct('policy','dirichlet-tangent','sourceAuditIndex',sourceThermalIndex, ...
        'sourceFaceID',thermalAudit.faceID(sourceThermalIndex),'ownerCell',thermalAudit.ownerCell(sourceThermalIndex), ...
        'normalDistanceM',thermalAudit.normalDistanceM(sourceThermalIndex), ...
        'tangentialOffsetM',thermalAudit.tangentialOffsetM(sourceThermalIndex), ...
        'tangentialGradientInputKm',thermalAudit.tangentialGradientInputKm(sourceThermalIndex), ...
        'normalGradientKm',thermalAudit.normalGradientKm(sourceThermalIndex), ...
        'gradientXR',thermalAudit.gradientXR(sourceThermalIndex,:), ...
        'wallTemperatureInputK',thermalAudit.wallTemperatureInputK(sourceThermalIndex), ...
        'ownerTemperatureProxyK',thermalAudit.cellTemperatureK(sourceThermalIndex), ...
        'cellTemperatureMeaning','EOS of conservative FV means used as point proxy, not exact cell mean or centroid temperature', ...
        'heatFluxDefinition','signed q=-k(Tw)*normalGradient; no abs, clipping or multiplier');
    data.researchIdentity.wallThermalGradientPolicy='dirichlet-tangent';
    data.researchIdentity.wallThermalGradientReplayed=true;
end
if variableTransport
    data.researchIdentity.kind='TMR-axisymmetric-Sutherland-SA-noft2-five-quantity-numerical-study';
    data.researchIdentity.turbulenceTransportImplemented=true;
    data.researchIdentity.turbulenceValidated=false;
    data.researchIdentity.localVariableTransport=true;
    data.wallBinding.sourceViscosityPaS=w.viscosity(sourceWallIndex);
    data.wallBinding.sourceThermalConductivityWmK=w.thermalConductivity(sourceWallIndex);
    data.wallBinding.transportEvaluationTemperatureInputK=w.temperatureInput(sourceWallIndex);
    data.transport=struct('kind','explicit-local-Sutherland-laminar-transport', ...
        'modelInput',gas.transport,'referenceViscosityPaS',gas.transport.referenceViscosity, ...
        'referenceTemperatureK',gas.transport.referenceTemperature, ...
        'sutherlandTemperatureK',gas.transport.sutherlandTemperature, ...
        'referenceConductivityWmK',gas.k,'constantPrandtl',gas.Pr, ...
        'caloricModel','calorically perfect EOS; explicit constant gamma/R/cp; not variable heat capacity', ...
        'conductivityModel','k(T)=cp*mu(T)/constant Pr; no independent measured conductivity fit', ...
        'scalarGasMuMeaning','muRef at referenceTemperature; not current cell/face/wall viscosity', ...
        'scalarGasKMeaning','cp*muRef/Pr at referenceTemperature; not current local conductivity', ...
        'evaluationPolicy','cellwise Barth-Jespersen bounded constitutive face/source T; original viscous/thermal gradients unchanged; exact prescribed Tw at walls', ...
        'numericalTemperatureReconstruction',info.transport.reconstruction.kind, ...
        'limitedTemperatureCellCount',info.transport.reconstruction.limitedCellCount, ...
        'wallSourceFaceID',ids,'wallTemperatureInputK',w.temperatureInput, ...
        'wallViscosityPaS',w.viscosity,'wallThermalConductivityWmK',w.thermalConductivity, ...
        'temperatureDomainNote','gas.temperatureRange is numerical acceptance, not transport/chemistry accuracy certification', ...
        'parameterSource','Explicit gas.transport input; axisymmetricFVTransport evaluates the stated law', ...
        'wallCoefficientValueKind','constitutive model evaluated at prescribed wall temperature; not an independent solved transport unknown');
    [canonicalGas,provenance]=createTmrAxisymmetricAirGas;
    if isequaln(gas,canonicalGas),data.transport.parameterProvenance=provenance;end
    if wallThermalEnabled
        data.transport.evaluationPolicy=['本构温度采用逐格Barth-Jespersen有界采样；内场热/黏性WLS不改；' ...
            '墙系数严格在给定Tw处取值，墙热梯度显式采用Dirichlet切向约束。'];
    end
end
data.wallBinding.sourceTurbulentViscosityPaS=info.sa.faceMuT(ids(sourceWallIndex));
