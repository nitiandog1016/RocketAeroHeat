function validateFiveQuantityLedger(result,mesh)
% 模块用途：重算真实五量初末体积积分和本段BE账，不能仅信一个已通过标志。
names={'initialConservedIntegral','finalConservedIntegral','accumulatedBoundaryIntegral','accumulatedSourceIntegral'};
assert(isequal(size(result.initialQ),[mesh.cellCount 5])&&all(isfinite(result.initialQ),'all')&& ...
    isequal(size(result.residualScale),[1 5])&&all(isfinite(result.residualScale)&result.residualScale>0), ...
    'AxisFV:TmrSAViewLedger','初场和原固定尺度必须完整包含第五量。');
for j=1:numel(names)
    value=result.(names{j});
    assert(isnumeric(value)&&isreal(value)&&isequal(size(value),[1 5])&&all(isfinite(value)), ...
        'AxisFV:TmrSAViewLedger','四量账不可充当五量账，积分须有限。');
end
initial=sum(result.initialQ.*mesh.volumePerRadian,1);final=sum(result.Q.*mesh.volumePerRadian,1);
assert(isequal(initial,result.initialConservedIntegral)&&isequal(final,result.finalConservedIntegral), ...
    'AxisFV:TmrSAViewLedger','初末五量体积积分与真实Q不能逐值重算。');
totalScale=sum(mesh.volumePerRadian)*result.residualScale;
relative=abs(final-initial+result.accumulatedBoundaryIntegral-result.accumulatedSourceIntegral)./totalScale;
h=result.history;n=result.acceptedSteps;tol=result.options.conservationTolerance;
assert(isstruct(h)&&all(isfield(h,{'stepDefect','balance','residual','newtonDefect','newtonTarget'}))&& ...
    isequal(size(h.stepDefect),[n+1 5])&&numel(h.balance)==n+1&&numel(h.residual)==n+1&& ...
    numel(h.newtonDefect)==n+1&&numel(h.newtonTarget)==n+1&& ...
    all(isfinite(h.stepDefect),'all')&&all(isfinite(h.balance))&&all(isfinite(h.residual))&& ...
    all(isfinite(h.newtonDefect))&&all(isfinite(h.newtonTarget))&& ...
    all(abs(h.stepDefect)./totalScale<=tol,'all')&&all(h.balance<=tol)&& ...
    all(h.newtonDefect<=h.newtonTarget)&&all(relative<=tol)&&max(relative)==result.globalBalanceRelative, ...
    'AxisFV:TmrSAViewLedger','五量逐步/累计BE账或原Newton接受门槛不成立，不能生成稳态页面。');
end

function inputs=validateSABoundary(boundary,gas)
% 模块用途：冻结三个储库的给定N/nu=5身份，不能误写muT/mu=5或称实验入口。
inputs=struct([]);names={'iMin','iMax','jMax'};
for j=1:numel(names)
    bc=boundary.(names{j});
    assert(isfield(bc,'nuTilde')&&isnumeric(bc.nuTilde)&&isreal(bc.nuTilde)&& ...
        isscalar(bc.nuTilde)&&isfinite(bc.nuTilde)&&bc.nuTilde>0, ...
        'AxisFV:TmrSAViewBoundary','三条开放边须明确给定有限正nuTilde常储库。');
    laminar=axisymmetricFVTransport(bc.primitive(4),gas);nu=laminar.mu/bc.primitive(1);
    ratio=bc.nuTilde/nu;
    assert(isfinite(ratio)&&abs(ratio/5-1)<1e-12,'AxisFV:TmrSAViewBoundary', ...
        '专用TMR研究页要求原给定nuTilde/nu∞=5，不能静默换入口或误用muT/mu。');
    item=struct('side',names{j},'nuTildeInputM2s',bc.nuTilde, ...
        'laminarKinematicViscosityM2s',nu,'nuTildeToLaminarKinematicViscosity',ratio, ...
        'turbulentToLaminarViscosity',ratio^4/(ratio^3+7.1^3), ...
        'valueKind','prescribed numerical reservoir, not measured turbulence profile');
    if isempty(inputs),inputs=item;else,inputs(end+1)=item;end %#ok<AGROW>
end
end
