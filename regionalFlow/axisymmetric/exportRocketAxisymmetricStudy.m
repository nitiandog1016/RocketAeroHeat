function validateResult(result,item)
% 模块用途：零步初猜、假物理时刻、旧气体/几何、四量账或放宽原门槛全部拒绝。
mesh=item.mesh;
required={'Q','initialQ','gas','geometryBinding','steadyConverged','stopReason','acceptedSteps', ...
    'residualNorm','residualScale','history','options','finalInfo','pseudoTime','pseudoTimeIsPhysical', ...
    'physicalTimeAdvanced','physicalSolution','eligibleForSurfaceCoverage','wallTemperatureValueKind', ...
    'globalBalanceRelative','initialConservedIntegral','finalConservedIntegral', ...
    'accumulatedBoundaryIntegral','accumulatedSourceIntegral'};
assert(isstruct(result)&&isscalar(result)&&all(isfield(result,required)), ...
    'RocketAxisView:Identity','缺少原五量推进结果或完整接受历史。');
validateattributes(result.acceptedSteps,{'numeric'},{'real','finite','scalar','integer','positive'});
validateattributes(result.pseudoTime,{'numeric'},{'real','finite','scalar','positive'});
assert(isequal(result.physicalSolution,false)&&isequal(result.eligibleForSurfaceCoverage,false)&& ...
    ~isfield(result,'time')&&isequal(result.pseudoTimeIsPhysical,false)&&isequal(result.physicalTimeAdvanced,0)&& ...
    strcmp(result.wallTemperatureValueKind,'prescribed')&&isequaln(result.gas,item.gas)&& ...
    isequal(result.initialQ,item.Q)&&isequal(result.residualScale,item.residualScale)&& ...
    isnumeric(result.Q)&&isreal(result.Q)&&isequal(size(result.Q),[mesh.cellCount 5])&& ...
    all(isfinite(result.Q),'all')&&all(result.Q(:,5)>=0), ...
    'RocketAxisView:Identity','仅接收从同一完整域初猜真实推进的五量数值端点，不能标为物理解。');
binding=struct('X',mesh.X,'R',mesh.R,'cells',mesh.cells,'volumePerRadian',mesh.volumePerRadian);
assert(isequaln(result.geometryBinding,binding)&&isequaln(buildAxisymmetricFVGeometry(mesh.X,mesh.R),mesh), ...
    'RocketAxisView:Binding','原FV几何绑定或完整度量不能逐值重建。');
o=result.options;
assert(all(isfield(o,{'steadyResidualTolerance','steadyRequiredSteps','minimumSteadySteps', ...
    'conservationTolerance','nonlinearAbsoluteTolerance','nonlinearRelativeTolerance'}))&& ...
    o.steadyResidualTolerance==2e-6&&o.steadyRequiredSteps==3&&o.minimumSteadySteps>=3&& ...
    o.conservationTolerance==5e-10&&o.nonlinearAbsoluteTolerance==1e-11&&o.nonlinearRelativeTolerance==1e-9, ...
    'RocketAxisView:Acceptance','必须保留原稳态、五量守恒及Newton接受门槛。');
names={'initialConservedIntegral','finalConservedIntegral','accumulatedBoundaryIntegral','accumulatedSourceIntegral'};
for k=1:numel(names)
    value=result.(names{k});assert(isnumeric(value)&&isreal(value)&&isequal(size(value),[1 5])&&all(isfinite(value)), ...
        'RocketAxisView:Ledger','五量积分必须完整有限，四量账不能冒充五量账。');
end
initial=sum(result.initialQ.*mesh.volumePerRadian,1);final=sum(result.Q.*mesh.volumePerRadian,1);
assert(isequal(initial,result.initialConservedIntegral)&&isequal(final,result.finalConservedIntegral), ...
    'RocketAxisView:Ledger','原初末Q体积积分不能逐值重算。');
totalScale=sum(mesh.volumePerRadian)*result.residualScale;
relative=abs(final-initial+result.accumulatedBoundaryIntegral-result.accumulatedSourceIntegral)./totalScale;
h=result.history;n=result.acceptedSteps;
requiredHistory={'stepDefect','balance','residual','newtonDefect','newtonTarget','pseudoTime','dt'};
assert(isstruct(h)&&all(isfield(h,requiredHistory))&&isequal(size(h.stepDefect),[n+1 5]), ...
    'RocketAxisView:Ledger','原五量逐步缺陷或历史数量与接受步数不符。');
for key=requiredHistory(2:end)
    value=h.(key{1});assert(isnumeric(value)&&isreal(value)&&isvector(value)&& ...
        numel(value)==n+1&&all(isfinite(value)),'RocketAxisView:Ledger','原接受历史不完整或非有限。');
end
assert(all(isfinite(h.stepDefect),'all')&&all(h.balance>=0&h.balance<=o.conservationTolerance)&& ...
    all(abs(h.stepDefect)./totalScale<=o.conservationTolerance,'all')&& ...
    all(h.newtonDefect>=0&h.newtonDefect<=h.newtonTarget)&&all(h.newtonTarget>=0)&& ...
    all(h.residual>=0)&&h.residual(end)==result.residualNorm&& ...
    h.pseudoTime(1)==0&&h.dt(1)==0&&all(h.dt(2:end)>0)&& ...
    isequal(cumsum(h.dt(:)),h.pseudoTime(:))&&h.pseudoTime(end)==result.pseudoTime&& ...
    all(relative<=o.conservationTolerance)&&max(relative)==result.globalBalanceRelative&& ...
    h.balance(end)==result.globalBalanceRelative, ...
    'RocketAxisView:Ledger','原五量逐步/累计BE账、Newton接受或真实伪时间历史不成立。');
assert(islogical(result.steadyConverged)&&isscalar(result.steadyConverged), ...
    'RocketAxisView:Steady','稳态身份须为逻辑标量。');
passed=n>=max(3,o.minimumSteadySteps)&&all(h.residual(end-2:end)<=2e-6);
assert(isequal(result.steadyConverged,passed)&& ...
    (~passed||strcmp(result.stopReason,'steady-residual-converged')), ...
    'RocketAxisView:Steady','稳态标签与原连续三步残差门槛不一致。');
end

function audit=validateAcceptedChain(result,item,folder,root,checkpointKind)
% 模块用途：逐真实端点重算BE和原Newton目标；多步必须绑定不可变检查点链。
% 单步已有完整初末Q，可独立验算；多步只有累计摘要不足以证明每一步确实接受。
n=result.acceptedSteps;mesh=item.mesh;gas=item.gas;boundary=item.boundary;
if isempty(folder)
    assert(n==1,'RocketAxisView:Checkpoint','多步结果必须显式给checkpointFolder，不能只信历史摘要。');
    entries=[];chain=[];
else
    target=fullfile(folder,'rocket_axisymmetric_evidence.mat');
    chain=load(target,'caseDefinition','implicit','durable');
    assert(all(isfield(chain,{'caseDefinition','implicit','durable'}))&& ...
        isequaln(chain.caseDefinition,item)&&isequaln(chain.implicit,result)&& ...
        strcmp(chain.durable.kind,checkpointKind)&& ...
        numel(chain.durable.steps)==n,'RocketAxisView:Checkpoint','检查点主记录与当前原工况/聚合端点不一致。');
    entries=chain.durable.steps;
    for k=1:numel(chain.durable.sourceBindings)
        binding=chain.durable.sourceBindings(k);
        assert(strcmp(fileSHA(fullfile(root,binding.path)),binding.sha256), ...
            'RocketAxisView:Checkpoint','真实求解源码已变化，不能沿用旧端点。');
    end
end
Q=item.Q;[beforeRate,beforeInfo]=axisymmetricRANSResidual(Q,mesh,gas,boundary);
scale=result.residualScale;totalScale=sum(mesh.volumePerRadian)*scale;V=mesh.volumePerRadian;
initial=sum(Q.*V,1);net=zeros(1,5);src=net;times=0;residuals=max(abs(beforeRate)./scale,[],'all');
solverContract=rocketAxisymmetricSolverContract(item);
balances=0;stepDefects=zeros(1,5);stepDefectBudgets=zeros(1,5);targets=0;defects=0;nextCFL=solverContract.initialPseudoCFL;maxBERatio=0;
stepSHA=cell(n,1);
for k=1:n
    if isempty(folder),s=result;
    else
        name=sprintf('steps/step_%06d.mat',k);path=fullfile(folder,name);entry=entries(k);
        stepSHA{k}=fileSHA(path);
        assert(entry.number==k&&strcmp(entry.relativePath,name)&&strcmp(entry.sha256,stepSHA{k}), ...
            'RocketAxisView:Checkpoint','不可变端点缺失、断号、改字节或重排。');
        payload=load(path,'segment','stepContext');
        assert(all(isfield(payload,{'segment','stepContext'}))&& ...
            payload.stepContext.number==k&&payload.stepContext.matlabProcessID==entry.matlabProcessID&& ...
            isequaln(payload.stepContext.sourceBindings,chain.durable.sourceBindings), ...
            'RocketAxisView:Checkpoint','真实端点进程或源码身份断链。');
        s=payload.segment;
    end
    assert(s.acceptedSteps==1&&isequal(s.initialQ,Q)&&isequal(s.residualScale,scale)&& ...
        isequaln(s.gas,gas)&&~s.physicalSolution&&~s.eligibleForSurfaceCoverage&& ...
        ~s.pseudoTimeIsPhysical&&s.physicalTimeAdvanced==0, ...
        'RocketAxisView:Endpoint','每个原始单步必须与前一真实Q相接并保持研究身份。');
    o=s.options;
    assert(o.initialPseudoCFL==nextCFL&&o.steadyResidualTolerance==2e-6&& ...
        o.steadyRequiredSteps==3&&o.minimumSteadySteps==3&&o.conservationTolerance==5e-10&& ...
        o.nonlinearAbsoluteTolerance==1e-11&&o.nonlinearRelativeTolerance==1e-9&& ...
        o.differenceStep==solverContract.differenceStep&&o.maximumPseudoCFL==solverContract.maximumPseudoCFL&&strcmp(o.differenceScheme,'central')&& ...
        o.jacobianRefreshEvery==1&&o.maxNewtonIterations==24, ...
        'RocketAxisView:Endpoint','逐步原数值方法、CFL或门槛变化。');
    [afterRate,afterInfo]=axisymmetricRANSResidual(s.Q,mesh,gas,boundary);
    assert(isequaln(afterInfo,s.finalInfo),'RocketAxisView:Endpoint','逐步完整五量方程不能重放。');
    dt=s.history.dt(end);assert(isfinite(dt)&&dt>0);
    explicit=1/max(beforeInfo.convectiveFrequency+beforeInfo.diffusiveFrequency);
    target=1e-11+1e-9*max(abs(dt*(beforeRate./scale)),[],'all');
    U0=Q./scale;U1=s.Q./scale;be=U1-U0-dt*(afterRate./scale);
    roundoff=512*eps*max(abs(U0)+abs(U1)+abs(dt*(afterRate./scale)),[],'all');
    actual=max(abs(be),[],'all');
    assert(s.history.newtonTarget(end)==target&&actual<=target+roundoff&& ...
        abs(s.history.newtonDefect(end)-actual)<=roundoff&& ...
        isequal(s.accumulatedBoundaryIntegral,dt*afterInfo.netBoundaryFlux)&& ...
        isequal(s.accumulatedSourceIntegral,dt*afterInfo.sourceIntegral), ...
        'RocketAxisView:BE','真实单步BE缺陷、Newton目标或实际边界/源积分不成立。');
    if ~isempty(folder)
        ctx=payload.stepContext;
        assert(ctx.explicitStepAtInitialState==explicit&& ...
            ctx.nextPseudoCFL==min(o.maximumPseudoCFL,o.pseudoCFLGrowth*dt/explicit), ...
            'RocketAxisView:Endpoint','真实CFL恢复记录不符。');
    end
    old=sum(Q.*V,1);final=sum(s.Q.*V,1);
    stepDefect=final-old+s.accumulatedBoundaryIntegral-s.accumulatedSourceIntegral;
    assert(all(abs(stepDefect)./totalScale<=5e-10),'RocketAxisView:BE','单步实际五量账不成立。');
    net=net+s.accumulatedBoundaryIntegral;src=src+s.accumulatedSourceIntegral;
    balance=max(abs(final-initial+net-src)./totalScale);
    times(end+1)=times(end)+dt;residuals(end+1)=max(abs(afterRate)./scale,[],'all'); %#ok<AGROW>
    balances(end+1)=balance;stepDefects(end+1,:)=stepDefect;targets(end+1)=target; %#ok<AGROW>
    % 原solver对sum((U1-U0)*scale*V)求账，聚合器对sum(Q1V)-sum(Q0V)求账。
    % 两个合法表达式仅允许各自积分形成的有单位舍入差，不允许容差内任意改账。
    stepDefectBudgets(end+1,:)=512*eps*(sum(abs(s.Q).*V,1)+sum(abs(Q).*V,1)+ ...
        abs(s.accumulatedBoundaryIntegral)+abs(s.accumulatedSourceIntegral)); %#ok<AGROW>
    defects(end+1)=s.history.newtonDefect(end);maxBERatio=max(maxBERatio,actual/(target+roundoff)); %#ok<AGROW>
    Q=s.Q;beforeRate=afterRate;beforeInfo=afterInfo;
    nextCFL=min(o.maximumPseudoCFL,o.pseudoCFLGrowth*dt/explicit);
end
h=result.history;
assert(isequal(Q,result.Q)&&isequal(net,result.accumulatedBoundaryIntegral)&& ...
    isequal(src,result.accumulatedSourceIntegral)&&isequal(times,h.pseudoTime)&& ...
    isequal(residuals,h.residual)&&isequal(balances,h.balance)&& ...
    all(abs(stepDefects-h.stepDefect)<=stepDefectBudgets,'all')&& ...
    isequal(targets,h.newtonTarget)&&isequal(defects,h.newtonDefect)&& ...
    all(balances<=5e-10),'RocketAxisView:Checkpoint','聚合历史或五量账不能从真实端点重建。');
audit=struct('kind','replayed-every-accepted-BE-endpoint-with-original-targets', ...
    'acceptedEndpointsReplayed',n,'immutableChainProvided',~isempty(folder), ...
    'stepSHA256',{stepSHA},'maxBEToOriginalTargetAndRoundoff',maxBERatio, ...
    'fiveQuantityBalanceRelative',balances(end),'originalThresholdsPreserved',true, ...
    'physicalSolution',false,'newProductionSolvedAreaM2',0);
end

function [surface,segment,triangle,curved,audit]=revolveWall(domain,mesh,ns)
% 模块用途：逐段真实旋转，轴极点只有一个顶点；独立审计闭合、面积与实体有向体积。
wall=domain.wallPolylineXR;np=size(wall,1);nw=np-1;theta=(0:ns-1)'*(2*pi/ns);dtheta=2*pi/ns;
assert(wall(1,2)==0&&wall(end,2)==0&&all(wall(2:end-1,2)>0), ...
    'RocketAxisView:Geometry','完整墙母线必须只有真实鼻尖和真实底心两个轴端点。');
surface=struct('V',zeros((np-2)*ns+2,3),'F',zeros((nw-2)*2*ns+2*ns,3));
rings=cell(np,1);rings{1}=1;surface.V(1,:)=[wall(1,1),0,0];
for i=2:np-1
    rings{i}=1+(i-2)*ns+(1:ns);surface.V(rings{i},:)=[repmat(wall(i,1),ns,1),wall(i,2)*cos(theta),wall(i,2)*sin(theta)];
end

rings{np}=size(surface.V,1);surface.V(end,:)=[wall(end,1),0,0];
nf=size(surface.F,1);segment=zeros(nf,1);triangle=segment;curved=segment;row=0;
for i=1:nw
    a=wall(i,:);b=wall(i+1,:);L=norm(b-a);bodyNormal=-mesh.faces.normal(domain.wallBoundaryFaceID(i),:);
    for k=1:ns
        kn=mod(k,ns)+1;
        if i==1
            tris=[rings{i},rings{i+1}(k),rings{i+1}(kn)];weights=L*dtheta*(a(2)+b(2))/2;kind=0;
        elseif i==nw
            tris=[rings{i}(k),rings{i+1},rings{i}(kn)];weights=L*dtheta*(a(2)+b(2))/2;kind=0;
        else
            tris=[rings{i}(k),rings{i+1}(k),rings{i+1}(kn);rings{i}(k),rings{i+1}(kn),rings{i}(kn)];
            weights=L*dtheta*[a(2)+2*b(2);2*a(2)+b(2)]/6;kind=[1;2];
        end
        for t=1:size(tris,1)
            xyz=surface.V(tris(t,:),:);c=mean(xyz,1);r=hypot(c(2),c(3));
            normal=[bodyNormal(1),bodyNormal(2)*c(2:3)/r];
            if dot(cross(xyz(2,:)-xyz(1,:),xyz(3,:)-xyz(1,:)),normal)<0,tris(t,:)=tris(t,[1 3 2]);end
        end
        rows=row+(1:size(tris,1));surface.F(rows,:)=tris;segment(rows)=i;triangle(rows)=kind;curved(rows)=weights;row=rows(end);
    end
end
assert(row==nf,'RocketAxisView:Geometry','完整旋转面数量不符。');
F=surface.F;V=surface.V;e=[F(:,[1 2]);F(:,[2 3]);F(:,[3 1])];[~,~,ic]=unique(sort(e,2),'rows');
count=accumarray(ic,1);direction=sign(e(:,2)-e(:,1));winding=accumarray(ic,direction);
crosses=cross(V(F(:,2),:)-V(F(:,1),:),V(F(:,3),:)-V(F(:,1),:),2);
signedVolume=sum(dot(V(F(:,1),:),crosses,2))/6;
assert(all(count==2)&&all(winding==0)&&all(vecnorm(crosses,2,2)>0)&&signedVolume>0, ...
    'RocketAxisView:Geometry','旋转显示必须闭合、定向一致、无退化面且实体体积为正。');
expectedVolume=domain.sourceTriangulatedBodyVolumeM3;
audit=struct('closedTwoManifold',true,'consistentlyOutwardOriented',true, ...
    'sharedNoseVertex',rings{1},'sharedBaseCenterVertex',rings{np}, ...
    'axisPoleCount',2,'displaySignedVolumeM3',signedVolume,'nativeFacetedBodyVolumeM3',expectedVolume, ...
    'completeMeridionalSegments',nw,'sourceOriginalTriangleProjectionCompleted',false, ...
    'fictitiousEndcapsAdded',false);
end

