function report=exportRocketAxisymmetricStudy(item,result,folder,options)
%EXPORTROCKETAXISYMMETRICSTUDY 将完整真实箭体已接受端点接回离线三维工作台。
% 模块一：逐值重建原工况/完整域，重放五量RANS，核对原五量BE账及墙热来源。
% 模块二：旋转完整细分母线，鼻尖和底心使用共享极点；不增加虚盖或漏掉真实底面。
% 模块三：显示面保持源段常值；真曲面/显示弦面面积及热积分分别列示，不缩放热流。
% 模块四：调用既有离线WebGL导出，再只修改导出副本的研究标签和数据。
% 模块五：非稳态端点明确标为伪时间研究；未定义温度留NaN，给定Tw不能标成壁温解。
% item必须是createRocketAxisymmetricCase的完整原工况；result须真实接受至少一个BE步。
% 默认显示细分母线旋转面；另附原生V/F的保守曲面积投影，两种几何不可混称。
% 本模块不增加生产求解面积，不认证稳态/网格/域独立性或公开实验精度。
if nargin<4,options=struct;end
defaults=struct('azimuthSegments',64,'name','完整零攻角箭体五量SA数值研究', ...
    'title','RocketAeroHeat · 完整箭体数值研究','evidenceSource','调用者提供的真实已接受端点', ...
    'checkpointFolder','');
assert(isstruct(options)&&isscalar(options)&&all(ismember(fieldnames(options),fieldnames(defaults))), ...
    'RocketAxisView:Options','存在未知导出选项。');
for key=fieldnames(defaults)',if ~isfield(options,key{1}),options.(key{1})=defaults.(key{1});end,end
validateattributes(options.azimuthSegments,{'numeric'},{'real','finite','scalar','integer','>=',8,'<=',4096});
options.azimuthSegments=double(options.azimuthSegments);
for key={'name','title','evidenceSource','checkpointFolder'}
    value=options.(key{1});assert((ischar(value)&&(isrow(value)|| ...
        (isempty(value)&&strcmp(key{1},'checkpointFolder'))))||(isstring(value)&&isscalar(value)), ...
        'RocketAxisView:Options','显示说明须为单个文本。');options.(key{1})=char(value);
end
assert((ischar(folder)&&isrow(folder))||(isstring(folder)&&isscalar(folder)), ...
    'RocketAxisView:Options','输出目录须为单一路径。');folder=char(folder);
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));

%% 一、原生工况和源几何逐值重建；不能拿TMR/截断后体或改边界结果冒充完整箭体
requiredItem={'mesh','surfaceMesh','geometryTruth','domain','gas','boundary','Q','residualScale', ...
    'freestream','inputContract','initialization','options'};
assert(isstruct(item)&&isscalar(item)&&all(isfield(item,requiredItem)), ...
    'RocketAxisView:Case','必须附带完整原工况。');
if isfield(item,'caseFactory')
    if isequal(item.caseFactory,'createRocketAxisymmetricWallCase')
        fresh=createRocketAxisymmetricWallCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-controlled-discretization-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricCollarCase')
        fresh=createRocketAxisymmetricCollarCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-collar-family-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricPressureCase')
        fresh=createRocketAxisymmetricPressureCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-pressure-source-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricFluxCase')
        fresh=createRocketAxisymmetricFluxCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-interior-flux-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricLocalCase')
        fresh=createRocketAxisymmetricLocalCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-local-Jacobian-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricRootCase')
        fresh=createRocketAxisymmetricRootCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-spatial-root-confirmed-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricSensitivityCase')
        assert(~isempty(item.options.rootEvidenceSHA256),'RocketAxisView:Case','插值初猜不得当作新网格定常结果。');
        fresh=createRocketAxisymmetricSensitivityCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-sensitivity-root-confirmed-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricWallResolutionCase')
        assert(~isempty(item.options.rootEvidenceSHA256),'RocketAxisView:Case','更细网格上的插值初猜不能当结果。');
        fresh=createRocketAxisymmetricWallResolutionCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-wall-resolution-root-confirmed-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricContactCase')
        assert(~isempty(item.options.rootEvidenceSHA256),'RocketAxisView:Case','同Q通量检查不得当成新定常解。');
        fresh=createRocketAxisymmetricContactCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-contact-root-confirmed-checkpoints-v1';
    elseif isequal(item.caseFactory,'createRocketAxisymmetricContactRefinedCase')
        assert(~isempty(item.options.rootEvidenceSHA256),'RocketAxisView:Case','粗根插值初猜不得当成精网格结果。');
        fresh=createRocketAxisymmetricContactRefinedCase(item.options);
        checkpointKind='rocket-complete-C-domain-SA-contact-refined-root-confirmed-checkpoints-v1';
    else
        error('RocketAxisView:Case','只接受明确登记的完整箭体工况工厂。');
    end
else
    fresh=createRocketAxisymmetricCase(item.options);
    checkpointKind='rocket-complete-C-domain-SA-checkpoints-v1';
end
assert(isequaln(fresh,item),'RocketAxisView:Case','原工况、完整域、原生面元、气体或给定边界不能逐值重建。');
mesh=item.mesh;domain=item.domain;gas=item.gas;boundary=item.boundary;
validateResult(result,item);
checkpointValidation=validateAcceptedChain(result,item,options.checkpointFolder,root,checkpointKind);
[rate,info]=axisymmetricRANSResidual(result.Q,mesh,gas,boundary);
assert(isequaln(info,result.finalInfo)&& ...
    isequal(rate,(-mesh.incidence*info.faceFluxIntegralPerRadian+info.cellSourceIntegral)./mesh.volumePerRadian)&& ...
    max(abs(rate)./result.residualScale,[],'all')==result.residualNorm&& ...
    isequal(info.physicalSolution,false)&&isequal(info.eligibleForSurfaceCoverage,false)&& ...
    info.turbulenceImplemented&&~info.turbulenceValidated&& ...
    strcmp(info.sa.modelID,'SA-noft2-nonnegative-AJS2012-v1'), ...
    'RocketAxisView:Replay','终态、五量完整空间方程、原残差或研究身份不能逐值重放。');
w=info.wall;ids=w.faceID(:);nw=numel(ids);
[present,wallIndex]=ismember(domain.wallBoundaryFaceID,ids);
assert(all(present)&&nw==numel(domain.wallBoundaryFaceID)&&numel(unique(ids))==nw&& ...
    isequal(sort(ids),find(mesh.faces.boundarySide==3))&& ...
    isequal(w.ownerCell,mesh.faces.owner(ids))&&isequal(w.areaPerRadian,mesh.faces.areaPerRadian(ids))&& ...
    isequal(w.centroid,mesh.faces.centroid(ids,:))&&isequal(w.normal,mesh.faces.normal(ids,:))&& ...
    all(isfinite(w.pressure)&w.pressure>0)&&all(isfinite(w.heatFluxIntoWall)), ...
    'RocketAxisView:Wall','源墙必须完整包含鼻部至真实底心的每个FV面、owner及源值。');
assert(all(abs(w.areaPerRadian(wallIndex)-domain.wallAreaPerRadianM2)<= ...
    256*eps*max(domain.wallAreaPerRadianM2)), ...
    'RocketAxisView:Wall','墙面积与真实完整母线不符。');
thermal=info.wallThermalGradient;
[present,thermalIndex]=ismember(ids,thermal.faceID);
assert(all(present)&&numel(thermal.faceID)==nw&&numel(unique(thermal.faceID))==nw&& ...
    strcmp(thermal.kind,'explicit-Dirichlet-tangent-wall-temperature-gradient-v1')&& ...
    ~thermal.cellStateClipped&&isequal(thermal.ownerCell(thermalIndex),w.ownerCell)&& ...
    isequal(thermal.wallTemperatureInputK(thermalIndex),w.temperatureInput)&& ...
    isequal(thermal.normalXR(thermalIndex,:),w.normal)&& ...
    all(thermal.tangentialGradientInputKm==0)&&all(thermal.normalDistanceM>0), ...
    'RocketAxisView:WallThermal','完整墙面Dirichlet切向热梯度来源不成立。');
transport=axisymmetricFVTransport(w.temperatureInput,gas);
signedHeat=-w.thermalConductivity.*thermal.normalGradientKm(thermalIndex);
assert(isequal(w.viscosity,transport.mu)&&isequal(w.thermalConductivity,transport.k)&& ...
    all(abs(signedHeat-w.heatFluxIntoWall)<=128*eps*(abs(signedHeat)+abs(w.heatFluxIntoWall)))&& ...
    all(info.sa.faceNuTilde(ids)==0)&&all(info.sa.faceMuT(ids)==0)&& ...
    isequal(info.sa.effectiveFaceMu(ids),w.viscosity)&&isequal(info.sa.effectiveFaceK(ids),w.thermalConductivity), ...
    'RocketAxisView:WallThermal','墙signed q、当前k(Tw)、墙N=0或muT=0不一致。');

%% 二、完整细分母线旋转；只在真实鼻尖及真实底心合并极点，完整保留底面径向分布
[visualMesh,sourceSegment,parameterTriangle,curvedArea,geometryAudit]=revolveWall(domain,mesh,options.azimuthSegments);
sourceWallIndex=wallIndex(sourceSegment);sourceThermalIndex=thermalIndex(sourceWallIndex);
nf=size(visualMesh.F,1);visualMesh.localGeometry=struct('region',{domain.wallRegion(sourceSegment)});
data=buildAerothermalViewerData(visualMesh);template=data.fields(1);data.fields=struct([]);
area=data.faceArea;trueArea=2*pi*sum(w.areaPerRadian);facetArea=sum(area);
trueHeat=2*pi*sum(w.areaPerRadian.*w.heatFluxIntoWall);
facetHeat=sum(area.*w.heatFluxIntoWall(sourceWallIndex));
areaBySource=accumarray(sourceWallIndex,curvedArea,[nw 1]);
assert(all(abs(areaBySource-2*pi*w.areaPerRadian)<=1024*eps*trueArea), ...
    'RocketAxisView:Area','逐显示三角形真实旋转曲面积不能还原全部源墙面积。');
audit=struct('kind','complete-refined-meridian-revolution-not-original-triangle-projection', ...
    'sourceWallFaces',nw,'displayTriangleCount',nf,'azimuthSegments',options.azimuthSegments, ...
    'revolvedWallAreaM2',trueArea,'displayFacetedAreaM2',facetArea, ...
    'nativeOriginalFacetedAreaM2',domain.sourceTriangulatedWallAreaM2, ...
    'revolvedWallHeatW',trueHeat,'displayFacetedHeatIntegralW',facetHeat, ...
    'sourceWallHeatPerRadianW',sum(w.areaPerRadian.*w.heatFluxIntoWall), ...
    'wallEnergyFluxOutW',2*pi*sum(w.totalEnergyFluxOutPerRadian), ...
    'wallMechanicalPowerIntoFluidW',2*pi*sum(w.mechanicalPowerIntoFluidPerRadian), ...
    'signedHeatFluxWasRenormalized',false,'nativeOriginalTriangleProjectionCompleted',false, ...
    'sourceOriginalTriangleIDsAreCandidatesOnly',true,'geometry',geometryAudit, ...
    'fullBaseAreaM2',domain.fullBaseAreaM2,'fictitiousEndcapsAdded',false,'newProductionSolvedAreaM2',0, ...
    'areaNote','原真实细分母线完整旋转；真曲面积与显示弦面面积分别核对。源段q原值不缩放；原生V/F未投影，候选面编号不是已完成映射。');

%% 二甲、真实曲面积保守投影回原始三角面；不以显示弦面法向宣称压力合力守恒
projection=mapRocketAxisymmetricWall(item);
nativePressure=projection.weights*w.pressure(wallIndex);
nativeHeat=projection.weights*w.heatFluxIntoWall(wallIndex);
nativeTw=projection.weights*w.temperatureInput(wallIndex);
ownerGasTemperature=info.primitive(w.ownerCell,4);
nativeGasTemperature=projection.weights*ownerGasTemperature(wallIndex);
nativeCurvedHeat=sum(projection.sourceCurvedAreaM2.*nativeHeat);
heatBudget=2e-11*sum(2*pi*w.areaPerRadian.*abs(w.heatFluxIntoWall));
assert(abs(nativeCurvedHeat-trueHeat)<=heatBudget, ...
    'RocketAxisView:NativeProjection','真实原三角面投影未保持曲面signed总热。');
[projectionRow,projectionColumn,projectionWeight]=find(projection.weights);
overlapArea=full(projection.overlapAreaM2(sub2ind(size(projection.overlapAreaM2),projectionRow,projectionColumn)));
nativeProjection=struct('kind',projection.kind,'indexBase',0, ...
    'vertices',projection.sourceVertices,'faces',projection.sourceFaces-1, ...
    'sourceFaceID',projection.sourceFaceID,'originalFaceBandID',projection.sourceFaceBandID, ...
    'sourceCurvedAreaM2',projection.sourceCurvedAreaM2,'sourceFacetAreaM2',projection.sourceDisplayFacetAreaM2, ...
    'wallBoundaryFaceID',projection.wallBoundaryFaceID, ...
    'sourceFaceIndex',projectionRow-1,'wallSegmentIndex',projectionColumn-1, ...
    'overlapAreaM2',overlapArea,'weight',projectionWeight, ...
    'pressurePa',nativePressure,'heatFluxIntoWallWm2',nativeHeat,'wallInputK',nativeTw, ...
    'wallAdjacentGasProxyK',nativeGasTemperature,'wallAdjacentGasProxyStatus',ones(size(nativeGasTemperature)), ...
    'pressureStatus',ones(size(nativePressure)),'heatFluxStatus',ones(size(nativeHeat)), ...
    'wallInputStatus',2*ones(size(nativeTw)), ...
    'wallSolvedK',nan(size(nativeTw)),'edgeTemperatureK',nan(size(nativeTw)), ...
    'recoveryTemperatureK',nan(size(nativeTw)), ...
    'unknownTemperatureStatus',zeros(size(nativeTw)), ...
    'pressureMethod','actual five-quantity SA-RANS owner EOS pressure; true-curved-area weighted scalar projection', ...
    'heatFluxMethod','actual signed Fourier q=-k(Tw)*gn; true-curved-area conservative projection, not abs or a heat multiplier', ...
    'wallInputMethod','prescribed Dirichlet Tw, not a solved wall temperature', ...
    'wallAdjacentGasMethod','area-weighted EOS-of-conservative-means owner gas temperature proxy; not wall/edge/recovery temperature', ...
    'gasTemperatureProjectionProvesEnergyConservation',false, ...
    'unknownTemperatureMethod','no independent edge/recovery/wall-temperature solution', ...
    'projectionMethod',projection.projectionMethod,'surfaceDefinition',projection.surfaceDefinition, ...
    'completeCurvedHeatW',nativeCurvedHeat, ...
    'originalFacetHeatIntegralW',sum(projection.sourceDisplayFacetAreaM2.*nativeHeat), ...
    'pressureForceOrMomentConservationEstablished',false, ...
    'originalSourceFacesPreserved',true,'candidateMappingOnly',false, ...
    'physicalSolution',false,'eligibleForSurfaceCoverage',false,'newProductionSolvedAreaM2',0);
audit.nativeOriginalTriangleProjectionCompleted=true;
audit.originalProjectionCurvedHeatW=nativeCurvedHeat;
audit.originalProjectionFacetHeatIntegralW=nativeProjection.originalFacetHeatIntegralW;
audit.displayGeometryIsOriginalNativeTriangles=false;
audit.areaNote=['显示为细分母线完整旋转面，逐显示面q不缩放；另附原生V/F曲面积保守投影。' ...
    '三组真曲/显示弦面/原生弦面面积与热积分分列；标量p投影不保证压力合力或力矩守恒。'];
steady=result.steadyConverged;
if steady,stage='已达原残差稳态的数值研究（未验证物理精度）';
else,stage='未达稳态的已接受伪时间端点，仅供数值研究';end
sourceBindings=currentBindings(root);
identity=struct('kind','complete-rocket-axisymmetric-five-quantity-SA-numerical-study', ...
    'stage',stage,'evidenceSource',options.evidenceSource,'currentSourceBindings',sourceBindings, ...
    'currentSpatialResidualReplayPassed',true,'acceptedSteps',result.acceptedSteps,'steadyConverged',steady, ...
    'physicalSolution',false,'eligibleForSurfaceCoverage',false,'experimentalValidation',false, ...
    'wholeRocketPhysicalSolutionValidated',false,'newProductionSolvedAreaM2',0,'newSolvedSurfaceAreaM2',0, ...
    'timeKind','pseudo-time-steady-search','pseudoTimeIsPhysical',false,'physicalTimeAdvancedS',0, ...
    'nativeOriginalTriangleProjectionCompleted',true,'completeRealWallGeometry',true, ...
    'displayGeometryIsOriginalNativeTriangles',false, ...
    'alphaDeg',0,'betaDeg',0,'nonaxisymmetricProtrusionsSupported',false);
data.researchIdentity=identity;data.surfaceIntegralAudit=audit;data.flowDirection=[-1 0 0];
data.numericalSolver=rocketAxisymmetricSolverContract(item);data.initialization=item.initialization;
data.sourceSurfaceProjection=nativeProjection;data.checkpointValidation=checkpointValidation;
discretizationNote='';
if isfield(item,'caseFactory')
    data.researchIdentity.caseFactory=item.caseFactory;
    data.researchIdentity.wallVelocityGradientPolicy=item.inputContract.wallVelocityGradientPolicy;
    data.researchIdentity.viscousWorkVelocityPolicy=item.inputContract.viscousWorkVelocityPolicy;
    discretizationNote=sprintf(' 壁速度梯度策略=%s；内面黏性功速度策略=%s。', ...
        item.inputContract.wallVelocityGradientPolicy,item.inputContract.viscousWorkVelocityPolicy);
end
if isfield(info,'wallVelocityGradient'),data.wallVelocityGradient=info.wallVelocityGradient;end
if isfield(info,'viscousWorkVelocity'),data.viscousWorkVelocity=info.viscousWorkVelocity;end
if isfield(info,'pressureSourceQuadrature')
    assert(isfield(item.boundary,'pressureSourceQuadrature')&& ...
        strcmp(info.pressureSourceQuadrature.policy,item.boundary.pressureSourceQuadrature), ...
        'RocketAxisView:PressureSource','源积分审计必须与实际边界中的全域离散合同一致。');
    data.pressureSourceQuadrature=info.pressureSourceQuadrature;
    data.researchIdentity.pressureSourceQuadraturePolicy=info.pressureSourceQuadrature.policy;
    discretizationNote=[discretizationNote ' 压力源积分=' info.pressureSourceQuadrature.policy ...
        '；未裁单元压力，积分近似不是新增物理边界。'];
end
if isfield(info,'interiorConvectiveFlux')
    assert(isfield(item.boundary,'interiorConvectiveFlux')&&strcmp(info.interiorConvectiveFlux.policy,item.boundary.interiorConvectiveFlux), ...
        'RocketAxisView:InteriorFlux','内部通量审计须与实际全域离散选项一致。');
    data.interiorConvectiveFlux=info.interiorConvectiveFlux;
    data.researchIdentity.interiorConvectiveFluxPolicy=info.interiorConvectiveFlux.policy;
    discretizationNote=[discretizationNote ' 内部Euler通量=' info.interiorConvectiveFlux.policy ...
        '；开放面HLLE保持，SA采用同一实际质量通量；耗散及物理精度待验证。'];
end
if isfield(item.inputContract,'gridPolicy')
    data.researchIdentity.gridPolicy=item.inputContract.gridPolicy;
    data.researchIdentity.effectiveCollarOptions=item.inputContract.effectiveCollarOptions;
    discretizationNote=[discretizationNote ' 网格策略=' item.inputContract.gridPolicy ...
        '；节点法向偏移不等于体质心墙距；近壁及外域充分性未验收。'];
    if isfield(domain,'collar'),data.normalCollarGeometry=domain.collar;end
end
data.coordinateNote='SI · 主轴X · 鼻尖+X · 零攻角来流-X · 完整真实墙面细分旋转研究';
data.missingReason=repmat({''},nf,1);data.heatingGaps=struct([]);
data.caseNote=sprintf(['%s；%s。完整鼻部、锥/柱段、收缩、后体和真实底面。' ...
    '接受%d个BE伪步，原五量残差%.9g，原稳态门槛2e-6连续3步；伪时间%.9g s不是物理时间。' ...
    '物理结果资格false，新增生产求解面积0。Tw是给定；Te/Tr/求解Tw未知。' ...
    '真曲面积%.12g m²，显示弦面面积%.12g m²；真曲面signed总热%.12g W，显示积分%.12g W。' ...
    '采用细分母线旋转显示；另附原始三角面曲面积保守p/q投影，原F/V保持。'], ...
    options.name,stage,result.acceptedSteps,result.residualNorm,result.pseudoTime,trueArea,facetArea,trueHeat,facetHeat);
data.caseNote=[data.caseNote discretizationNote];
data.resultCondition=struct('caption',data.caseNote,'name',options.name,'sourceMethod',info.method, ...
    'sourceTemperatureModel',info.temperatureModel,'gas',gas,'inputContract',item.inputContract, ...
    'boundaryInput',boundary,'timeKind','pseudo-time-steady-search','pseudoTimeS',result.pseudoTime, ...
    'physicalTimeAdvancedS',0,'steadyConverged',steady,'residualNorm',result.residualNorm, ...
    'steadyTolerance',2e-6,'steadyRequiredSteps',3,'acceptedSteps',result.acceptedSteps, ...
    'globalBEFiveQuantityBalanceRelative',result.globalBalanceRelative,'conservationTolerance',5e-10, ...
    'physicalSolution',false,'newProductionSolvedAreaM2',0);
data.wallBinding=struct('sourceWallIndex',sourceWallIndex,'sourceFaceID',ids(sourceWallIndex), ...
    'ownerCell',w.ownerCell(sourceWallIndex),'meridionalSegment',sourceSegment, ...
    'originalMeridionalSegment',domain.wallSourceOriginalSegment(sourceSegment), ...
    'originalFaceBandID',domain.wallSourceFaceBandID(sourceSegment), ...
    'parameterTriangle',parameterTriangle,'curvedAreaPerTriangleM2',curvedArea, ...
    'sourceAreaPerRadianM2',w.areaPerRadian(sourceWallIndex),'sourceFluidNormalXR',w.normal(sourceWallIndex,:), ...
    'sourcePressurePa',w.pressure(sourceWallIndex),'sourceHeatFluxIntoWallWm2',w.heatFluxIntoWall(sourceWallIndex), ...
    'sourceTemperatureInputK',w.temperatureInput(sourceWallIndex), ...
    'sourceWallAdjacentGasProxyK',ownerGasTemperature(sourceWallIndex), ...
    'sourceViscosityPaS',w.viscosity(sourceWallIndex),'sourceConductivityWmK',w.thermalConductivity(sourceWallIndex), ...
    'sourceVelocityInputXR',w.velocityInput(sourceWallIndex,:), ...
    'sourceOriginalTriangleIDsAreCandidatesOnly',true);
data.wallBinding.originalTriangleCandidates=domain.wallSourceTriangleIDs(sourceSegment);
data.wallThermalGradient=thermal;
data.wallThermalBinding=struct('policy','dirichlet-tangent','sourceAuditIndex',sourceThermalIndex, ...
    'sourceFaceID',thermal.faceID(sourceThermalIndex),'ownerCell',thermal.ownerCell(sourceThermalIndex), ...
    'normalDistanceM',thermal.normalDistanceM(sourceThermalIndex), ...
    'tangentialOffsetM',thermal.tangentialOffsetM(sourceThermalIndex), ...
    'tangentialGradientInputKm',thermal.tangentialGradientInputKm(sourceThermalIndex), ...
    'normalGradientKm',thermal.normalGradientKm(sourceThermalIndex),'gradientXR',thermal.gradientXR(sourceThermalIndex,:), ...
    'wallTemperatureInputK',thermal.wallTemperatureInputK(sourceThermalIndex), ...
    'ownerTemperatureProxyK',thermal.cellTemperatureK(sourceThermalIndex), ...
    'ownerTemperatureMeaning','EOS of conservative FV means used as point proxy, not an exact cell mean temperature');
scope=['完整零攻角无突起箭体；当前五量SA-RANS数值端点，' stage '；未完成公开实验/网格/外域验证。' ...
    '源墙面逐段常值旋转；没有新增生产求解面积，不能代替20度横流或有突起三维解。'];
scope=[scope discretizationNote];
add('heatFlux','墙面热流（数值研究）','kW/m²',w.heatFluxIntoWall(sourceWallIndex)/1000,ones(nf,1), ...
    ['五量耦合SA-noft2-RANS；Fourier signed q=-k(Tw)*gn，正值进入墙；k=cp*mu(Tw)/Pr，显式Sutherland；' ...
    '等温墙Dirichlet切向约束gn=(Tw-Towner)/dn；墙N=0、muT=0，不乘经验增强因子；' info.method],'');
