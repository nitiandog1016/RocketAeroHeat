function report=exportRocketAxisymmetricWorkbench(checkpointFolder,folder,options)
%EXPORTROCKETAXISYMMETRICWORKBENCH 将冻结完整箭体端点接入同窗五步骤科研浏览。
% 模块一：读取原始真实检查点，经完整逐步BE重放后导出结果与原面投影。
% 模块二：原生模型和细分墙网格复用现有WebGL几何管线，不在浏览时重新求解。
% 模块三：同一个侧栏依次查看输入、网格、边界、真实推进及结果，保持同一宿主。
% 模块四：本页是冻结研究快照；默认main的可编辑/可计算五步骤工作流保持。
% 模块五：从实际边界和终态审计导出两个独立离散策略，旧快照缺省仍属v68策略。
if nargin<3,options=struct;end
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
assert(isstruct(options)&&isscalar(options)&&~isfield(options,'checkpointFolder'), ...
    'RocketStudyHost:Options','checkpointFolder由第一参数统一指定。');
assert((ischar(folder)&&isrow(folder))||(isstring(folder)&&isscalar(folder)), ...
    'RocketStudyHost:Folder','输出目录须为单一路径。');folder=char(folder);
target=fullfile(checkpointFolder,'rocket_axisymmetric_evidence.mat');
saved=load(target,'caseDefinition','implicit','report');item=saved.caseDefinition;result=saved.implicit;
options.checkpointFolder=char(checkpointFolder);
view=exportRocketAxisymmetricStudy(item,result,fullfile(folder,'results'),options);
snapshot=load(view.snapshotFile,'visualMesh','data');
geometry=exportRocketTestGeometryView({item.surfaceMesh,snapshot.visualMesh},fullfile(folder,'geometry'), ...
    {'原始闭合箭体三角面 · 无突起 · 仅几何','真实细分墙段旋转网格 · 仅几何'});
for name={'rocket-study.html','rocket-study.css','rocket-study.js'}
    if strcmp(name{1},'rocket-study.html'),destination='index.html';else,destination=name{1};end
    copyfile(fullfile(root,'web',name{1}),fullfile(folder,destination));
end
f=item.inputContract.flight;g=item.domain;h=result.history;
if result.steadyConverged,stage='原残差稳态；物理精度尚未验收';else,stage='未达稳态 · 已接受伪时间端点';end
steps=struct('number',num2cell((0:result.acceptedSteps)'), ...
    'residual',num2cell(h.residual(:)),'dt',num2cell(h.dt(:)),'balance',num2cell(h.balance(:)));
payload=struct('kind','complete-rocket-frozen-research-workbench-v1','stage',stage, ...
    'initialization',item.initialization, ...
    'geometryURL','geometry/index.html','resultsURL','results/index.html', ...
    'resultsJSONURL','results/results.json','nativeProjectionIncluded',true, ...
    'flight',f,'totalLengthM',item.geometryTruth.totalLength, ...
    'sourceVertices',size(item.surfaceMesh.V,1),'sourceFaces',size(item.surfaceMesh.F,1), ...
    'displayFaces',size(snapshot.visualMesh.F,1),'cellCount',item.mesh.cellCount, ...
    'wallSegments',numel(g.wallBoundaryFaceID),'radialLayers',g.options.radialLayers, ...
    'curvedAreaM2',g.fullRevolvedWallAreaM2,'nativeFacetAreaM2',g.sourceTriangulatedWallAreaM2, ...
    'nearWallNormalDistanceM',[min(g.wallNormalDistanceM),max(g.wallNormalDistanceM)], ...
    'boundary',struct('freestreamPrimitiveRhoUxUrT',item.inputContract.freestreamPrimitiveRhoUxUrT, ...
        'wallTemperatureInputK',f.Twall,'nuTildeRatioInput',item.inputContract.nuTildeRatioInput, ...
        'outerRadiusM',g.options.outerRadius,'temperatureRangeK',item.gas.temperatureRange), ...
    'numericalStrategies',numericalStrategies(item,result), ...
    'wallAdjacentGasProxyIncluded',any(strcmp({snapshot.data.fields.key},'wallAdjacentGas')), ...
    'acceptedSteps',result.acceptedSteps,'steadyConverged',result.steadyConverged, ...
    'residual',result.residualNorm,'steadyTolerance',2e-6, ...
    'fiveQuantityBalanceRelative',result.globalBalanceRelative,'steps',steps, ...
    'timeKind','pseudo-time-steady-search','physicalTimeAdvancedS',0, ...
    'readOnlyFrozenStudy',true,'physicalSolution',false,'experimentalValidation',false, ...
    'eligibleForSurfaceCoverage',false,'newProductionSolvedAreaM2',0, ...
    'browserVisualOrWebGLRuntimeVerified',false,'sourceEvidence',target);
json=jsonencode(payload,'ConvertInfAndNaN',true);
if isfield(item,'gridSensitivity'),payload.gridSensitivity=item.gridSensitivity;end
if isfield(item.initialization,'spatialRootHistory')
    r=item.initialization.spatialRootHistory;
    payload.rootIterationHistory=struct('iteration',num2cell(r.iteration(:)),'residual',num2cell(r.residual(:)), ...
        'alpha',num2cell(r.alpha(:)),'boundaryBalance',num2cell(r.boundaryBalance(:)));
    json=jsonencode(payload,'ConvertInfAndNaN',true);
end
writeText(fullfile(folder,'study-data.json'),json);
writeText(fullfile(folder,'study-data.js'),['window.ROCKET_STUDY=' json ';' newline]);
report=struct('status','exported-single-host-five-step-frozen-rocket-research-workbench', ...
    'htmlFile',fullfile(folder,'index.html'),'resultView',view,'geometryFile',geometry, ...
    'dataFile',fullfile(folder,'study-data.json'),'acceptedSteps',result.acceptedSteps, ...
    'readOnlyFrozenStudy',true,'physicalSolution',false,'experimentalValidation',false, ...
    'eligibleForSurfaceCoverage',false,'newProductionSolvedAreaM2',0, ...
    'browserVisualOrWebGLRuntimeVerified',false);
writeText(fullfile(folder,'workbench-summary.json'),jsonencode(report));
end

function strategies=numericalStrategies(item,result)
% 模块用途：绑定真实工况策略；不按工厂默认值或文件名猜测当前端点采用了哪种离散。
wall='legacy';work='legacy-wls';factory='createRocketAxisymmetricCase';
if isfield(item.boundary.jMin,'velocityGradient'),wall=char(item.boundary.jMin.velocityGradient);end
if isfield(item.boundary,'viscousWorkVelocity'),work=char(item.boundary.viscousWorkVelocity);end
if isfield(item,'caseFactory'),factory=item.caseFactory;end
assert(ismember(wall,{'legacy','dirichlet-tangent'})&&ismember(work,{'legacy-wls','arithmetic'}), ...
    'RocketStudyHost:Strategy','未知的墙梯度或内部面黏性功速度策略，不能静默贴标签。');
if isfield(item.inputContract,'wallVelocityGradientPolicy')
    assert(strcmp(wall,item.inputContract.wallVelocityGradientPolicy), ...
        'RocketStudyHost:Strategy','墙梯度输入合同与实际边界策略不一致。');
end
if isfield(item.inputContract,'viscousWorkVelocityPolicy')
    assert(strcmp(work,item.inputContract.viscousWorkVelocityPolicy), ...
        'RocketStudyHost:Strategy','黏性功输入合同与实际边界策略不一致。');
end
grid='star-ray-reference';collar=struct;
if isfield(item.inputContract,'gridPolicy'),grid=item.inputContract.gridPolicy;collar=item.inputContract.effectiveCollarOptions;end
assert(ismember(grid,{'normal-collar','star-ray-reference'}), ...
    'RocketStudyHost:Strategy','未知网格构造策略。');
info=result.finalInfo;hasWall=isfield(info,'wallVelocityGradient');hasWork=isfield(info,'viscousWorkVelocity');
pressure='linear-planar';hasPressure=isfield(info,'pressureSourceQuadrature');
if isfield(item.boundary,'pressureSourceQuadrature'),pressure=char(item.boundary.pressureSourceQuadrature);end
assert(ismember(pressure,{'linear-planar','cell-constant'})&& ...
    hasPressure==isfield(item.boundary,'pressureSourceQuadrature'), ...
    'RocketStudyHost:Strategy','压力源积分输入和终态审计必须一致。');
if hasPressure,assert(strcmp(info.pressureSourceQuadrature.policy,pressure),'RocketStudyHost:Strategy','压力源审计策略不匹配。');end
interior='hllc';hasInterior=isfield(info,'interiorConvectiveFlux');
if isfield(item.boundary,'interiorConvectiveFlux'),interior=char(item.boundary.interiorConvectiveFlux);end
assert(ismember(interior,{'hllc','hlle-davis','hlle-einfeldt'})&&hasInterior==isfield(item.boundary,'interiorConvectiveFlux'), ...
    'RocketStudyHost:Strategy','内部Euler通量输入和终态审计不一致。');
if hasInterior,assert(strcmp(info.interiorConvectiveFlux.policy,interior),'RocketStudyHost:Strategy','内部通量审计不匹配。');end
wallKind='';workKind='';
if hasWall,wallKind=info.wallVelocityGradient.kind;end
if hasWork,workKind=info.viscousWorkVelocity.kind;end
assert(hasWall==strcmp(wall,'dirichlet-tangent')&&hasWork==strcmp(work,'arithmetic'), ...
    'RocketStudyHost:Strategy','终态实际策略审计与真实边界选项不一致。');
strategies=struct('caseFactory',factory,'source','actual-case-definition-boundary-and-replayed-finalInfo', ...
    'gridPolicy',grid,'effectiveCollarOptions',collar, ...
    'wallVelocityGradientPolicy',wall,'viscousWorkVelocityPolicy',work, ...
    'pressureSourceQuadraturePolicy',pressure,'pressureSourceQuadratureAuditPresent',hasPressure, ...
    'interiorConvectiveFluxPolicy',interior,'interiorConvectiveFluxAuditPresent',hasInterior, ...
    'pressureSourceScope','planar-area integral of cell-constant or linear-planar p; pressure face flux and hoop stress unchanged', ...
    'wallVelocityGradientAuditPresent',hasWall,'viscousWorkVelocityAuditPresent',hasWork, ...
    'wallVelocityGradientAuditKind',wallKind,'viscousWorkVelocityAuditKind',workKind, ...
    'wallScope','selected wall Newton stress gradient only; cell WLS, SA and Fourier unchanged', ...
    'workScope','interior viscous energy work velocity only; boundary trace and traction unchanged', ...
    'physicalAccuracyValidated',false,'generalSkewGridPositivityProved',false, ...
    'secondOrderArithmeticReconstructionClaimed',false);
contract=rocketAxisymmetricSolverContract(item);
strategies.jacobianDifferencePolicy=contract.jacobianDifferencePolicy;
strategies.jacobianRelativeStep=contract.differenceStep;
strategies.numericalSolver=contract.solver;
strategies.interiorFluxArithmetic='double';
if isfield(item.boundary,'interiorFluxArithmetic'),strategies.interiorFluxArithmetic=item.boundary.interiorFluxArithmetic;end
if isfield(contract,'initializationSolver'),strategies.initializationSolver=contract.initializationSolver;end
end

function writeText(path,value)
% 模块用途：完整UTF-8中文快照写入，离线打开不依赖服务或网络。
fid=fopen(path,'w','n','UTF-8');assert(fid>=0);guard=onCleanup(@()fclose(fid));fprintf(fid,'%s',value);
end
