function [workVelocity,audit]=axisymmetricViscousWorkVelocity(mesh,cellVelocity,boundary,faceVelocity,traction)
%AXISYMMETRICVISCOUSWORKVELOCITY 显式选择内部面黏性功的一阶速度迹。
% 模块一：全局boundary.viscousWorkVelocity缺省/legacy-wls保留原WLS速度和全部边界迹。
% 模块二：仅arithmetic将内部面功速度改成两侧单元速度代理的算术平均，不裁原始迹。
% 模块三：牵引、动量通量、梯度、hoop及本构不变；边界继续使用原实际黏性速度迹。
% 模块四：保存原/新速度、牵引与逐面真实功积分，不能把一阶平均称为二阶线性重构。
% 本选择便于核对配对动量/能量恒等式，不证明一般偏斜网格正性或物理精度。
f=mesh.faces;nf=numel(f.owner);nc=mesh.cellCount;
assert(isnumeric(cellVelocity)&&isreal(cellVelocity)&&isequal(size(cellVelocity),[nc 2])&& ...
    isnumeric(faceVelocity)&&isreal(faceVelocity)&&isequal(size(faceVelocity),[nf 2])&& ...
    isnumeric(traction)&&isreal(traction)&&isequal(size(traction),[nf 2])&& ...
    all(isfinite([cellVelocity;faceVelocity;traction]),'all'), ...
    'AxisFV:ViscousWorkVelocityState','单元速度、原面速度和牵引必须是完整有限实数两分量数组。');
assert(isstruct(boundary)&&isscalar(boundary)&&all(isfield(boundary,{'iMin','iMax','jMin','jMax'})), ...
    'AxisFV:ViscousWorkVelocityBoundary','黏性功速度需要四条逻辑边的明确边界合同。');
names={'iMin','iMax','jMin','jMax'};
for side=1:4
    bc=boundary.(names{side});
    assert(isstruct(bc)&&isscalar(bc)&&~isfield(bc,'viscousWorkVelocity'), ...
        'AxisFV:ViscousWorkVelocityBoundary','viscousWorkVelocity是全局boundary字段，不能放在单条边内而被静默忽略。');
end
policy='legacy-wls';
if isfield(boundary,'viscousWorkVelocity'),policy=boundary.viscousWorkVelocity;end
assert(((ischar(policy)&&isrow(policy))||(isstring(policy)&&isscalar(policy)&&~ismissing(policy)))&& ...
    ismember(char(policy),{'legacy-wls','arithmetic'}), ...
    'AxisFV:ViscousWorkVelocityBoundary','viscousWorkVelocity只允许legacy-wls或arithmetic。');
policy=char(policy);workVelocity=faceVelocity;
audit=struct('kind','legacy-WLS-viscous-work-velocity-unchanged','policy',policy,'faceID',zeros(0,1));
if strcmp(policy,'legacy-wls'),return;end

%% 一、只对真实内部共享面取两侧一阶平均；不改边界给定或出流黏性迹
assert(all(isfinite(f.owner)&f.owner>=1&f.owner<=nc&f.owner==fix(f.owner))&& ...
    all(isfinite(f.neighbour)&f.neighbour>=0&f.neighbour<=nc&f.neighbour==fix(f.neighbour)), ...
    'AxisFV:ViscousWorkVelocityGeometry','真实共享面必须有有效owner/neighbour，边界neighbour为0。');
ids=find(f.neighbour>0);o=f.owner(ids);j=f.neighbour(ids);bf=mesh.boundaryFaces(:);
assert(numel(unique(bf))==numel(bf)&&isequal(sort(bf),find(f.neighbour==0))&& ...
    isequal(size(f.centroid),[nf 2])&&isequal(size(f.areaPerRadian),[nf 1])&& ...
    all(isfinite(f.centroid),'all')&&all(isfinite(f.areaPerRadian)&f.areaPerRadian>=0)&& ...
    all(f.areaPerRadian(ids)>0), ...
    'AxisFV:ViscousWorkVelocityGeometry','内部面和边界集合、真实面坐标或r权面积不一致。');
old=faceVelocity(ids,:);value=.5*(cellVelocity(o,:)+cellVelocity(j,:));
oldWork=sum(old.*traction(ids,:),2);newWork=sum(value.*traction(ids,:),2);
assert(all(isfinite([value,oldWork,newWork]),'all'), ...
    'AxisFV:ViscousWorkVelocityState','内部面功速度或牵引功非有限，不裁速度或改牵引。');
workVelocity(ids,:)=value;area=f.areaPerRadian(ids);

%% 二、保留无限制原WLS迹和一阶新迹，逐真实面说明功率改变来自何处
audit=struct('kind','explicit-arithmetic-interior-viscous-work-velocity-v1','policy',policy, ...
    'faceID',ids,'ownerCell',o,'neighbourCell',j,'facePointXR',f.centroid(ids,:), ...
    'areaPerRadianM2',area,'ownerVelocityProxyXR',cellVelocity(o,:), ...
    'neighbourVelocityProxyXR',cellVelocity(j,:),'oldVelocityXR',old,'velocityXR',value, ...
    'tractionXR',traction(ids,:),'oldWorkFluxPerAreaWm2',oldWork,'workFluxPerAreaWm2',newWork, ...
    'oldWorkIntegralPerRadianW',oldWork.*area,'workIntegralPerRadianW',newWork.*area, ...
    'differenceIntegralPerRadianW',(newWork-oldWork).*area, ...
    'boundaryFaceID',bf,'boundaryVelocityXR',faceVelocity(bf,:),'boundaryWorkVelocityXR',workVelocity(bf,:), ...
    'boundaryVelocityChanged',false,'tractionChanged',false,'cellStateClipped',false, ...
    'rawVelocityWasClipped',false,'cellVelocityIsExactFVMean',false, ...
    'cellVelocityMeaning','conservative-mean-derived velocities used as point proxies, not exact cell-mean velocities', ...
    'secondOrderLinearReconstructionClaimed',false,'generalSkewGridPositivityProved',false, ...
    'scope','explicit first-order arithmetic interior viscous work velocity only; boundary traces, traction, gradients, hoop, SA and Fourier unchanged; no physical validation');
end
