function [GxT,GrT,audit]=axisymmetricWallThermalGradient(mesh,cellTemperature,boundary,wallFaces,wallTemperature,GxT,GrT)
%AXISYMMETRICWALLTHERMALGRADIENT 显式Dirichlet切向数据约束的斜壁温度梯度。
% 模块一：默认/legacy保留原位移纠正；仅用户明确选dirichlet-tangent的墙改梯度。
% 模块二：t=[-nr,nx]，g·t=gt，g·delta=Tw-Towner，解真实法向分量。
% 模块三：常数Tw的gt严格0；函数Tw必须显式给gt，不能虚构未给的边界导数。
% 模块四：只改Fourier墙面梯度，不裁Q/温度，不改内场WLS/SA或给热流乘因子。
% 注意EOS(守恒均值)仅作单点代理；强拉伸/曲壁/非线性层需网格与物理验证。
f=mesh.faces;nf=numel(f.owner);nc=mesh.cellCount;wallFaces=wallFaces(:);wallTemperature=wallTemperature(:);
assert(isequal(size(cellTemperature),[nc 1])&&isequal(size(GxT),[nf 1])&&isequal(size(GrT),[nf 1])&& ...
    numel(wallFaces)==numel(wallTemperature)&&numel(unique(wallFaces))==numel(wallFaces)&& ...
    all(wallFaces>=1&wallFaces<=nf&wallFaces==fix(wallFaces)), ...
    'AxisFV:WallThermalGeometry','墙梯度需要完整真实单元/面温度、梯度和唯一墙面索引。');
assert(isreal(cellTemperature)&&isreal(wallTemperature)&&isreal(GxT)&&isreal(GrT)&& ...
    all(isfinite([cellTemperature;wallTemperature;GxT;GrT])), ...
    'AxisFV:WallThermalState','温度和输入梯度须为有限实数，不能裁剪或静默替代。');
names={'iMin','iMax','jMin','jMax'};selected=false(numel(wallFaces),1);gt=zeros(numel(wallFaces),1);
for side=1:4
    bc=boundary.(names{side});hasPolicy=isfield(bc,'thermalGradient');hasTangent=isfield(bc,'temperatureTangentialGradient');
    if ~hasPolicy&&~hasTangent,continue;end
    assert(strcmp(bc.type,'wall')&&hasPolicy,'AxisFV:WallThermalBoundary', ...
        '热梯度策略只属于wall，切向导数须同时显式指定thermalGradient策略。');
    policy=bc.thermalGradient;
    assert(((ischar(policy)&&isrow(policy))||(isstring(policy)&&isscalar(policy)&&~ismissing(policy)))&& ...
        ismember(char(policy),{'legacy','dirichlet-tangent'}), ...
        'AxisFV:WallThermalBoundary','thermalGradient只允许legacy或dirichlet-tangent。');
    if strcmp(policy,'legacy')
        assert(~hasTangent,'AxisFV:WallThermalBoundary','legacy不消费切向数据，不能静默忽略所给导数。');continue;
    end
    ids=find(f.boundarySide(wallFaces)==side);selected(ids)=true;
    assert(isfield(bc,'temperature')&&(~isa(bc.temperature,'function_handle')||hasTangent), ...
        'AxisFV:WallThermalBoundary','函数墙温须显式给temperatureTangentialGradient，单位K/m。');
    for k=ids'
        value=0;
        if hasTangent
            value=bc.temperatureTangentialGradient;
            if isa(value,'function_handle'),value=value(f.centroid(wallFaces(k),:));end
        end
        assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value), ...
            'AxisFV:WallThermalBoundary','墙切向温度导数须是有限实标量或返回标量的函数。');
        assert(isa(bc.temperature,'function_handle')||value==0, ...
            'AxisFV:WallThermalBoundary','常数给定墙温的切向导数必须为0，不能给互相矛盾的边界。');
        gt(k)=double(value);
    end
end
ids=wallFaces(selected);o=f.owner(ids);normal=f.normal(ids,:);tangent=[-normal(:,2),normal(:,1)];delta=f.delta(ids,:);
assert(all(f.neighbour(ids)==0)&&all(ismember(f.boundarySide(ids),1:4))&& ...
    all(isfinite([normal,delta]),'all')&&all(abs(sum(normal.^2,2)-1)<=1e-10), ...
    'AxisFV:WallThermalGeometry','显式热梯度只能作用于真实单位外法向的边界墙。');
dn=sum(delta.*normal,2);ds=sum(delta.*tangent,2);
assert(all(isfinite(dn)&dn>0),'AxisFV:WallThermalGeometry','墙面真实法向距离必须严格为正，不以epsilon替代。');
gt=gt(selected);Tw=wallTemperature(selected);Tc=cellTemperature(o);
gn=(Tw-Tc-gt.*ds)./dn;old=[GxT(ids),GrT(ids)];gradient=gt.*tangent+gn.*normal;
assert(all(isfinite(gradient),'all')&&all(isfinite(gn)), ...
    'AxisFV:WallThermalState','显式墙梯度非有限，未裁梯度或改变温度。');
GxT(ids)=gradient(:,1);GrT(ids)=gradient(:,2);
audit=struct('kind','explicit-Dirichlet-tangent-wall-temperature-gradient-v1','faceID',ids,'ownerCell',o, ...
    'normalXR',normal,'tangentXR',tangent,'normalDistanceM',dn,'tangentialOffsetM',ds, ...
    'cellTemperatureK',Tc,'wallTemperatureInputK',Tw,'tangentialGradientInputKm',gt, ...
    'normalGradientKm',gn,'oldGradientXR',old,'gradientXR',gradient, ...
    'oldTangentialGradientKm',sum(old.*tangent,2),'skewRatio',vecnorm(delta,2,2)./dn, ...
    'cellStateClipped',false,'scope','explicit wall Fourier gradient only; EOS of conservative means is a point proxy, not an exact cell-mean temperature; no physical validation');
end
