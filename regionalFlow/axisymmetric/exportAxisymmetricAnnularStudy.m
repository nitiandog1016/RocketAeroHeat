function report=exportAxisymmetricAnnularStudy(mesh,result,folder,options)
%EXPORTAXISYMMETRICANNULARSTUDY 将真实周期环隙NS墙面快照接入既有离线工作台。
% 模块一：核对稳态、守恒量/气体/几何绑定及原墙面数据，不伪造外缘状态。
% 模块二：旋转内外圆柱墙边；两端为轴向周期接口，明确保持开口而不画端盖。
% 模块三：原q密度直接映射，曲面真面积/功率与绘图弦面面积/功率分别记账。
% 模块四：沿用原WebGL、探针、截面和CSV合同；本页只代表数值校核，新增物理解0。
% options仅允许azimuthSegments（默认48）、name、title和evidenceSource。
% result必须由推进器保存gas及geometryBinding；不读取当前待编辑工况。
if nargin<4,options=struct;end
defaults=struct('azimuthSegments',48,'name','v62周期环隙NS数值校核', ...
    'title','RocketAeroHeat · 周期环隙数值校核','evidenceSource','调用者提供的mesh/result冻结快照');
assert(isstruct(options)&&isscalar(options)&&all(ismember(fieldnames(options),fieldnames(defaults))), ...
    'AxisFV:AnnularViewOptions','未知环隙查看选项。');
for key=fieldnames(defaults)',if ~isfield(options,key{1}),options.(key{1})=defaults.(key{1});end,end
validateattributes(options.azimuthSegments,{'numeric'},{'real','finite','scalar','integer','>=',8,'<=',4096});
for key={'name','title','evidenceSource'}
    value=options.(key{1});
    assert((ischar(value)&&isrow(value))||(isstring(value)&&isscalar(value)), ...
        'AxisFV:AnnularViewOptions','名称、标题和证据说明须为单个文本。');
    options.(key{1})=char(value);
end
assert((ischar(folder)&&isrow(folder))||(isstring(folder)&&isscalar(folder)), ...
    'AxisFV:AnnularViewOptions','输出目录须为单个路径。');
folder=char(folder);root=fileparts(fileparts(fileparts(mfilename('fullpath'))));

%% 一、冻结参数、真收敛与当前墙面绑定；仅支持严格同心的周期环隙
requiredMesh={'kind','X','R','cells','vertices','cellCount','volumePerRadian', ...
    'faces','boundaryFaces','periodicI'};
requiredResult={'Q','gas','geometryBinding','steadyConverged','stopReason', ...
    'acceptedSteps','residualNorm','residualScale','options','history','finalInfo','physicalSolution', ...
    'eligibleForSurfaceCoverage','wallTemperatureValueKind'};
assert(isstruct(mesh)&&isscalar(mesh)&&all(isfield(mesh,requiredMesh))&& ...
    strcmp(mesh.kind,'axisymmetric-body-fitted-fv-v1')&&isequal(mesh.periodicI,true), ...
    'AxisFV:AnnularViewGeometry','本页仅接受轴向显式配对周期的贴体环隙网格。');
assert(isstruct(result)&&isscalar(result)&&all(isfield(result,requiredResult))&& ...
    isequal(result.steadyConverged,true)&&strcmp(result.stopReason,'steady-residual-converged')&& ...
    isequal(result.physicalSolution,false)&&isequal(result.eligibleForSurfaceCoverage,false)&& ...
    strcmp(result.wallTemperatureValueKind,'prescribed'), ...
    'AxisFV:AnnularViewIdentity','须为真实达到残差稳态的数值校核；不接受物理覆盖晋升或工作上限。');
binding=result.geometryBinding;
assert(isstruct(binding)&&isscalar(binding)&& ...
    all(isfield(binding,{'X','R','cells','volumePerRadian'}))&& ...
    isequal(binding.X,mesh.X)&&isequal(binding.R,mesh.R)&& ...
    isequal(binding.cells,mesh.cells)&&isequal(binding.volumePerRadian,mesh.volumePerRadian), ...
    'AxisFV:AnnularViewBinding','推进结果绑定的X/R/控制体/体积与当前网格不匹配。');
validateattributes(mesh.X,{'numeric'},{'real','finite','2d','nonempty'});
validateattributes(mesh.R,{'numeric'},{'real','finite','positive','size',size(mesh.X)});
assert(all(size(mesh.X)>=2)&&isequal(mesh.vertices,[mesh.X(:),mesh.R(:)]), ...
    'AxisFV:AnnularViewGeometry','节点矩阵与源子午面顶点不一致。');
x=mesh.X(:,1);r=mesh.R(1,:);scale=max(1,max(abs(mesh.vertices),[],'all'));tol=512*eps(scale);
assert(all(diff(x)>0)&&all(diff(r)>0)&& ...
    max(abs(mesh.X-x),[],'all')<=tol&&max(abs(mesh.R-r),[],'all')<=tol, ...
    'AxisFV:AnnularViewGeometry','仅支持X递增、r递增、轴线X的同心直圆柱环隙。');
gas=axisymmetricFVGas(result.gas);P=axisymmetricFVState(result.Q,gas);
info=result.finalInfo;
assert(size(P,1)==mesh.cellCount&&isstruct(info)&&isscalar(info)&& ...
    all(isfield(info,{'wall','primitive','method','temperatureModel','faceFluxIntegralPerRadian','cellSourceIntegral', ...
    'wallTemperatureValueKind','physicalSolution','eligibleForSurfaceCoverage'}))&& ...
    isequaln(P,info.primitive)&&strcmp(info.wallTemperatureValueKind,'prescribed')&& ...
    isequal(info.physicalSolution,false)&&isequal(info.eligibleForSurfaceCoverage,false), ...
    'AxisFV:AnnularViewState','Q、明确气体模型和终态原始量/研究身份不一致。');
assert(ischar(info.method)&&~isempty(info.method)&&ischar(info.temperatureModel)&&~isempty(info.temperatureModel), ...
    'AxisFV:AnnularViewState','终态必须保留实际算法和热物性来源。');
% 求稳态伪时间不得借用time字段，旧真实RK2推进页的语义保持原样。
isPseudo=isfield(result,'pseudoTime');
if isPseudo
    assert(~isfield(result,'time')&&isfield(result,'pseudoTimeIsPhysical')&& ...
        isequal(result.pseudoTimeIsPhysical,false)&&isfield(result,'physicalTimeAdvanced')&& ...
        isequal(result.physicalTimeAdvanced,0),'AxisFV:AnnularViewTime','伪时间和物理时间身份混淆。');
    timeValue=result.pseudoTime;timeLabel='求稳态伪时间（非物理时间）';
else
    assert(isfield(result,'time'),'AxisFV:AnnularViewTime','缺少明确时间身份。');
    timeValue=result.time;timeLabel='流体推进时间';
end
validateattributes(timeValue,{'numeric'},{'real','finite','scalar','positive'});
validateattributes(result.acceptedSteps,{'numeric'},{'real','finite','scalar','integer','positive'});
validateattributes(result.residualNorm,{'numeric'},{'real','finite','scalar','nonnegative'});
assert(all(isfield(result.options,{'steadyResidualTolerance','steadyRequiredSteps','minimumSteadySteps'}))&& ...
    result.options.steadyResidualTolerance>0&& ...
    result.acceptedSteps>=result.options.minimumSteadySteps&& ...
    result.residualNorm<=result.options.steadyResidualTolerance&& ...
    numel(result.history.residual)>=result.options.steadyRequiredSteps&& ...
    all(result.history.residual(end-result.options.steadyRequiredSteps+1:end)<=result.options.steadyResidualTolerance), ...
    'AxisFV:AnnularViewConvergence','没有匹配的实际连续稳态残差证据。');
w=info.wall;
wallKeys={'faceID','ownerCell','centroid','areaPerRadian','normal','temperatureInput', ...
    'velocityInput','pressure','heatFluxIntoWall','mechanicalPowerIntoFluidPerRadian','totalEnergyFluxOutPerRadian'};
assert(isstruct(w)&&isscalar(w)&&all(isfield(w,wallKeys)), ...
    'AxisFV:AnnularViewWall','缺少完整实际墙面快照。');
wallCount=numel(w.faceID);ids=w.faceID;
validateattributes(ids,{'numeric'},{'real','finite','integer','positive','column','<=',numel(mesh.faces.owner)});
assert(wallCount==2*(numel(x)-1)&&numel(unique(ids))==wallCount&& ...
    isequal(sort(ids),sort(mesh.boundaryFaces(:)))&& ...
    all(ismember(mesh.faces.boundarySide(ids),[3 4]))&& ...
    all(mesh.faces.neighbour(ids)==0), ...
    'AxisFV:AnnularViewWall','墙面须完整覆盖两条径向壁，不能含周期端面或漏面。');
for key={'ownerCell','areaPerRadian','temperatureInput','pressure','heatFluxIntoWall', ...
        'mechanicalPowerIntoFluidPerRadian','totalEnergyFluxOutPerRadian'}
    value=w.(key{1});
    assert(isnumeric(value)&&isreal(value)&&isequal(size(value),[wallCount 1])&&all(isfinite(value)), ...
        'AxisFV:AnnularViewWall','墙面标量须为逐墙面有限实数列向量。');
end
for key={'centroid','normal','velocityInput'}
    value=w.(key{1});
    assert(isnumeric(value)&&isreal(value)&&isequal(size(value),[wallCount 2])&&all(isfinite(value),'all'), ...
        'AxisFV:AnnularViewWall','墙面坐标、法向和速度须为逐墙面二维实数向量。');
end
assert(isequal(w.ownerCell,mesh.faces.owner(ids))&& ...
    isequal(w.centroid,mesh.faces.centroid(ids,:))&& ...
    isequal(w.normal,mesh.faces.normal(ids,:))&& ...
    isequal(w.areaPerRadian,mesh.faces.areaPerRadian(ids))&& ...
    isequal(w.pressure,P(w.ownerCell,5))&&all(w.pressure>0)&&all(w.areaPerRadian>0)&& ...
    all(w.temperatureInput>=gas.temperatureRange(1)&w.temperatureInput<=gas.temperatureRange(2)), ...
    'AxisFV:AnnularViewBinding','原墙面owner/质心/法向/面积/压力或温度域与绑定终态不一致。');
inner=mesh.faces.boundarySide(ids)==3;outer=~inner;
assert(all(abs(w.normal(:,1))<tol)&&all(abs(w.normal(inner,2)+1)<tol)&& ...
    all(abs(w.normal(outer,2)-1)<tol)&& ...
    all(abs(w.centroid(inner,2)-r(1))<tol)&&all(abs(w.centroid(outer,2)-r(end))<tol)&& ...
    all(abs(sum(w.velocityInput.*w.normal,2))<tol), ...
    'AxisFV:AnnularViewWall','内壁流体外法向须为-er、外壁为+er；固定壁不得穿透。');
assert(max(abs(w.totalEnergyFluxOutPerRadian- ...
    (w.heatFluxIntoWall.*w.areaPerRadian-w.mechanicalPowerIntoFluidPerRadian)))< ...
    512*eps(max(1,max(abs(w.totalEnergyFluxOutPerRadian)))), ...
    'AxisFV:AnnularViewWall','原墙热、机械功和墙能量通量身份不一致。');
% 仅重放一次空间算子，不做时间推进；EOS检查本身不能绑定mu/Pr与原墙热。
periodic=struct('type','periodic');
replayBoundary=struct('iMin',periodic,'iMax',periodic, ...
    'jMin',struct('type','wall','temperature',@(point)wallValue(point,'temperature'), ...
    'velocity',@(point)wallValue(point,'velocity')), ...
    'jMax',struct('type','wall','temperature',@(point)wallValue(point,'temperature'), ...
    'velocity',@(point)wallValue(point,'velocity')));
[replayRate,replayInfo]=axisymmetricNavierStokesResidual(result.Q,mesh,gas,replayBoundary);
validateattributes(result.residualScale,{'numeric'},{'real','finite','positive','size',[1 4]});
assert(isequaln(replayInfo.wall,w)&&isequal(replayRate, ...
    (-mesh.incidence*info.faceFluxIntegralPerRadian+info.cellSourceIntegral)./mesh.volumePerRadian)&& ...
    isequal(max(abs(replayRate)./result.residualScale,[],'all'),result.residualNorm), ...
    'AxisFV:AnnularViewReplay','冻结气体、墙条件、原通量或真实残差不能由同一Q重放；拒绝改物性后沿用旧墙热。');

%% 二、用共享圆环节点构造两片开口圆柱；逐三角面保留源墙面/控制体编号
ns=double(options.azimuthSegments);nx=numel(x);theta=(0:ns-1)'*(2*pi/ns);
visualMesh=struct;visualMesh.V=zeros(2*nx*ns,3);visualMesh.F=zeros(2*ns*wallCount,3);
sourceWallIndex=zeros(2*ns*wallCount,1);surfaceKind=cell(2*ns*wallCount,1);
for side=1:2
    radius=r(1);if side==2,radius=r(end);end
    for ix=1:nx
        ring=(side-1)*nx*ns+(ix-1)*ns+(1:ns);
        visualMesh.V(ring,:)=[repmat(x(ix),ns,1),radius*cos(theta),radius*sin(theta)];
    end
end
for j=1:wallCount
    side=1+double(outer(j));
    [distance,ix]=min(abs((x(1:end-1)+x(2:end))/2-w.centroid(j,1)));
    assert(distance<=tol&&abs(w.areaPerRadian(j)/w.centroid(j,2)-(x(ix+1)-x(ix)))<=tol, ...
        'AxisFV:AnnularViewBinding','源墙面质心/面积不能对应原轴向边。');
    base=(side-1)*nx*ns+(ix-1)*ns;
    for k=1:ns
        next=mod(k,ns)+1;a=base+k;b=base+ns+k;c=base+ns+next;d=base+next;
        triangles=[a b c;a c d];
        if outer(j),triangles=triangles(:,[1 3 2]);end
        faces=(j-1)*2*ns+(k-1)*2+(1:2);
        visualMesh.F(faces,:)=triangles;sourceWallIndex(faces)=j;
    end
    faces=(j-1)*2*ns+(1:2*ns);
    label='数值校核 · 内圆柱墙（流体外法向-er）';if outer(j),label='数值校核 · 外圆柱墙（流体外法向+er）';end
    surfaceKind(faces)={label};
end
visualMesh.localGeometry=struct('region',{surfaceKind});
data=buildAerothermalViewerData(visualMesh);template=data.fields(1);data.fields=struct([]);
nf=size(visualMesh.F,1);area=data.faceArea;wallArea=2*pi*w.areaPerRadian;
curvedArea=wallArea(sourceWallIndex)/(2*ns);trueHeat=sum(wallArea.*w.heatFluxIntoWall);
facetHeat=sum(area.*w.heatFluxIntoWall(sourceWallIndex));
ratio=sin(pi/ns)/(pi/ns);facetArea=sum(area);trueArea=sum(wallArea);
assert(abs(facetArea/trueArea-ratio)<1e-12&& ...
    abs(trueArea-2*pi*(r(1)+r(end))*(x(end)-x(1)))<1e-12*max(1,trueArea), ...
    'AxisFV:AnnularViewArea','曲面真面积与圆柱弦面绘图面积不满足独立几何恒等式。');
data.coordinateNote='SI · 主轴X · 内壁流体外法向-er / 外壁+er · 周期接口开口；没有鼻部或端盖';
data.flowDirection=[-1 0 0];data.missingReason=repmat({''},nf,1);data.heatingGaps=struct([]);
data.researchIdentity=struct('kind','annular-axisymmetric-NS-numerical-check', ...
    'physicalSolution',false,'eligibleForSurfaceCoverage',false,'experimentalValidation',false, ...
    'newProductionSolvedAreaM2',0,'newSolvedSurfaceAreaM2',0,'source',options.evidenceSource, ...
    'axisIncluded',false,'axialEndsArePhysicalWalls',false,'steadyConverged',true);
data.wallBinding=struct('sourceWallIndex',sourceWallIndex,'sourceFaceID',ids(sourceWallIndex), ...
    'ownerCell',w.ownerCell(sourceWallIndex),'sourceAreaPerRadianM2',w.areaPerRadian(sourceWallIndex), ...
    'curvedAreaPerTriangleM2',curvedArea,'sourceFluidNormalXR',w.normal(sourceWallIndex,:), ...
    'sourcePressurePa',w.pressure(sourceWallIndex),'sourceHeatFluxIntoWallWm2',w.heatFluxIntoWall(sourceWallIndex), ...
    'sourceTemperatureInputK',w.temperatureInput(sourceWallIndex), ...
    'sourceVelocityInputXR',w.velocityInput(sourceWallIndex,:));
sourceBindings=currentBindings(root,isPseudo);
data.researchIdentity.currentSourceBindings=sourceBindings;
data.researchIdentity.sourceBindingNote='当前源码哈希及一次空间残差重放与本次导出绑定；原NS运行身份由独立推进证据核对';
data.researchIdentity.currentSpatialResidualReplayPassed=true;
audit=struct('kind','curved-cylinder-versus-chordal-display-area-audit','azimuthSegments',ns, ...
    'sourceWallFaces',wallCount,'displayTriangleCount',nf,'physicalCurvedWallAreaM2',trueArea, ...
    'displayFacetedAreaM2',facetArea,'displayToCurvedAreaRatio',facetArea/trueArea, ...
    'exactChordToArcRatio',ratio,'relativeAreaDeficit',1-facetArea/trueArea, ...
    'sourceWallHeatPerRadianW',sum(w.heatFluxIntoWall.*w.areaPerRadian), ...
    'physicalCurvedWallHeatW',trueHeat,'displayFacetedHeatIntegralW',facetHeat, ...
    'physicalMinusFacetedHeatW',trueHeat-facetHeat, ...
    'physicalMovingWallPowerW',2*pi*sum(w.mechanicalPowerIntoFluidPerRadian), ...
    'physicalWallEnergyFluxOutW',2*pi*sum(w.totalEnergyFluxOutPerRadian), ...
    'renderedHeatFluxWasRenormalized',false,'newSolvedSurfaceAreaM2',0, ...
    'physicalSolution',false,'eligibleForSurfaceCoverage',false,'endcapFaces',0, ...
    'areaNote','数据faceArea/CSV及覆盖率使用真实平三角弦面面积；物理曲面热积分单列2*pi*r*dx，原q密度不缩放', ...
    'scope','本页只有周期环隙的两片物理圆柱墙；周期端面保持开口，不是完整箭体或生产覆盖');
data.surfaceIntegralAudit=audit;
data.caseNote=sprintf(['%s；数值校核，新增生产面积0，未认证空气/实验/真实箭体。' ...
    'gamma=%.8g，R=%.8g J/(kg K)，mu=%.8g Pa s，Pr=%.8g；ri=%.8g m，ro=%.8g m，L=%.8g m。' ...
    '给定Tw范围[%.8g, %.8g] K；内壁ux范围[%.8g, %.8g]、外壁ux范围[%.8g, %.8g] m/s。' ...
    '真实稳态残差%.8g，接受%d步，%s%.8g s。' ...
    '曲面面积%.12g m²，弦面绘图面积%.12g m²；原q不缩放。' ...
    '曲面总墙热%.12g W，按绘图面积积分%.12g W。壁温是给定输入。'], ...
    options.name,gas.gamma,gas.R,gas.mu,gas.Pr,r(1),r(end),x(end)-x(1), ...
    min(w.temperatureInput),max(w.temperatureInput),min(w.velocityInput(inner,1)),max(w.velocityInput(inner,1)), ...
    min(w.velocityInput(outer,1)),max(w.velocityInput(outer,1)), ...
    result.residualNorm,result.acceptedSteps,timeLabel,timeValue,trueArea,facetArea,trueHeat,facetHeat);
data.resultCondition=struct('caption',data.caseNote,'name',options.name,'gas',gas, ...
    'radialIntervalM',[r(1) r(end)],'axialIntervalM',[x(1) x(end)], ...
    'periodicAxialBoundary',true,'wallTemperatureInputK',w.temperatureInput, ...
    'wallVelocityInputXR',w.velocityInput,'sourceMethod',info.method, ...
    'sourceTemperatureModel',info.temperatureModel,'timeS',timeValue, ...
    'steadyConverged',true,'residualNorm',result.residualNorm,'acceptedSteps',result.acceptedSteps, ...
    'steadyTolerance',result.options.steadyResidualTolerance, ...
    'fluidPrimitiveRange',struct('densityKgM3',[min(P(:,1)) max(P(:,1))], ...
    'temperatureK',[min(P(:,4)) max(P(:,4))],'pressurePa',[min(P(:,5)) max(P(:,5))]), ...
    'temperatureRangeNote','此范围是EOS(Q均值)所得流体状态；不是外缘温度、真体平均温度、恢复温度或求解壁温');
if isPseudo
    data.resultCondition=rmfield(data.resultCondition,'timeS');
    data.resultCondition.timeKind='pseudo-time-steady-search';
    data.resultCondition.pseudoTimeS=timeValue;data.resultCondition.physicalTimeAdvancedS=0;
    data.resultCondition.temporalMethod='Global backward Euler pseudo-time; coupled Newton; unchanged FV residual';
    data.researchIdentity.timeKind='pseudo-time-steady-search';
    data.researchIdentity.pseudoTimeIsPhysical=false;data.researchIdentity.physicalTimeAdvancedS=0;
end

%% 三、逐变量状态/来源/范围；面元常值保留原q、p和给定Tw的身份
scope=['同心周期环隙的常物性无旋轴对称NS数值校核；未认证r=0、湍流、三维横流、真实箭体或实验。' ...
    '显示面积为弦面三角形；曲面真面积/总墙热单列审计，不缩放原q。'];
add('heatFlux','环隙墙热流（数值校核）','kW/m²',w.heatFluxIntoWall(sourceWallIndex)/1000, ...
    ones(nf,1),['实际终态Fourier墙热；q=-k grad(T)·n_fluid，正值进入墙；' info.method], ...
    [scope '；包括移动壁黏性发热；不把机械功重复加作导热热流'], '');
add('pressure','墙面压力迹（数值校核）','kPa',w.pressure(sourceWallIndex)/1000, ...
    ones(nf,1),['实际终态临壁控制体压力迹；EOS(Q均值)；' info.method],scope,'');
add('wallInput','给定壁温输入（数值校核）','K',w.temperatureInput(sourceWallIndex),2*ones(nf,1), ...
    '原NS壁面Dirichlet温度边界输入；不是求解壁温',scope,'');
add('wallSolved','求解壁温（数值校核未解）','K',nan(nf,1),zeros(nf,1),'未执行独立壁温求解', ...
    scope,'本研究给定Tw，不含壁体/热平衡温度解；不能用输入Tw补齐');
add('edgeTemperature','外缘温度（数值校核未定义）','K',nan(nf,1),zeros(nf,1),'未定义独立边界层外缘温度', ...
    scope,'环隙NS流体体场温度不自动代表外缘温度；当前没有独立外缘接口');
add('recoveryTemperature','恢复温度（数值校核未解）','K',nan(nf,1),zeros(nf,1),'未求解绝热恢复温度', ...
    scope,'本研究仅求给定Tw下的墙热，没有独立绝热壁根；不能借用体场温度或总温');
for j=1:numel(data.regions)
    mask=strcmp(data.region,data.regions(j).name);data.regions(j).fields=struct;
    for k=1:numel(data.fields)
        field=data.fields(k);state=field.status;
        data.regions(j).fields.(field.key)=struct('computedArea',sum(area(mask&state==1)), ...
            'prescribedArea',sum(area(mask&state==2)),'missingArea',sum(area(mask&state==0)));
    end
end

%% 四、冻结完整证据并复制既有查看器；只替换显示文字，不改渲染/导出算法
if ~exist(folder,'dir'),mkdir(folder);end
copyfile(fullfile(root,'web','viewer.css'),fullfile(folder,'viewer.css'));
for name={'section.js','export.js','viewer.js'}
    % 原0/1/2状态与数据合同保持原样，仅本研究页显示“数值校核”。
    code=fileread(fullfile(root,'web',name{1}));
    writeText(fullfile(folder,name{1}),strrep(code,'工程计算','数值校核'));
end
html=fileread(fullfile(root,'web','index.html'));
html=strrep(html,'<title>RocketAeroHeat · 三维结果工作台</title>', ...
    ['<title>' escapeHTML(options.title) '</title>']);
