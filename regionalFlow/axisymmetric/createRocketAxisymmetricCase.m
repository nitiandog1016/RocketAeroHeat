function item=createRocketAxisymmetricCase(options)
%CREATEROCKETAXISYMMETRICCASE 完整零攻角箭体内部外流的五量SA数值工况。
% 模块一：沿用项目飞行输入及标准大气，主轴X、鼻尖+X、来流-X、SI。
% 模块二：从同一闭合真实参数箭体建立外域，鼻部/收缩/后体不另造截断入口。
% 模块三：仅远场、静止墙温及SA远场量为给定；全域均匀流只作数值初猜。
% 模块四：冻结五量尺度与给定量来源，不把初猜、几何通过或数值稳态算生产面积。
% options.flight可逐字段覆盖createCaseConfig.flight；geometry和domain分别传给几何器。
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(root,fullfile(root,'regionalFlow','axisymmetric'));
if nargin<1,options=struct;end
assert(isstruct(options)&&isscalar(options)&& ...
    all(ismember(fieldnames(options),{'flight','geometry','domain','nuTildeRatio'})), ...
    'RocketAxis:Options','只允许flight、geometry、domain和nuTildeRatio。');
cfg=createCaseConfig;flight=cfg.flight;
if isfield(options,'flight')
    f=options.flight;
    assert(isstruct(f)&&isscalar(f)&&all(ismember(fieldnames(f),fieldnames(flight))), ...
        'RocketAxis:Flight','飞行条件只接受项目已有的高度/Mach/攻角/侧滑/墙温。');
    for key=fieldnames(f)',flight.(key{1})=f.(key{1});end
end
for key=fieldnames(flight)'
    value=flight.(key{1});
    assert(isnumeric(value)&&isreal(value)&&isscalar(value)&&isfinite(value), ...
        'RocketAxis:Flight','每个飞行输入必须是有限实数标量。');
end
assert(flight.alpha==0&&flight.beta==0,'RocketAxis:Axisymmetry', ...
    '当前完整轴对称外域仅支持alpha=beta=0，不能代替20度三维横流。');
assert(flight.altitude>=0&&flight.altitude<=86000&&flight.Mach>1, ...
    'RocketAxis:Flight','当前研究切片要求标准大气有效高度及超声速来流。');
geometry=struct('protrusionEnabled',false);domainOptions=struct;
if isfield(options,'geometry'),geometry=options.geometry;end
assert(isstruct(geometry)&&isscalar(geometry),'RocketAxis:Geometry','geometry须为标量结构体。');
if ~isfield(geometry,'protrusionEnabled'),geometry.protrusionEnabled=false;end
assert(isequal(geometry.protrusionEnabled,false),'RocketAxis:Axisymmetry', ...
    '带周向突起的几何不能默默压成轴对称体。');
if isfield(options,'domain'),domainOptions=options.domain;end
[surface,truth]=buildRocketTestBody(geometry);
[mesh,domain]=buildRocketAxisymmetricDomain(surface,truth,domainOptions);

%% 一、标准大气和定比热空气；保留实际EOS与黏度来源，禁止借用TMR流场
freestream=calcFreestream(flight);
referenceTemperature=273.15;sutherlandTemperature=110.4;
referenceViscosity=1.716e-5;
gas=axisymmetricFVGas(struct('gamma',freestream.gamma,'R',freestream.R, ...
    'mu',referenceViscosity,'Pr',.72,'temperatureRange',[40 2000], ...
    'transport',struct('model','sutherland','referenceViscosity',referenceViscosity, ...
        'referenceTemperature',referenceTemperature,'sutherlandTemperature',sutherlandTemperature)));
assert(flight.Twall>=gas.temperatureRange(1)&&flight.Twall<=gas.temperatureRange(2), ...
    'RocketAxis:WallTemperature','给定Tw越出当前显式数值温域。');
primitive=[freestream.density,-freestream.speed,0,freestream.temperature];
axisymmetricFVConservative(primitive,gas);
laminar=axisymmetricFVTransport(primitive(4),gas);
ratio=5;if isfield(options,'nuTildeRatio'),ratio=options.nuTildeRatio;end
assert(isnumeric(ratio)&&isreal(ratio)&&isscalar(ratio)&&isfinite(ratio)&&ratio>=0, ...
    'RocketAxis:Turbulence','nuTildeRatio须显式有限非负；0为零SA输入，不能称已转捩湍流。');
N=ratio*laminar.mu/primitive(1);
boundary=struct('iMin',struct('type','axis','symmetryGradient','mirror-parity'), ...
    'iMax',struct('type','axis','symmetryGradient','mirror-parity'), ...
    'jMin',struct('type','wall','temperature',flight.Twall,'velocity',[0 0], ...
        'thermalGradient','dirichlet-tangent'), ...
    'jMax',struct('type','riemannReservoir','primitive',primitive,'nuTilde',N));

%% 二、全域初猜与固定残差尺度；只有真实推进后才产生数值求解端点
Q0=axisymmetricFVConservative(repmat(primitive,mesh.cellCount,1),gas);
Q=[Q0,repmat(primitive(1)*N,mesh.cellCount,1)];
scale=[primitive(1),primitive(1)*freestream.speed,primitive(1)*freestream.speed, ...
    Q0(1,4),max(primitive(1)*N,laminar.mu)];
initialization=struct('kind','uniform-freestream-interior-numerical-initial-guess', ...
    'allFiveComponentsUniform',true,'timeStepsTaken',0,'initialStateIsSolution',false, ...
    'forebodyProfileImported',false,'externalCFDSolutionImported',false, ...
    'truncatedAfterbodyInletPrescribed',false, ...
    'initialConservedIntegralPerRadian',sum(Q.*mesh.volumePerRadian,1));
inputs=struct('flight',flight,'freestreamPrimitiveRhoUxUrT',primitive, ...
    'wallTemperatureInputK',flight.Twall,'wallTemperatureValueKind','prescribed', ...
    'nuTildeRatioInput',ratio,'farfieldNuTildeInputM2s',N,'turbulentPrandtlInput',.90, ...
    'solverFreestreamViscosityPaS',laminar.mu,'atmosphereReferenceViscosityPaS',freestream.dynamicViscosity, ...
    'solverFreestreamReynoldsPerM',primitive(1)*freestream.speed/laminar.mu, ...
    'flowDirection',[-1 0 0],'units','SI','completeExternalDomain',true, ...
    'gasModel','calorically perfect air; gamma/R from standardAtmosphere; explicit Sutherland', ...
    'transportSource','existing standardAtmosphere: muRef=1.716e-5 at 273.15K, S=110.4K; k=cp*mu/.72', ...
    'temperatureRangeIsNumericalAcceptanceNotPhysicalCertification',true, ...
    'pressureAndHeatNotComputedYet',true,'edgeTemperatureSolved',false, ...
    'recoveryTemperatureSolved',false,'wallTemperatureSolved',false, ...
    'physicalSolution',false,'experimentalValidation',false,'eligibleForSurfaceCoverage',false, ...
    'newProductionSolvedAreaM2',0);
item=struct('mesh',mesh,'surfaceMesh',surface,'geometryTruth',truth,'domain',domain, ...
    'gas',gas,'boundary',boundary,'Q',Q,'residualScale',scale,'freestream',freestream, ...
    'inputContract',inputs,'initialization',initialization,'options',options);
end
