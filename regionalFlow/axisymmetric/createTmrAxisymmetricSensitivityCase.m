function item=createTmrAxisymmetricSensitivityCase(kind,parentEvidenceFile,dataRoot)
%CREATETMRAXISYMMETRICSENSITIVITYCASE 构造冻结TMR节点的四档方向网格敏感性工况。
% 模块一：只读v66真实五量稳态，核对原节点、空气、边界、尺度和完整空间回放。
% 模块二：从NASA原level3节点分离加密流向/法向，禁止几何插值或改动原墙面。
% 模块三：按逻辑父单元复制全部五个守恒量，仅作新网格的数值初猜。
% 模块四：重新计算新网格初始体积分，明列与父网格差异，不声称保守重映射。
% 输入kind：baseline(41x26)、streamwise(81x26)、normal(41x51)、both(81x51)。
% 本函数不推进时间、不建立网格收敛或实验资格；输出仍是待求解的研究工况。
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
if nargin<1||isempty(kind),kind='baseline';end
assert(isText(kind),'AxisFV:TmrSensitivityInput','工况名称必须是单一文本。');kind=char(kind);
assert(ismember(kind,{'baseline','streamwise','normal','both'}), ...
    'AxisFV:TmrSensitivityInput','只接受baseline、streamwise、normal或both四档网格。');
if nargin<2||isempty(parentEvidenceFile)
    parentEvidenceFile=fullfile(root,'outputs','v66_validation','tmr_wall_thermal','tmr_wall_thermal_evidence.mat');
    if ~exist(parentEvidenceFile,'file')
        parentEvidenceFile=fullfile(root,'validation','v66','tmr_wall_thermal','tmr_wall_thermal_evidence.mat');
    end
end
assert(isText(parentEvidenceFile),'AxisFV:TmrSensitivityInput','父检查点必须是单一文件路径。');parentEvidenceFile=char(parentEvidenceFile);
assert(exist(parentEvidenceFile,'file')==2,'AxisFV:TmrSensitivitySource','缺少v66真实稳态检查点。');
if nargin<3||isempty(dataRoot),dataRoot=fullfile(root,'tests','data','tmr_mach7');end
assert(isText(dataRoot),'AxisFV:TmrSensitivityInput','冻结原网格目录必须是单一文本路径。');

%% 一、冻结父状态身份；给定边界及稳态数值资格不能被新网格继承为物理解
parentSHA=fileSHA(parentEvidenceFile);parent=load(parentEvidenceFile,'mesh','gas','boundary','implicit','report');
assert(all(isfield(parent,{'mesh','gas','boundary','implicit','report'})), ...
    'AxisFV:TmrSensitivityParent','父检查点缺少完整网格、气体、边界、结果或报告。');
result=parent.implicit;gas=parent.gas;boundary=parent.boundary;
assert(isstruct(result)&&isscalar(result)&&all(isfield(result, ...
    {'Q','residualScale','steadyConverged','residualNorm','finalInfo','options','history'}))&& ...
    result.steadyConverged&&isfinite(result.residualNorm)&&result.residualNorm<=2e-6&& ...
    isequal(size(result.Q),[1000 5])&&all(isfinite(result.Q),'all')&&all(result.Q(:,5)>=0)&& ...
    isnumeric(result.residualScale)&&isreal(result.residualScale)&&numel(result.residualScale)==5&& ...
    all(isfinite(result.residualScale)&result.residualScale>0), ...
    'AxisFV:TmrSensitivityParent','需要1000格、五量、原门限通过且尺度明确的真实v66稳态。');
assert(isstruct(parent.report)&&isscalar(parent.report)&&all(isfield(parent.report, ...
    {'steadyConverged','wallThermalGradientPolicy','physicalSolution','eligibleForSurfaceCoverage','newProductionSolvedAreaM2'}))&& ...
    parent.report.steadyConverged&&strcmp(parent.report.wallThermalGradientPolicy,'dirichlet-tangent')&& ...
    ~parent.report.physicalSolution&&~parent.report.eligibleForSurfaceCoverage&&parent.report.newProductionSolvedAreaM2==0, ...
    'AxisFV:TmrSensitivityParent','父结果必须保留v66热梯度策略和未获生产/实验资格的身份。');
[expectedGas,~]=createTmrAxisymmetricAirGas;
assert(isequaln(gas,expectedGas),'AxisFV:TmrSensitivityParent','不能在网格敏感性中改变冻结Sutherland空气。');
assert(isstruct(boundary)&&all(isfield(boundary,{'iMin','iMax','jMin','jMax'}))&& ...
    all(isfield(boundary.jMin,{'type','temperature','velocity','thermalGradient'}))&& ...
    strcmp(boundary.jMin.type,'wall')&&isequal(boundary.jMin.temperature,311)&& ...
    isequal(double(boundary.jMin.velocity),[0 0])&&strcmp(boundary.jMin.thermalGradient,'dirichlet-tangent'), ...
    'AxisFV:TmrSensitivityParent','须保持静止311K墙与显式Dirichlet切向热梯度。');
for name={'iMin','iMax','jMax'}
    bc=boundary.(name{1});
    assert(isstruct(bc)&&all(isfield(bc,{'type','primitive','nuTilde'}))&& ...
        strcmp(bc.type,'riemannReservoir')&&isnumeric(bc.primitive)&&isreal(bc.primitive)&& ...
        numel(bc.primitive)==4&&all(isfinite(bc.primitive))&&bc.primitive(1)>0&&bc.primitive(2)<0&&bc.primitive(3)==0&& ...
        isnumeric(bc.nuTilde)&&isreal(bc.nuTilde)&&isscalar(bc.nuTilde)&&isfinite(bc.nuTilde)&&bc.nuTilde>0&& ...
        isequaln(bc,boundary.iMin), ...
        'AxisFV:TmrSensitivityParent','本四档网格只保持原相同HLLE储库/SA输入，不能混入出口或入口改动。');
end
opts=result.options;
assert(isstruct(opts)&&all(isfield(opts,{'steadyResidualTolerance','steadyRequiredSteps','minimumSteadySteps','conservationTolerance','residualScale'}))&& ...
    opts.steadyResidualTolerance==2e-6&&opts.steadyRequiredSteps==3&&opts.minimumSteadySteps==3&& ...
    opts.conservationTolerance==5e-10&&isequal(opts.residualScale,result.residualScale)&& ...
    isfield(result.history,'residual')&&numel(result.history.residual)>=3&&all(result.history.residual(end-2:end)<=2e-6), ...
    'AxisFV:TmrSensitivityParent','不能放宽原稳态三步/守恒门槛或重定尺度。');

%% 二、原level4/level3来源与精确嵌套，直接选节点而不重采样几何
coarse=loadTmrMach7Grid(4,dataRoot);fine=loadTmrMach7Grid(3,dataRoot);
assert(isequal(size(coarse.X),[41 26])&&isequal(size(fine.X),[81 51])&& ...
    isequal(coarse.X,fine.X(1:2:end,1:2:end))&&isequal(coarse.R,fine.R(1:2:end,1:2:end)), ...
    'AxisFV:TmrSensitivityGrid','冻结官方两档节点没有精确嵌套。');
coarseMesh=buildAxisymmetricFVGeometry(coarse.X,coarse.R);
assert(isequaln(parent.mesh,coarseMesh),'AxisFV:TmrSensitivityParent','父几何不是原level4实际FV网格，不能按假设索引复制。');
try
    [parentRate,parentInfo]=axisymmetricRANSResidual(result.Q,parent.mesh,gas,boundary);
catch exception
    error('AxisFV:TmrSensitivityParent','父方程空间回放失败（%s）：%s',exception.identifier,exception.message);
end
residualScale=reshape(double(result.residualScale),1,5);
assert(isequaln(parentInfo,result.finalInfo)&&max(abs(parentRate)./residualScale,[],'all')==result.residualNorm&& ...
    strcmp(parentInfo.sa.modelID,'SA-noft2-nonnegative-AJS2012-v1')&& ...
    parentInfo.sa.cellModel.constants.turbulentPrandtl==.90, ...
    'AxisFV:TmrSensitivityParent','父完整算子/SA/残差不能逐值回放，不能复用陈旧云图状态。');
switch kind
    case 'baseline',factorI=1;factorJ=1;iNodes=1:2:81;jNodes=1:2:51;source=coarse.source;levelDown=4;
    case 'streamwise',factorI=2;factorJ=1;iNodes=1:81;jNodes=1:2:51;source=fine.source;levelDown=3;
    case 'normal',factorI=1;factorJ=2;iNodes=1:2:81;jNodes=1:51;source=fine.source;levelDown=3;
    case 'both',factorI=2;factorJ=2;iNodes=1:81;jNodes=1:51;source=fine.source;levelDown=3;
end
X=fine.X(iNodes,jNodes);R=fine.R(iNodes,jNodes);
if strcmp(kind,'baseline'),mesh=coarseMesh;else,mesh=buildAxisymmetricFVGeometry(X,R);end
assert(isequal(mesh.X,X)&&isequal(mesh.R,R)&&all(mesh.volumePerRadian>0)&& ...
    all(mesh.planarArea>0)&&all(mesh.faces.normalDistance>0)&&~mesh.periodicI&& ...
    isequal(mesh.X(1:factorI:end,1:factorJ:end),coarse.X)&& ...
    isequal(mesh.R(1:factorI:end,1:factorJ:end),coarse.R), ...
    'AxisFV:TmrSensitivityGrid','新网格失去原节点/正几何或父节点身份。');

%% 三、仅作数值初猜的逻辑父单元复制，所有五量原样保留，不作隐式温度/SA修正
[iCell,jCell]=ind2sub(mesh.shape,(1:mesh.cellCount)');
iParent=floor((iCell-1)/factorI)+1;jParent=floor((jCell-1)/factorJ)+1;
parentCellID=sub2ind(coarseMesh.shape,iParent,jParent);Q=result.Q(parentCellID,:);
assert(isequal(size(Q),[mesh.cellCount 5])&&isequal(Q,result.Q(parentCellID,:))&&all(Q(:,5)>=0), ...
    'AxisFV:TmrSensitivityInitialization','逻辑父复制必须逐值保留全部五量。');
axisymmetricFVState(Q(:,1:4),gas);
parentIntegral=sum(result.Q.*coarseMesh.volumePerRadian,1);
initialIntegral=sum(Q.*mesh.volumePerRadian,1);initialDifference=initialIntegral-parentIntegral;
parentVolume=sum(coarseMesh.volumePerRadian);initialVolume=sum(mesh.volumePerRadian);
childVolumeByParent=accumarray(parentCellID,mesh.volumePerRadian,[coarseMesh.cellCount 1]);
groupedVolumeDifference=childVolumeByParent-coarseMesh.volumePerRadian;
assert(strcmp(parentSHA,fileSHA(parentEvidenceFile)),'AxisFV:TmrSensitivitySource','构造工况期间父检查点改变。');

%% 四、明示初始账、固定合同和适用边界；此处没有得到新网格稳态或网格收敛
parentBinding=struct('path',parentEvidenceFile,'sha256',parentSHA,'parentCellCount',coarseMesh.cellCount, ...
    'parentNodeShape',size(coarseMesh.X),'parentOriginalResidual',result.residualNorm, ...
    'completeSpatialReplayPassed',true,'diagnosticResidualEvaluations',1,'gas',gas,'boundary',boundary, ...
    'residualScale',residualScale,'steadyOptions',opts,'initialConservedIntegralPerRadian',parentIntegral, ...
    'physicalSolution',false,'eligibleForSurfaceCoverage',false);
criteria=struct('steadyResidualTolerance',opts.steadyResidualTolerance,'steadyRequiredSteps',opts.steadyRequiredSteps, ...
    'minimumSteadySteps',opts.minimumSteadySteps,'conservationTolerance',opts.conservationTolerance,'residualScale',residualScale);
gridStudy=struct('kind','tmr-directional-original-node-grid-sensitivity-v1','caseID',kind, ...
    'sourceLevelDown',levelDown,'source',source,'officialLevel3IIndices',iNodes,'officialLevel3JIndices',jNodes, ...
    'factorI',factorI,'factorJ',factorJ,'nodeShape',size(X),'cellShape',mesh.shape,'cellCount',mesh.cellCount, ...
    'parentCellID',parentCellID,'parentI',iParent,'parentJ',jParent, ...
    'initialGuessKind','logical-parent-cell-copy-not-conservative-remap', ...
    'initializationCopiesAllFiveConservedComponents',true,'conservativeRemapPerformed',false, ...
    'parentWallNodesPreservedExactly',true,'wallFaceCount',nnz(mesh.faces.boundarySide==3), ...
    'originalSteadyCriteria',criteria,'initialConservedIntegralPerRadian',initialIntegral, ...
    'parentConservedIntegralPerRadian',parentIntegral,'initialIntegralDifferencePerRadian',initialDifference, ...
    'initialIntegralDifferenceOverFixedVolumeScale',initialDifference./(parentVolume*residualScale), ...
    'initialVolumePerRadianM3',initialVolume,'parentVolumePerRadianM3',parentVolume, ...
    'volumeDifferencePerRadianM3',initialVolume-parentVolume,'childGroupedVolumeDifferencePerParentM3',groupedVolumeDifference, ...
    'maximumGroupedVolumeRelativeDifference',max(abs(groupedVolumeDifference)./coarseMesh.volumePerRadian), ...
    'integralAccountingScope','new mesh initial integral is the budget origin; parent integral difference is initialization/geometry diagnostic, not conservation error', ...
    'quantityOrder',{{'mass','axialMomentum','radialMomentum','totalEnergy','rhoNuTilde'}}, ...
    'quantityUnits',{{'kg/rad','kg m/(s rad)','kg m/(s rad)','J/rad','kg m^2/(s rad)'}}, ...
    'timeStepsTaken',0,'physicalTimeAdvancedS',0,'newGridSteadySolved',false,'gridConvergenceEstablished',false, ...
    'physicalSolution',false,'eligibleForSurfaceCoverage',false,'experimentalValidation',false,'newProductionSolvedAreaM2',0);
item=struct('mesh',mesh,'gas',gas,'boundary',boundary,'Q',Q,'residualScale',residualScale, ...
    'parentBinding',parentBinding,'gridStudy',gridStudy);
end

function yes=isText(value)
% 模块用途：只接受可确定的单一路径/名称，拒绝缺失字符串、数字及文本数组。
yes=(ischar(value)&&isrow(value))||(isstring(value)&&isscalar(value)&&~ismissing(value));
end

function digest=fileSHA(path)
% 模块用途：锁定真实父文件完整字节，生成过程不得改写既有证据。
fid=fopen(path,'rb');assert(fid>=0,'AxisFV:TmrSensitivitySource','不能读取父证据。');
cleanup=onCleanup(@()fclose(fid));bytes=fread(fid,Inf,'*uint8');clear cleanup;
md=java.security.MessageDigest.getInstance('SHA-256');md.update(bytes);
digest=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
