function [pressure,audit]=axisymmetricPressureSourceQuadrature(mesh,p,gx,gr,policy)
%AXISYMMETRICPRESSURESOURCEQUADRATURE 显式选择轴对称径向压力源的空间积分近似。
% 模块一：linear-planar用WLS压力在平面质心求积，保持原仿射压力精确性。
% 模块二：cell-constant用同一单元压力的分片常数重构，对平面面积精确积分。
% 模块三：保留原外推压力作为诊断，不裁原始量/守恒量，不按正负切换策略。
% 该选择仅作用于integral(p dA)，不修改面压力通量、hoop黏性应力或壁热。
% p由单元守恒均值经EOS恢复；不声称它是精确压力体平均或精确平面平均。
assert((ischar(policy)&&isrow(policy))||(isstring(policy)&&isscalar(policy)&&~ismissing(policy)), ...
    'AxisFV:PressureQuadraturePolicy','压力源积分策略须为单一文本。');policy=char(policy);
assert(ismember(policy,{'linear-planar','cell-constant'}), ...
    'AxisFV:PressureQuadraturePolicy','压力源积分只支持linear-planar或cell-constant。');
nc=mesh.cellCount;
assert(isnumeric(p)&&isreal(p)&&isnumeric(gx)&&isreal(gx)&&isnumeric(gr)&&isreal(gr)&& ...
    isequal(size(p),[nc 1])&&isequal(size(gx),size(p))&&isequal(size(gr),size(p))&& ...
    all(isfinite([p;gx;gr]))&&all(p>0), ...
    'AxisFV:PressureQuadratureInput','须提供有限正单元压力与有限完整WLS梯度。');
delta=mesh.planarCentroid-mesh.volumeCentroid;
raw=p+gx.*delta(:,1)+gr.*delta(:,2);
if strcmp(policy,'cell-constant'),pressure=p;else,pressure=raw;end
assert(all(isfinite(pressure)&pressure>0), ...
    'AxisFV:PressureSource','所选压力源积分非有限或非正，未裁压力或切换积分策略。');
audit=struct('kind','explicit-axisymmetric-pressure-source-quadrature-v1','policy',policy, ...
    'cellPressureProxyPa',p,'sourcePressureProxyPa',pressure,'rawLinearPlanarPressurePa',raw, ...
    'planarDisplacementXR',delta,'planarAreaM2',mesh.planarArea, ...
    'pressureIntegralPerRadianN',pressure.*mesh.planarArea, ...
    'rawNonpositiveCount',nnz(raw<=0),'rawNonfiniteCount',nnz(~isfinite(raw)), ...
    'cellStateClipped',false,'negativePressureClipped',false,'adaptivePolicyFallback',false, ...
    'pressureFluxModified',false,'hoopStressModified',false,'physicalSolution',false);
end
