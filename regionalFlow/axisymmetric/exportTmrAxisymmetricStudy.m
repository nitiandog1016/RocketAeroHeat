function writeText(path,value)
fid=fopen(path,'w','n','UTF-8');assert(fid>=0,'AxisFV:TmrViewWrite','无法写出文件。');cleanup=onCleanup(@()fclose(fid));
assert(fprintf(fid,'%s',value)>=0,'AxisFV:TmrViewWrite','文件写出失败。');
end
function escaped=escapeHTML(value)
escaped=strrep(value,'&','&amp;');escaped=strrep(escaped,'<','&lt;');escaped=strrep(escaped,'>','&gt;');escaped=strrep(escaped,'"','&quot;');
end
