function [gas,provenance]=createTmrAxisymmetricAirGas
%CREATETMRAXISYMMETRICAIRGAS 冻结TMR定比热空气/Sutherland层流输运切片。
% 模块一：按NASA TMR规定的Rankine参考温度显式转SI，不混用273.15/110.4。
% 模块二：定gamma/R/Pr与原WIND总量入口切片相配；不自动匹配另一组Re。
% 模块三：本接口没有SA变量或湍流输运，温域仅为数值接受域，非精度认证。
reference=491.6*(5/9);sutherland=198.6*(5/9);
gas=struct('gamma',1.4,'R',287.05,'mu',1.716e-5,'Pr',.72, ...
    'temperatureRange',[40 2000], ...
    'transport',struct('model','sutherland','referenceViscosity',1.716e-5, ...
        'referenceTemperature',reference,'sutherlandTemperature',sutherland));
gas=axisymmetricFVGas(gas);
provenance=struct('kind','explicit-TMR-calorically-perfect-laminar-air-transport-v1', ...
    'sourceURL','https://tmbwg.github.io/turbmodels/spalart.html', ...
    'runningNotesURL','https://tmbwg.github.io/turbmodels/noteonrunning.html', ...
    'referenceViscosityPaS',1.716e-5,'referenceTemperatureRankine',491.6, ...
    'sutherlandTemperatureRankine',198.6,'RankineToKelvinFactor',5/9, ...
    'caloricModel','gamma1.4/R287.05 calorically perfect, constantcp; not NASA7', ...
    'conductivityModel','cp*mu(T)/Pr with Pr=.72; not an independent measured k(T) fit', ...
    'temperatureDomainNote','40..2000K is numerical acceptance only; transport/phase/chemistry accuracy not certified over the full interval', ...
    'inletPolicy','Keep prescribed WIND M/p0/T0; do not silently reset rho/p to match rounded Re/m diagram', ...
    'turbulenceImplemented',false,'physicalSolution',false,'eligibleForSurfaceCoverage',false, ...
    'experimentalValidation',false,'newProductionSolvedAreaM2',0);
end
