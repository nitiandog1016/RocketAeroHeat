function report=compareNasaBoattailPressure()
%COMPARENASABOATTAILPRESSURE 对照原图15个实验符号与声速流线工程压力关联。
% 模块一：原图读数与实验总误差分开，所有点保留，不把理论曲线当观测。
% 模块二：给出点误差、等权平均绝对相对差及读图区间传播，不设置虚假验收线。
% 模块三：只比较无量纲p_bt/p_c，不借用名义远场参数补造绝对压力或壁温。
root=fileparts(mfilename('fullpath'));addpath(fullfile(root,'tests'));b=loadNasaBoattailBenchmark();cases=struct([]);
for angle=[6 12 18]
    % 1Pa只作为代数归一化，不是实验柱压；只取该关联的无量纲压力比。
    candidate=estimateSonicBoattailPressure(1,angle);prediction=candidate.candidatePressureRatio;
    points=b.points([b.points.boattailAngleDeg]==angle);observed=[points.pressureRatio];h=[points.ratioDigitizationHalfWidth];
    relative=(prediction-observed)./observed;
    row=struct('angleDeg',angle,'label',sprintf('%d°尾锥',angle),'points',points,'candidate',candidate, ...
        'predictionRatio',prediction,'relativeDifference',relative, ...
        'meanAbsoluteRelativeDifference',mean(abs(relative)), ...
        'maximumAbsoluteRelativeDifference',max(abs(relative)), ...
        'meanSignedRelativeDifference',mean(relative), ...
        'ratioAbsoluteDifference',prediction-observed, ...
        'relativeDifferenceDigitizationLower',(prediction-(observed+h))./(observed+h), ...
        'relativeDifferenceDigitizationUpper',(prediction-(observed-h))./(observed-h), ...
        'experimentalCylinderPressurePa',NaN,'wallTemperatureK',NaN, ...
        'normalizationInputIsMeasuredPressure',false,'pointWeighting','五个图示符号等权；不假定统计独立', ...
        'uncertaintyScope','区间仅传播5像素读图和配准界限；实验总误差未知', ...
        'completeNSRANSExperimentalValidation',false,'productionQualified',false);
    if isempty(cases),cases=row;else,cases(end+1)=row;end %#ok<AGROW>
end
report=struct('status','conditional-engineering-pressure-ratio-versus-digitized-experimental-symbols', ...
    'sourceManifestSHA256',b.sourceManifestSHA256,'cases',cases,'pointCount',15, ...
    'allSelectedPointsRetained',true,'freeStreamPressureUsedAsDenominator',false, ...
    'externalCFDImported',false,'experimentalComparisonPerformed',true, ...
    'completeNSRANSExperimentalValidation',false,'heatValidationComplete',false, ...
    'productionQualified',false,'newProductionSolvedAreaM2',0);
end
