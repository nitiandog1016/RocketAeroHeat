function [mesh,report]=attachThermistorStepComparison(mesh,report)
%ATTACHTHERMISTORSTEPCOMPARISON 将同一热敏珠原面上的两个半步结果接到整步快照。
% 模块一：核对几何、时间起点、两个真实时间层和逐面数据的来源。
[folder,cleanup]=openThermistorArchive('halfsteps'); %#ok<NASGU>
s=jsondecode(fileread(fullfile(folder,'summary.json')));
file=fullfile(folder,'wall.csv');w=readtable(file);base=mesh.thermistorStartup;
one=s.firstHalfEnergy;two=s.secondHalfEnergy;t=mesh.hybridCondition.elapsedPhysicalTimeS;
assert(strcmp(s.bodySHA256,base.bodySHA256) && strcmp(s.meshSHA256,base.meshSHA256) && ...
    strcmp(s.referenceFrameSHA256,base.energy.acceptedFrameSHA256) && ...
    strcmp(s.referenceWallTableSHA256,base.wallTableSHA256) && ...
    strcmp(s.initialSHA256,base.energy.oldFrameSHA256) && strcmp(one.oldFrameSHA256,s.initialSHA256) && ...
    strcmp(one.acceptedFrameSHA256,two.oldFrameSHA256) && strcmp(one.acceptedFrameSHA256,s.intermediateFrameSHA256) && ...
    strcmp(two.acceptedFrameSHA256,s.fineFrameSHA256) && strcmp(cm011FileSHA256(file),s.fineWallTableSHA256) && ...
    s.elapsedPhysicalTimeS==t && one.dtSeconds==two.dtSeconds && one.dtSeconds+two.dtSeconds==t, ...
    'RAH:Bead:TimeSource','两个半步的原面、时间层或来源与整步快照不匹配。');

% 模块二：在原有编号和完整面积上复算功率与两项差值的面积加权 RMS。
b=mesh.hybridWall;n=height(b);area=w.areaM2;
f=mesh.F;v=mesh.V;
triangleArea=vecnorm(cross(v(f(:,2),:)-v(f(:,1),:),v(f(:,3),:)-v(f(:,1),:),2),2,2)/2;
assert(s.originalFaces==n && isequal(w.faceID,b.faceID) && all(isfinite(area) & area>0) && ...
    all(abs(area-triangleArea)<1e-10*area) && ...
    all(isfinite(w.pressurePa) & w.pressurePa>0 & isfinite(w.heatFluxWm2)) && ...
    all(isfinite(w.nearWallCellTemperatureK) & w.nearWallCellTemperatureK>=mesh.hybridCondition.ambientTemperatureK & ...
        w.nearWallCellTemperatureK<=mesh.hybridCondition.wallTemperatureK) && ...
    max(abs(w.pressurePa-mesh.hybridCondition.ambientPressurePa-w.pressureGaugePa))<2e-10, ...
    'RAH:Bead:TimeFields','两个半步的原面编号、面积、表压或温度不符。');
dp=w.pressureGaugePa-b.pressureGaugePa;dq=w.heatFluxWm2-b.heatFluxWm2;
assert(abs(sum(area)-s.areaM2)<1e-11*s.areaM2 && ...
    abs(sum(area.*w.heatFluxWm2)+two.wallReleaseW)<1e-11*two.wallReleaseW && ...
    abs(sqrt(sum(area.*dp.^2)/sum(area))-s.pressurePa.weightedRMS)<1e-10 && ...
    abs(sqrt(sum(area.*dq.^2)/sum(area))-s.heatFluxWm2.weightedRMS)<1e-9, ...
    'RAH:Bead:TimeBalance','全表面积分或同刻差值与登记结果不符。');

% 模块三：保留整步主结果，在每个对照变量中注明独立的源帧和求解方法。
mesh.beadStepComparison=struct('summary',s,'wall',w,'pressureDifferencePa',dp,'heatDifferenceWm2',dq);
mesh.evidenceIdentity.sourceFrame.comparisonFrameSHA256=s.fineFrameSHA256;
mesh.evidenceIdentity.sourceFrame.comparisonIntermediateSHA256=s.intermediateFrameSHA256;
mesh.evidenceIdentity.sourceFrame.comparisonWallSHA256=s.fineWallTableSHA256;
report.timeStepComparison=s;
end
