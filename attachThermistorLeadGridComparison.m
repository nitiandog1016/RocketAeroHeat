function mesh=attachThermistorLeadGridComparison(mesh)
% 模块一：核对 3 m/s 带线试件两次独立求解的几何、工况、原面表和功率。
[folder,guard]=openThermistorArchive('leads3'); %#ok<NASGU>
path=fullfile(folder,'wall.csv');base=readtable(path);body=jsondecode(fileread(fullfile(folder,'body.json')));
ref=jsondecode(fileread(fullfile(folder,'summary.json')));s=mesh.thermistorLead;w=mesh.hybridWall;
native=s;if isfield(s,'referenceNative'),native=s.referenceNative;end
v=mesh.V;f=mesh.F;n=size(f,1);
area=vecnorm(cross(v(f(:,2),:)-v(f(:,1),:),v(f(:,3),:)-v(f(:,1),:),2),2,2)/2;
assert(isequal(v,body.V) && isequal(f,body.F) && strcmp(native.bodySHA256,ref.bodySHA256) && ...
    strcmp(native.caseSHA256,ref.caseSHA256) && strcmp(ref.wallSHA256,cm011FileSHA256(path)) && ...
    isequal(base.faceID,(0:n-1)') && isequal(base.regionID,body.regionID) && all(abs(base.areaM2-area)<1e-18));
assert(abs(area'*base.heatFluxWm2+ref.totalOutwardW)<1e-12 && abs(area'*w.heatFluxWm2+s.totalOutwardW)<1e-12);
% 模块二：同一原面分别相减。两网的首层采样位置已由成品网逐点核对。
c=mesh.hybridCondition;
[base,scale]=scaleThermistorWallField(base,c,c.ambientTemperatureK,305.15,ref.totalOutwardW);
mesh.thermistorLeadGrid=struct('referenceFrame',ref.sourceFrameSHA256,'referenceMesh',ref.meshSHA256, ...
    'referenceWallSHA256',ref.wallSHA256,'referenceOutwardW',ref.totalOutwardW, ...
    'referenceWallK',305.15,'wallK',c.wallTemperatureK,'scale',scale,'outwardW',-area'*base.heatFluxWm2, ...
    'baseHeatFluxWm2',base.heatFluxWm2,'deltaHeatWm2',w.heatFluxWm2-base.heatFluxWm2, ...
    'deltaPressurePa',w.pressurePa-base.pressurePa, ...
    'deltaNearWallK',w.nearWallCellTemperatureK-base.nearWallCellTemperatureK);
end
