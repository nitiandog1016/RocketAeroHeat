function report=inspectPhaseAwareRocketInlet(mesh,fs,maximumWeakTurnDeg)
%INSPECTPHASEAWAREROCKETINLET 原环/实际鼻尖独立核对，不把截面列表末环当鼻尖。
% 模块用途：判断零侧滑箭体两条子午剖面能否从自由流以附体弱波开始。
% 仅几何入口诊断；不把轴对称剖面变成20度攻角的真实三维流场。
assert(fs.beta==0,'RAH:PhaseInlet:Scope','当前几何诊断仅用于零侧滑。');
validateattributes(maximumWeakTurnDeg,{'numeric'},{'scalar','real','finite','positive','<',90});
V=mesh.V;F=mesh.F;sc=mesh.surfaceCoord;
tipID=find(V(:,1)==max(V(:,1)));assert(isscalar(tipID),'RAH:PhaseInlet:Tip','需要唯一几何鼻尖。');
tip=V(tipID,:);ring=V(sc.sectionNodeIDs{end},:);center=sc.sectionCenterYZ(end,:);
radius=mean(vecnorm(ring(:,2:3)-center,2,2));dx=mean(ring(:,1))-tip(1);
assert(dx<0&&radius>0,'RAH:PhaseInlet:Ring','最前截面环与实际端点关系不符。');
angle=atan2d(radius,-dx);wind=angle+fs.alpha;lee=angle-fs.alpha;
area=vecnorm(cross(V(F(:,2),:)-V(F(:,1),:),V(F(:,3),:)-V(F(:,1),:),2),2,2)/2;
incident=any(F==tipID,2);
report=struct('meshSHA256',phaseAwareMeshIdentity(mesh),'faces',size(F,1),'areaM2',sum(area), ...
    'tipVertexID',tipID,'tip',tip,'lastRingX',mean(ring(:,1)),'lastRingRadiusM',radius, ...
    'lastRingIsNotTip',true,'tipAdjacentFaces',nnz(incident),'tipAdjacentAreaM2',sum(area(incident)), ...
    'meridianInclinationDeg',angle,'windwardFirstTurnDeg',wind,'leewardFirstTurnDeg',lee, ...
    'maximumWeakShockTurnDeg',maximumWeakTurnDeg, ...
    'bothMeridiansOutsideAttachedWeakBranch',min(wind,lee)>maximumWeakTurnDeg, ...
    'geometryOnlyDiagnostic',true,'oldEdgeValuesUsed',false, ...
    'newCandidateHeatAreaM2',0,'newQualifiedAreaM2',0,'originalFaceStatesProduced',false, ...
    'needs','脱体钝鼻/亚声速至声速线外缘和相容边界层入口历史；不可重置下游起点');
end
