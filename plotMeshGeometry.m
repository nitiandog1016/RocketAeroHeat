function plotMeshGeometry(mesh, cfg)
%% ========================================================================
% plotMeshGeometry.m
%
% 三维箭体工程气动 / 气动热计算程序
%
% STL 三角面元 + 表面法向交互显示
%
% ========================================================================
%
% 功能：
%
% 1. 显示最终三角面网格
% 2. 显示部分表面法向
% 3. 鼠标拖动实现 360° 三维旋转
% 4. 鼠标滚轮实现相机缩放
% 5. 防止放大后模型被坐标轴裁剪
% 6. 使用正交投影，适合工程几何检查
%
%
% 主要解决：
%
% 以前放大模型以后出现：
%
%       模型像被平面切开
%
% 的问题。
%
% 原因通常是：
%
%       Axes Clipping
%       Perspective Camera
%       Zoom 修改可视范围
%
%
% 当前版本使用：
%
%       ax.Clipping = 'off'
%
%       camproj(ax,'orthographic')
%
%       camzoom(...)
%
% 从而避免模型被裁掉。
%
%% ========================================================================


%% ========================================================================
% 1. 创建图窗
% ========================================================================

fig = figure( ...
    'Color', 'w', ...
    'Name', 'STL Geometry and Surface Normals', ...
    'NumberTitle', 'off');


%% ========================================================================
% 2. 创建三维坐标轴
% ========================================================================

ax = axes( ...
    'Parent', fig);


hold(ax,'on');


%% ========================================================================
% 3. 三角面边线设置
% ========================================================================

showEdges = true;


if isfield(cfg,'plot') && ...
        isfield(cfg.plot,'showEdges')

    showEdges = ...
        cfg.plot.showEdges;

end


if showEdges

    edgeColor = ...
        [0.30 0.30 0.30];

    edgeAlpha = ...
        0.55;

else

    edgeColor = ...
        'none';

    edgeAlpha = ...
        0;

end


%% ========================================================================
% 4. 绘制三角表面
% ========================================================================

patch( ...
    'Parent', ax, ...
    'Faces', mesh.F, ...
    'Vertices', mesh.V, ...
    'FaceColor', [0.72 0.75 0.78], ...
    'EdgeColor', edgeColor, ...
    'EdgeAlpha', edgeAlpha, ...
    'FaceAlpha', 1.0);


%% ========================================================================
% 5. 显示表面法向
% ========================================================================

showNormals = true;


if isfield(cfg,'plot') && ...
        isfield(cfg.plot,'showNormals')

    showNormals = ...
        cfg.plot.showNormals;

end


if showNormals && ...
        isfield(mesh,'center') && ...
        isfield(mesh,'normal')


    %% --------------------------------------------------------------------
    % 三角面数量
    %% --------------------------------------------------------------------

    numberFaces = ...
        size(mesh.F,1);


    %% --------------------------------------------------------------------
    % 最大显示法向数量
    %% --------------------------------------------------------------------

    maxNormalNumber = 500;


    if isfield(cfg,'plot') && ...
            isfield(cfg.plot,'maxNormalNumber')

        maxNormalNumber = ...
            cfg.plot.maxNormalNumber;

    end


    numberNormals = ...
        min( ...
        numberFaces, ...
        maxNormalNumber);


    %% --------------------------------------------------------------------
    % 均匀抽样
    %% --------------------------------------------------------------------

    sampleIndex = ...
        round( ...
        linspace( ...
        1, ...
        numberFaces, ...
        numberNormals));


    sampleIndex = ...
        unique(sampleIndex);


    %% --------------------------------------------------------------------
    % 排除坏面元
    %% --------------------------------------------------------------------

    if isfield(mesh,'badFace')

        validSample = ...
            ~mesh.badFace(sampleIndex);


        sampleIndex = ...
            sampleIndex(validSample);

    end


    %% --------------------------------------------------------------------
    % 面心
    %% --------------------------------------------------------------------

    C = ...
        mesh.center(sampleIndex,:);


    %% --------------------------------------------------------------------
    % 法向
    %% --------------------------------------------------------------------

    N = ...
        mesh.normal(sampleIndex,:);


    %% --------------------------------------------------------------------
    % 删除 NaN / Inf
    %% --------------------------------------------------------------------

    valid = ...
        all(isfinite(C),2) ...
        & ...
        all(isfinite(N),2);


    C = ...
        C(valid,:);


    N = ...
        N(valid,:);


    %% --------------------------------------------------------------------
    % 模型特征尺寸
    %% --------------------------------------------------------------------

    modelRange = ...
        max(mesh.V,[],1) ...
        - ...
        min(mesh.V,[],1);


    characteristicLength = ...
        max(modelRange);


    %% --------------------------------------------------------------------
    % 法向长度
    %% --------------------------------------------------------------------

    normalScale = 0.03;


    if isfield(cfg,'plot') && ...
            isfield(cfg.plot,'normalScale')

        normalScale = ...
            cfg.plot.normalScale;

    end


    normalLength = ...
        characteristicLength ...
        * ...
        normalScale;


    %% --------------------------------------------------------------------
    % 绘制红色法向
    %% --------------------------------------------------------------------

    quiver3( ...
        ax, ...
        C(:,1), ...
        C(:,2), ...
        C(:,3), ...
        normalLength*N(:,1), ...
        normalLength*N(:,2), ...
        normalLength*N(:,3), ...
        0, ...
        'Color', [1 0 0], ...
        'LineWidth', 1.0, ...
        'MaxHeadSize', 0.6);

end


%% ========================================================================
% 6. 模型坐标范围
% ========================================================================

xmin = min(mesh.V(:,1));

xmax = max(mesh.V(:,1));

ymin = min(mesh.V(:,2));

ymax = max(mesh.V(:,2));

zmin = min(mesh.V(:,3));

zmax = max(mesh.V(:,3));


dx = xmax-xmin;

dy = ymax-ymin;

dz = zmax-zmin;


%% ========================================================================
% 7. 给坐标范围增加一定余量
% ========================================================================
%
% 防止模型刚好贴在 Axes 边界。
%
% 这里使用模型最大尺寸的 5%。
%

L = max([dx dy dz]);


margin = ...
    0.05 * L;


if margin <= 0

    margin = 1;

end


xlim(ax, ...
    [xmin-margin, ...
     xmax+margin]);


ylim(ax, ...
    [ymin-margin, ...
     ymax+margin]);


zlim(ax, ...
    [zmin-margin, ...
     zmax+margin]);


%% ========================================================================
% 8. 保持三维真实比例
% ========================================================================

axis(ax,'equal');


daspect(ax, ...
    [1 1 1]);


%% ------------------------------------------------------------------------
% 旋转时保持三维比例
%% ------------------------------------------------------------------------

axis(ax,'vis3d');


%% ========================================================================
% 9. 关闭对象裁剪
% ========================================================================
%
% 这是解决：
%
%       放大后模型像被切开
%
% 的关键设置之一。
%

try

    ax.Clipping = ...
        'off';

catch

end


%% ========================================================================
% 10. 使用正交投影
% ========================================================================
%
% 原来使用：
%
%       perspective
%
% 放大以后更容易出现近裁剪面问题。
%
%
% 对 CFD / 网格 / 热流云图，
% 正交投影一般反而更合适。
%
% 优点：
%
% 1. 不产生透视变形
% 2. 前后尺寸不会因为距离相机不同而改变
% 3. 更适合工程几何检查
% 4. 放大时更加稳定
%

camproj( ...
    ax, ...
    'orthographic');


%% ========================================================================
% 11. 网格与边框
% ========================================================================

box(ax,'on');


showGrid = true;


if isfield(cfg,'plot') && ...
        isfield(cfg.plot,'showGrid')

    showGrid = ...
        cfg.plot.showGrid;

end


if showGrid

    grid(ax,'on');

else

    grid(ax,'off');

end


%% ========================================================================
% 12. 字体
% ========================================================================

fontName = ...
    'Times New Roman';


fontSize = ...
    12;


if isfield(cfg,'plot') && ...
        isfield(cfg.plot,'fontName')

    fontName = ...
        cfg.plot.fontName;

end


if isfield(cfg,'plot') && ...
        isfield(cfg.plot,'fontSize')

    fontSize = ...
        cfg.plot.fontSize;

end


ax.FontName = ...
    fontName;


ax.FontSize = ...
    fontSize;


ax.LineWidth = ...
    1.0;


%% ========================================================================
% 13. 坐标名称
% ========================================================================

xlabel( ...
    ax, ...
    'X / m', ...
    'FontName', fontName, ...
    'FontSize', fontSize);


ylabel( ...
    ax, ...
    'Y / m', ...
    'FontName', fontName, ...
    'FontSize', fontSize);


zlabel( ...
    ax, ...
    'Z / m', ...
    'FontName', fontName, ...
    'FontSize', fontSize);


%% ========================================================================
% 14. 标题
% ========================================================================

title( ...
    ax, ...
    'STL triangular mesh and surface normals', ...
    'FontName', fontName, ...
    'FontSize', fontSize+1, ...
    'FontWeight', 'normal');


%% ========================================================================
% 15. 初始视角
% ========================================================================

viewAzimuth = ...
    35;


viewElevation = ...
    25;


if isfield(cfg,'plot') && ...
        isfield(cfg.plot,'viewAzimuth')

    viewAzimuth = ...
        cfg.plot.viewAzimuth;

end


if isfield(cfg,'plot') && ...
        isfield(cfg.plot,'viewElevation')

    viewElevation = ...
        cfg.plot.viewElevation;

end


view( ...
    ax, ...
    viewAzimuth, ...
    viewElevation);


%% ========================================================================
% 16. 设置相机目标为模型几何中心
% ========================================================================
%
% 这样旋转时会围绕箭体中心转，
% 不会绕奇怪的位置旋转。
%

modelCenter = [
    0.5*(xmin+xmax), ...
    0.5*(ymin+ymax), ...
    0.5*(zmin+zmax)
];


camtarget( ...
    ax, ...
    modelCenter);


%% ========================================================================
% 17. 光照
% ========================================================================

try

    camlight( ...
        ax, ...
        'headlight');


    lighting( ...
        ax, ...
        'gouraud');

catch

end


%% ========================================================================
% 18. 开启鼠标 360° 三维旋转
% ========================================================================

rotateObject = ...
    rotate3d(fig);


rotateObject.Enable = ...
    'on';


%% ------------------------------------------------------------------------
% Orbit 模式
%% ------------------------------------------------------------------------

try

    rotateObject.RotateStyle = ...
        'orbit';

catch

end


%% ========================================================================
% 19. 鼠标滚轮改成“相机缩放”
% ========================================================================
%
% 不再让滚轮改变：
%
%       XLim
%       YLim
%       ZLim
%
% 而是使用：
%
%       camzoom
%
% 改变相机视角。
%
% 这样模型不会因为坐标范围缩小而被切掉。
%

fig.WindowScrollWheelFcn = ...
    @(source,event) ...
    scrollCameraZoom( ...
        ax, ...
        event);


%% ========================================================================
% 20. 显示工具栏
% ========================================================================

try

    ax.Toolbar.Visible = ...
        'on';

catch

end


%% ========================================================================
% 21. 绘图结束
% ========================================================================

hold(ax,'off');


drawnow;


%% ========================================================================
% 22. 提示
% ========================================================================

fprintf('\n');
fprintf('Interactive 3-D view enabled.\n');
fprintf('Left mouse drag : rotate model\n');
fprintf('Mouse wheel     : camera zoom\n');
fprintf('Projection      : orthographic\n');
fprintf('Axes clipping   : disabled\n');

end



%% ========================================================================
% LOCAL FUNCTION
%
% 鼠标滚轮相机缩放
%% ========================================================================
function scrollCameraZoom(ax,event)

%% ------------------------------------------------------------------------
% VerticalScrollCount：
%
% 滚轮一个方向为正，
% 另一个方向为负。
%
% 使用指数缩放可以保证：
%
% 每次滚轮动作的比例基本一致。
%% ------------------------------------------------------------------------

scrollCount = ...
    event.VerticalScrollCount;


%% ------------------------------------------------------------------------
% 每一格滚轮大约缩放 12%
%% ------------------------------------------------------------------------

zoomFactor = ...
    1.12 ^ ...
    (-scrollCount);


%% ------------------------------------------------------------------------
% 防止单次滚动过猛
%% ------------------------------------------------------------------------

zoomFactor = ...
    max( ...
    0.50, ...
    min( ...
    2.0, ...
    zoomFactor));


%% ------------------------------------------------------------------------
% 相机缩放
%% ------------------------------------------------------------------------

camzoom( ...
    ax, ...
    zoomFactor);

end