function mesh=attachThermistorAngularSpacing(mesh)
% 模块一：把 96 档全周参照绑定到当前热敏珠、48 档端面细网及已确认的侧吹边界。
root=fileparts(mfilename('fullpath'));archive='sidewindAngular96';
key=jsondecode(fileread(fullfile(root,'cases','thermistor_b',[archive '.json'])));
[folder,guard]=openThermistorArchive(archive); %#ok<NASGU>
files={'body.json','bodySHA256';'case.json','caseSHA256';'wall.csv','wallSHA256';'comparison.json','mappingAuditSHA256'};
for j=1:size(files,1)
    assert(strcmp(cm011FileSHA256(fullfile(folder,files{j,1})),key.(files{j,2})));
end
body=jsondecode(fileread(fullfile(folder,'body.json')));spec=jsondecode(fileread(fullfile(folder,'case.json')));
s=jsondecode(fileread(fullfile(folder,'summary.json')));audit=jsondecode(fileread(fullfile(folder,'comparison.json')));
t=mesh.thermistorTipSpacing;ref=t.summary;c=mesh.hybridCondition;
assert(isequal(mesh.V,body.V) && isequal(mesh.F,body.F) && strcmp(key.baseFrameSHA256,ref.fineFrame) && ...
    strcmp(key.baseMeshSHA256,ref.fineMeshSHA256) && strcmp(key.baseWallSHA256,ref.fineWallSHA256));
assert(spec.angularCells==96 && spec.reportAngularCells==48 && spec.outerRadiusOverD==20 && ...
    spec.frontCapFirstLayerRatio==.5 && isequal(c.velocityMps,spec.velocityMps(:)') && isequal(c.velocityMps,[0 -3 0]) && ...
    spec.airK==c.ambientTemperatureK && spec.airPa==c.ambientPressurePa && spec.wallK==c.wallTemperatureK);
for f={'bodySHA256','caseSHA256','meshSHA256','nodeMapSHA256','sourceFrameSHA256','wallSHA256','sourceReactionSHA256'}
    k=f{1};assert(strcmp(s.(k),key.(k)));
end
assert(audit.commonPositionsExact && audit.axisAndSeamChecked && s.faces==audit.reportFaces && ...
    s.nativeWallTriangles==audit.nativeWallTriangles && audit.maxOriginalRelativeAreaError<2e-12 && ...
    audit.maxNativeShapeIntegralFractionError<2e-11 && strcmp(s.wallMapping,'P1-overlap-integral') && ...
    strcmp(s.temperatureSampling,'v313-common-first-nodes') && strcmp(s.energy.inputFrameSHA256,s.sourceFrameSHA256));
assert(abs(s.energy.relativeDifference)<.005 && s.relativeChange20<.002 && all(structfun(@(v)v<-8,s.residualWindow)) && ...
    all(structfun(@(v)v<-8,s.plus20Window)));
% 模块二：逐原面核对面积、热流方向和七区积分，同一位置比较两网首层流体温度。
w=readtable(fullfile(folder,'wall.csv'));v=mesh.V;f=mesh.F;
area=vecnorm(cross(v(f(:,2),:)-v(f(:,1),:),v(f(:,3),:)-v(f(:,1),:),2),2,2)/2;
assert(isequal(w.faceID,mesh.hybridWall.faceID) && isequal(w.regionID,body.regionID) && all(abs(w.areaM2-area)<1e-18) && ...
    all(isfinite(w.heatFluxWm2)) && all(w.pressurePa>0 & abs(w.pressurePa-(spec.airPa+w.pressureGaugePa))<1e-9) && ...
    all(w.nearWallCellTemperatureK>=spec.airK & w.nearWallCellTemperatureK<=spec.wallK));
g=struct('baseFrame',ref.fineFrame,'fineFrame',s.sourceFrameSHA256,'seedFrame',audit.seedSHA256, ...
    'baseMesh',ref.fineMeshSHA256,'fineMesh',s.meshSHA256,'fineReaction',s.sourceReactionSHA256,'baseReaction',ref.fineReaction, ...
    'mappingSHA256',s.nodeMapSHA256,'mappingAuditSHA256',key.mappingAuditSHA256,'sourceWallSHA256',s.wallSHA256, ...
    'originalFaces',s.faces,'nativeTriangles',s.nativeWallTriangles,'overlaps',audit.overlaps, ...
    'outward48W',-area'*t.fineHeat,'outward96W',-area'*w.heatFluxWm2, ...
    'scope','20D 带线 B 型热敏珠，3 m/s 侧吹、给定壁温 299.15 K。48 与 96 档共享原壁、外边界及首层采样点。');
assert(abs(g.outward96W-s.totalOutwardW)<1e-12 && abs(g.outward48W-ref.outwardFineW)<1e-12);
[q,ids]=mink(w.heatFluxWm2,2);assert(ids(1)==s.peakFaceID);
g.basePeakFace=ref.finePeakFace;g.baseSecondFace=ref.fineSecondFace;g.finePeakFace=ids(1);g.fineSecondFace=ids(2);g.finePeakGapWm2=diff(q);
for j=1:numel(s.regions)
    mask=w.regionID==j;
    g.regions(j)=struct('name',s.regions(j).name,'faces',nnz(mask),'outward48W',-area(mask)'*t.fineHeat(mask), ...
        'outward96W',-area(mask)'*w.heatFluxWm2(mask));
    assert(nnz(mask)==s.regions(j).faces && abs(g.regions(j).outward96W-s.regions(j).outwardW)<1e-12 && ...
        abs(g.regions(j).outward48W-ref.regions(j).fineOutW)<1e-12);
end
mesh.thermistorAngularSpacing=struct('summary',g,'heat96',w.heatFluxWm2,'gauge96',w.pressureGaugePa, ...
    'common96',w.nearWallCellTemperatureK,'deltaHeat',w.heatFluxWm2-t.fineHeat, ...
    'deltaPressure',w.pressureGaugePa-t.fineGauge,'deltaCommon',w.nearWallCellTemperatureK-t.fineFirstK);
end
