function data=buildPhaseAwareNoseViewerData(mesh)
%BUILDPHASEAWARENOSEVIEWERDATA 同相态原面鼻部外缘接回主工作台，未知热量不补值。
e=mesh.phaseAwareNoseEdge;n=size(mesh.F,1);
assert(strcmp(e.meshSHA256,phaseAwareMeshIdentity(mesh)),'RAH:PhaseNoseViewer:Geometry','原面几何改变。');
digest=phaseAwarePayloadSHA(e.sourceText,e.pressurePa,e.temperatureK,e.speedMps,e.velocityMps, ...
    e.recoveryTemperatureK,e.validFace,e.reasonCode,e.arcLengthM,e.Mach,e.faceAreaM2);
assert(strcmp(digest,e.source.sha256),'RAH:PhaseNoseViewer:Source','外缘字段与源指纹不一致。');
reason=reshape(e.reasonNames(double(e.reasonCode)+1),[],1);empty=nan(n,1);valid=double(e.validFace);
data=struct('kind','aerothermal-model','schemaVersion',1,'vertices',double(mesh.V),'faces',double(mesh.F)-1, ...
    'faceArea',e.faceAreaM2,'totalArea',sum(e.faceAreaM2),'fields',struct([]),'defaultField','pressure', ...
    'region',{repmat({'球鼻工程外缘/未解其余区域'},n,1)},'missingReason',{reason}, ...
    'coordinateNote','SI · 原面几何与编号保持 · X主轴/鼻尖+X', ...
    'caseNote','仅新相态球鼻外缘候选；后体、热流及固体壁温未解，不能视为全面积气动热。', ...
    'resultCondition',struct('caption',sprintf('M %.3g · p∞ %.6g Pa · T∞ %.6g K · 鼻部工程候选', ...
        e.condition.Mach,e.condition.pressurePa,e.condition.temperatureK)), ...
    'researchIdentity',struct('productionQualified',false,'physicalQualification',false,'source',e.source, ...
        'newQualifiedAreaM2',0),'heatingGaps',struct([]));
add('pressure','鼻部壁压近似','Pa',e.pressurePa,valid,'同相态正激波驻点总压 + 修正牛顿压力',reason);
add('edgeTemperature','外缘温度','K',e.temperatureK,valid,'同一驻点熵与总焓的相态空气恢复',reason);
add('edgeSpeed','外缘速度大小','m/s',e.speedMps,valid,'同总焓速度；方向为实际面来流切向投影',reason);
add('edgeMach','外缘Mach数','1',e.Mach,valid,'同模型局部声速与外缘速度',reason);
add('recoveryTemperature','层流恢复温度估计','K',e.recoveryTemperatureK,valid,'h_aw=h_e+sqrt(Pr_e)U_e²/2；同Cp有界反解',reason);
add('arcLength','拟合球面驻点弧长','m',masked(e.arcLengthM),valid,'拟合球面短大圆弧；不是已解三维流线',reason);
missing=repmat({'尚未完成相容热入口及球鼻边界层'},n,1);
add('heatFlux','入壁对流热流','W/m²',empty,zeros(n,1),'未求解热剖面；不以恢复温度冒充热流',missing);
add('wallInput','给定壁温','K',mesh.phaseAwareWallTemperature,2*double(isfinite(mesh.phaseAwareWallTemperature)), ...
    '显式壁温边界，不是解出的固体温度',repmat({'壁温未知'},n,1));
add('wallSolved','独立固体壁温','K',empty,zeros(n,1),'未求解固体热响应',repmat({'没有独立固体热解'},n,1));
data.regions=struct('name','鼻部候选及其他未解区域','faces',n,'area',data.totalArea);
data.heatingGaps=struct('reason',missing{1},'faces',n,'area',data.totalArea,'areaFraction',1);
    function v=masked(v),v(~e.validFace)=NaN;end
    function add(key,label,unit,values,status,method,why)
        field=struct('key',key,'label',label,'unit',unit,'values',values,'status',status, ...
            'methodIndex',zeros(n,1),'methodNames',{{method}},'scope',e.scope,'missingReason',{why}, ...
            'computedStateLabel','未验证鼻部工程候选','stateNote','原面计算/给定/未知分开；无实验或区域接口资格', ...
            'availability','available');
        if isempty(data.fields),data.fields=field;else,data.fields(end+1)=field;end
    end
end
