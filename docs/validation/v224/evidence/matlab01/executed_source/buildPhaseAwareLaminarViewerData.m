function data=buildPhaseAwareLaminarViewerData(mesh)
%BUILDPHASEAWARELAMINARVIEWERDATA 将新相态工程层接回既有科研工作台。
% 模块用途：只显示本链有来源的量；不合并旧物性压力/壁温或伪造CFD剖面。
b=mesh.phaseAwareLaminar;n=size(mesh.F,1);
assert(strcmp(b.meshSHA256,phaseAwareMeshIdentity(mesh))&&numel(b.heatFluxWm2)==n, ...
    'RAH:PhaseViewer:Identity','结果与原面几何不匹配。');
methods={b.method};empty=nan(n,1);reason=reshape(b.reasonNames(double(b.reasonCode)+1),[],1);
data=struct('kind','aerothermal-model','schemaVersion',1,'vertices',double(mesh.V),'faces',double(mesh.F)-1, ...
    'faceArea',b.faceAreaM2,'totalArea',sum(b.faceAreaM2),'fields',struct([]), ...
    'region',{repmat({'相态工程层责任区域'},n,1)},'missingReason',{reason}, ...
    'coordinateNote','SI · 原始几何比例 · X主轴/鼻尖+X约定', ...
    'resultCondition',struct('caption',['具名外缘：' b.source.id '；' b.source.role '；附着层流工程候选']), ...
    'caseNote','新相态工程链；给定外缘控制与真实外流分开。厚度为参考性质动量厚度，固体壁温及CFD入口剖面未解。', ...
    'defaultField','heatFlux','researchIdentity',struct('productionQualified',false, ...
    'physicalQualification',false,'source',b.source,'newQualifiedAreaM2',0));
valid=double(b.validFace);given=2*double(isfinite(b.wallTemperatureK));
add('heatFlux','入壁对流热流','W/m²',b.heatFluxWm2,valid,methods{1},b.scope,reason);
add('skinFriction','层流摩擦系数','1',masked(b.skinFrictionCoefficient),valid,methods{1},b.scope,reason);
add('momentumThickness','参考性质动量厚度','m',masked(b.referenceMomentumThicknessM),valid,methods{1}, ...
    'Thwaites参考性质积分量；不是密度加权的真实压缩性动量厚度',reason);
add('recoveryTemperature','恢复温度','K',masked(b.recoveryTemperatureK),valid, ...
    '同一相态标准空气：h_aw=h_e+sqrt(Pr_edge) U_e²/2',b.scope,reason);
add('referenceTemperature','参考温度','K',masked(b.referenceTemperatureK),valid, ...
    'Riley H.6/H.7同模型参考焓有界反解',b.scope,reason);
add('wallInput','给定壁温','K',b.wallTemperatureK,given,'显式壁温输入','给定边界，不是求解壁温',repmat({'壁温未知'},n,1));
add('wallSolved','独立固体壁温','K',empty,zeros(n,1),'未求解固体热响应','当前只求给定Tw下的对流热流',repmat({'未执行固体导热或热平衡'},n,1));
data.fields(end).availability='notProvidedInSnapshot';
add('energyThickness','压缩性能量厚度','m',empty,zeros(n,1),'未提供：需要相容速度/密度/焓剖面', ...
    b.profileMissingReason,repmat({b.profileMissingReason},n,1));
data.heatingGaps=struct([]);
for j=1:numel(b.reasonNames)-1
    mask=b.reasonCode==j;if ~any(mask),continue;end
    row=struct('reason',b.reasonNames{j+1},'faces',nnz(mask),'area',sum(b.faceAreaM2(mask)), ...
        'areaFraction',sum(b.faceAreaM2(mask))/data.totalArea);
    data.heatingGaps=[data.heatingGaps row]; %#ok<AGROW>
end
data.regions=struct('name','相态工程层责任区域','faces',n,'area',data.totalArea);
    function v=masked(v),v(~b.validFace)=NaN;end
    function add(key,label,unit,values,status,method,scope,missing)
        f=struct('key',key,'label',label,'unit',unit,'values',values,'status',status, ...
            'methodIndex',zeros(n,1),'methodNames',{{method}},'scope',scope, ...
            'missingReason',{missing},'computedStateLabel','未验证工程候选', ...
            'stateNote','计算/给定/未知分开；本接口和制造控制不授真实区域物理资格。', ...
            'availability','available');
        data.fields=[data.fields f];
    end
end
