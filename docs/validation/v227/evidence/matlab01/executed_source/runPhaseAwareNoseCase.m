function [current,freestream,report]=runPhaseAwareNoseCase(mesh,cfg,progressFcn)
%RUNPHASEAWARENOSECASE 显式局部鼻部外缘工况入口，不冒充完整热计算。
% 模块用途：重算当前大气输入，使用新物性速度，并清除结果副本中的旧物理场。
if nargin<3,progressFcn=[];end
started=tic;old=calcFreestream(cfg.flight);
e=solvePhaseAwareNoseEdge(mesh,old,cfg);air=phaseAwareAirState('PT',old.pressure,old.temperature,'linearTable');
freestream=struct('Mach',old.Mach,'alpha',old.alpha,'beta',old.beta,'altitude',old.altitude, ...
    'pressure',old.pressure,'temperature',old.temperature,'unitFlowDirection',old.unitFlowDirection, ...
    'speed',e.condition.speedMps,'density',air.densityKgm3,'speedOfSound',air.soundSpeedMps, ...
    'model',air.model,'transportModel',air.transportModel,'energyReference',air.energyReference);
current=mesh;
stale={'pressure','externalFlow','boundaryLayerEdge','axisymmetricMarch','surfaceStreamlines','stagnation', ...
    'stagnationShock','bowShockPreview','boundaryLayer','heating','heatingCoverage','stagnationHeating', ...
    'aerodynamicLoads','phaseAwareLaminar','phaseAwareEdge','wallThermal','flightHeatingHistory', ...
    'aerothermalExposure','aerothermalRegion','continuumRegime'};
for name=stale,if isfield(current,name{1}),current=rmfield(current,name{1});end,end
current.phaseAwareNoseEdge=e;current.phaseAwareWallTemperature=surfaceWallTemperature(size(mesh.F,1),cfg);
current.aerothermalResultMode='phaseAwareNoseEdge';
report=struct('status','completed-region-edge-only','condition',cfg.flight,'faceCount',size(mesh.F,1), ...
    'totalArea',e.summary.totalAreaM2,'pressureComputedAreaFraction',e.summary.candidateAreaFraction, ...
    'pressurePrescribedAreaFraction',0,'pressureMissingAreaFraction',1-e.summary.candidateAreaFraction, ...
    'heatComputedAreaFraction',0,'loadsAvailable',false,'physicalQualification',false, ...
    'scope','仅相态球鼻外缘工程候选；全面积热计算未完成','elapsedSeconds',toc(started));
if ~isempty(progressFcn)
    progressFcn(struct('phase','externalFlow','status','completed','fraction',1, ...
        'message','鼻部外缘区域计算完成；热流及其余区域未完成','elapsedSeconds',toc(started), ...
        'errorIdentifier','','errorMessage',''));
end
end
